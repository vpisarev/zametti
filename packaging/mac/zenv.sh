# Общее окружение переносимой сборки zametti под macOS. Подключать так:
#
#   source packaging/mac/zenv.sh
#
# Смысл тот же, что у packaging/linux/zenv.sh: Qt и сама программа собираются
# ОДНИМИ И ТЕМИ ЖЕ ключами. Разошедшиеся флаги у Qt и у программы — классический
# способ получить бинарь, который собрался, но не запускается.
#
# ЧЕМ МАК ОТЛИЧАЕТСЯ ОТ ЛИНУКСА, И ПОЧЕМУ ЗДЕСЬ НЕТ SYSROOT. На линуксе
# переносимость упирается в glibc, и её приходится брать из sysroot старой
# Ubuntu. На маке роль «пола» играет ДРУГОЕ: SDK и версия системы, названная
# ключом -mmacosx-version-min. Совместимость назад macOS обеспечивает сама, а
# системные рамки (AppKit, Metal, ImageIO) есть на любой машине по построению —
# их вкладывать внутрь не нужно и нельзя.
#
# Пути можно задать снаружи: ZPREFIX=/иное source packaging/mac/zenv.sh

export ZPREFIX="${ZPREFIX:-$HOME/ai/work/zdeps}" # куда кладём собранный Qt
export ZBUILD="${ZBUILD:-$HOME/ai/work/zbuild}"  # где собираем (сносится безболезненно)

# ПОЛ СИСТЕМЫ. Всё, что старше, программу не запустит; всё, что новее, — да.
# 12.0 (Monterey) выбран как самая старая macOS, которую Qt 6.10 объявляет
# поддерживаемой: обещать больше, чем обещает Qt, нечестно.
export ZMACOS_MIN="${ZMACOS_MIN:-12.0}"

# АРХИТЕКТУРЫ. Одна — быстро и для своей машины; две (arm64;x86_64) — жирный
# универсальный бинарь для чужих. Сборка Qt под две занимает вдвое дольше,
# поэтому по умолчанию своя, а универсальную просят явно:
#   ZARCHS='arm64;x86_64' source packaging/mac/zenv.sh
export ZARCHS="${ZARCHS:-$(uname -m)}"

echo "zenv(mac): prefix=$ZPREFIX build=$ZBUILD min=$ZMACOS_MIN archs=$ZARCHS"
