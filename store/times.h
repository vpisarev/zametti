// Времена в шапке заметки: запись, чтение и сравнение.
//
// С этапа 15 `created` и `modified` пишутся в ISO-8601 С ОФСЕТОМ
// (`2026-08-14T21:40:00+02:00`): в одной строке и абсолютный момент, и
// локальный контекст — когда для человека это было. Прежний вид
// (`2026-08-14T19:40:00Z`) читается по-прежнему, миграция ленивая: любое
// сохранение переписывает обе метки в новом виде, специального прохода по
// хранилищу нет.
//
// Три функции, и каждая закрывает свою ловушку.
//
//   1. ЗАПИСЬ. `QDateTime::currentDateTime().toString(Qt::ISODate)` офсет НЕ
//      печатает вовсе — у местного времени spec = LocalTime, и Qt выводит
//      «2026-08-13T13:35:12» без всякой зоны (замер пробником, не
//      документация). Офсет появляется только у OffsetFromUTC и TimeZone,
//      поэтому перед печатью время приводится к своему же офсету.
//   2. ЧТЕНИЕ. Метка без зоны — законная (чужой файл, чужая программа) и
//      читается в зоне ЧИТАЮЩЕЙ машины: другого разумного допущения нет, и оно
//      записано в справочнике формата.
//   3. СРАВНЕНИЕ. Строки с офсетами сравнивать побайтово нельзя:
//      «2026-08-14T21:40:00+02:00» лексикографически больше
//      «2026-08-14T19:40:00Z», а это ОДИН И ТОТ ЖЕ момент. Сортировки и
//      сравнения ходят через comparableTime — приведение к UTC.

#ifndef ZAMETTI_STORE_TIMES_H
#define ZAMETTI_STORE_TIMES_H

#include <QDateTime>
#include <QString>

#include <string>

namespace zametti::store {

// Как время ложится в шапку: ISO-8601 с офсетом зоны самого времени. Доли
// секунды отбрасываются — в шапке они шум, а разные их представления сделали
// бы одинаковые моменты разными строками.
QString isoWithOffset(const QDateTime& when);

// Время «сейчас» в местной зоне, готовое для шапки.
QString isoNow();

// Разбор обоих видов. Недействительная строка — недействительное время,
// молчком: это не беда программы, а чужой файл.
QDateTime parseNoteTime(const QString& text);
QDateTime parseNoteTime(const std::string& text);

// Сравнимая форма: UTC, всегда одной длины, всегда с «Z». Пусто, если строку
// не разобрать, — такие метки в сортировке идут последними и не притворяются
// началом времён.
QString comparableTime(const QString& text);
QString comparableTime(const std::string& text);

}  // namespace zametti::store

#endif  // ZAMETTI_STORE_TIMES_H
