// История правок: append-only журнал на каждую заметку.
//
// Живёт в хранилище (`history/<id>.log`), а не в кэше: она не восстановима из
// файлов заметок, переживает удаление заметки и однажды поедет в
// синхронизацию. Отсюда три жёстких правила, вынесенные в тесты:
//
//   A. журнал только дописывается; между прореживаниями файл строго растёт;
//   B. восстановление из истории — НОВАЯ запись; ни одна операция журнал не
//      укорачивает и не перематывает;
//   C. последняя запись не прореживается никогда — для удалённой заметки это
//      её вечный финальный слепок.
//
// Слепок — состояние заметки целиком, а не разность строк: восстановление
// обязано быть простым. Но на диск он ложится относительно предшественника,
// цепочками ограниченной длины (см. kGeneration) — так разность даёт экономию,
// не давая цепочке расти без края. Журнал целиком не пережимается никогда,
// иначе умерли бы дозапись, частичное чтение и прореживание.
//
// В историю идёт только текст заметки. Картинки не версионируются вовсе: в
// тексте от картинки лежит ссылка вида `![имя](01n….webp#w=600)`, и самая
// «фотографическая» заметка хранилища — это 337 байт текста на шесть
// фотографий. Тяжёлые журналы бывают у заметок, тяжёлых ТЕКСТОМ.
//
// Формат — CBOR-последовательность (RFC 8742) через штатные Qt-читатель и
// писатель: стандартный формат вместо самопального, без кодогенерации.
// Первая запись файла — шапка с магией и версией формата. Ломающие изменения
// поднимают версию; неломающие добавляют ключи в карты, а читатель незнакомые
// ключи пропускает.
//
// **fsync не зовётся никогда** — решение владельца: маленькому приложению
// незачем гонять диск, а дробить дозапись по 700 байт на отдельные коммиты
// файловой системы — прямая порча носителя. Байты уедут штатным writeback-ом
// через несколько секунд сами. Замер, на котором это стоит: fsync — 4.5 мс из
// 6.4 мс всей записи большой заметки (239 КБ) и 5.7 мс из 5.7 мс — малой.
//
// Чем платим: при отключении питания последняя запись может пропасть или
// оборваться. Оба случая штатные — оборванный хвост отрезается при открытии, а
// пропавшая запись обнаружится сверкой отпечатка при следующем открытии
// заметки и допишется как External. Заметку это не портит: её файл пишется
// через QSaveFile, а тот внутри себя fdatasync всё-таки делает (проверено
// strace), так что сама заметка ложится на диск раньше своей записи в истории.

#ifndef ZAMETTI_JOURNAL_H
#define ZAMETTI_JOURNAL_H

#include "hash.h"

#include <QByteArray>
#include <QString>
#include <QStringList>
#include <QVector>

namespace zametti::journal {

// Версия формата файла. Поднимается только при ломающем изменении: читатель
// отказывается открывать журнал версии, которой не знает, — молча пропустить
// незнакомую историю хуже, чем сказать об этом вслух.
inline constexpr int kFormatVersion = 1;

// Магия в шапке: чтобы «не тот файл» отличался от «битый файл».
inline constexpr char kMagic[] = "zametti-journal";

enum class Kind {
    Save = 1,       // обычное сохранение заметки
    External = 2,   // файл изменили снаружи, мы это увидели
    Restore = 3,    // человек вернул старый слепок
    Tombstone = 4,  // заметку удалили; слепка нет — им остаётся предыдущая запись
};

// Кодек слепка указан в самой записи: читатель обязан уметь встретить в старом
// журнале другой — это страховка на будущее, а не гибкость ради гибкости.
enum class Codec {
    None = 0,
    Zstd = 1,       // слепок сжат сам по себе — начало поколения
    ZstdDelta = 2,  // слепок сжат с ПРЕДЫДУЩИМ слепком в качестве префикса
};

// Поколение — цепочка записей, начатая полным слепком. Внутри поколения каждая
// запись сжимается относительно предыдущей: это ровно то, что делает
// `zstd --patch-from`, механизмом ZSTD_CCtx_refPrefix. Отдельная библиотека
// разностей не нужна.
//
// Длина поколения 32 выбрана замером на 200 правках заметки в 239 КБ:
//
//   уклад                     журнал   запись  восстановить  прореживание
//   каждый слепок сам по себе  15.84 МБ  1737 мкс   313 мкс        —
//   сплошная цепочка            0.09 МБ   579 мкс  3557 мкс      13 мс
//   поколениями по 8            1.99 МБ   586 мкс   445 мкс      17 мс
//   поколениями по 32           0.57 МБ   589 мкс   479 мкс      13 мс
//
// То есть поколения по 32 выигрывают у прежнего уклада по всем осям сразу: в
// 28 раз меньше на диске, запись втрое быстрее (сжимать почти нечего),
// восстановление сопоставимо. Сплошная цепочка меньше ещё вшестеро, но
// восстановление в ней растёт без границы, а порча одного звена уносит всё,
// что после. Длина поколения — та самая граница: и цены чтения, и урона.
inline constexpr int kGeneration = 32;

// Рамка записи — всё, кроме самих байтов слепка. Таймлайн строится по ней, и
// ради него слепки не распаковываются: у богатой заметки их могут быть сотни.
struct Entry {
    Kind kind = Kind::Save;
    qint64 time = 0;         // UTC, миллисекунды от эпохи
    Digest digest;           // BLAKE3 РАСПАКОВАННОГО слепка
    Codec codec = Codec::Zstd;
    qint64 plainSize = 0;    // размер слепка до сжатия — для таймлайна и буфера
    qint64 packedSize = 0;   // сколько занимает слепок в файле
    qint64 offset = 0;       // где запись начинается в файле
    qint64 source = 0;       // Restore: время записи-источника; иначе 0

    bool hasSnapshot() const { return kind != Kind::Tombstone; }
    // Начало поколения: слепок читается сам по себе, без предшественников.
    // У записи без слепка (надгробие) поколения нет — она стоит в стороне от
    // цепочки и не рвёт её: кодека в ней не записано вовсе, и без этой оговорки
    // она выглядела бы началом нового поколения.
    bool full() const { return hasSnapshot() && codec != Codec::ZstdDelta; }
};

// Читаемая часть журнала. Оборванный хвост (падение во время записи) — не
// беда, а норма: он отрезается, и об этом говорится вслух. Журнал никогда не
// считается битым из-за последней записи.
struct Journal {
    QVector<Entry> entries;
    bool tailTrimmed = false;  // хвост был неполон
    qint64 goodBytes = 0;      // длина целой части файла
};

// Итог обхода всего `history/`.
struct ThinReport {
    int journals = 0;
    qint64 recordsBefore = 0;
    qint64 recordsAfter = 0;
    qint64 bytesBefore = 0;
    qint64 bytesAfter = 0;
    QStringList problems;   // журналы, которые не открылись или не переписались
    QStringList trimmed;    // журналы с оборванным хвостом
};

// Кого оставит прореживание — номера записей по возрастанию. Чистая функция от
// времён, без файлов: наружу вынесена ради тестов шкалы и ради `--dry-run`.
//
// Шкала логарифмическая, от «сейчас»: последний час — всё, сутки — не чаще
// раза в минуту, неделя — раза в час, месяц — раза в сутки, дальше — раза в
// месяц, навсегда. Последняя запись остаётся всегда.
QVector<int> survivors(const QVector<Entry>& entries, qint64 now);

// Файловый замок хранилища: одно хранилище — одна программа. Берётся при
// запуске и держится всё время работы. Лежит в служебном .zametti/, а не в
// history/: verify считает посторонние файлы в хранилище бедой.
QString storeLockPath(const QString& root);

// История хранилища — единственный способ трогать журналы.
//
// **Единая точка синхронизации.** Каждый открытый метод устроен одинаково:
// берёт общий замок и зовёт свой закрытый ...Locked. Работы с файлами в
// открытых методах нет вовсе, поэтому «все ли операции под замком» видно
// глазом, а не проверяется памятью. Под замком и запись, и ЧТЕНИЕ: читатель,
// поймавший середину переписывания, — та же беда, только тише.
//
// Замок берётся RAII-обёрткой QMutexLocker и снимается её деструктором, то
// есть при любом выходе — обычном, досрочном или через исключение. Ручных
// lock/unlock в модуле нет ни одного, и заводить их нельзя: путь возврата,
// забывший отпустить замок, вешает всю историю навсегда.
//
// Замок один на все журналы, а не по замку на файл: журналов сотни, операции
// короткие, спорят они за диск, а не друг с другом, — а рассуждать об одном
// замке несравнимо проще. Цена замера: QMutex — 14.2 нс на взятие и
// отпускание, то есть на фоне записи в 30 мкс его попросту нет. Замок общий и
// для всех экземпляров класса: история у хранилища одна, сколько бы объектов
// её ни держало.
//
// Замок именно в памяти, а не файловый: QLockFile стоит 4.4 мс (замер) — он
// создаёт файл на диске, и на каждое сохранение это было бы в сто раз дороже
// самой записи. От другого ПРОЦЕССА он и не должен беречь: хранилище открыто
// ровно одной программой, и стережёт это storeLockPath.
class History {
public:
    explicit History(QString root);

    // Путь журнала заметки.
    QString pathFor(const QString& noteId) const;

    // Дописать запись в конец. Шапка пишется сама, если файла ещё нет.
    // snapshot — распакованные байты заметки (для Tombstone игнорируется).
    // false — и объяснение в error; журнал при отказе остаётся как был.
    //
    // Полным слепком или звеном цепочки запись станет — решает сама история,
    // по тому, сколько записей прошло от начала поколения. Предшественника она
    // восстанавливает сама: звать с расжатой базой на руках не нужно, а лишний
    // параметр, который легко передать неверно, дороже сэкономленных долей
    // миллисекунды.
    bool append(const QString& noteId, Kind kind, qint64 time, const QByteArray& snapshot,
                qint64 source, QString* error);

    // Прочитать рамки всех записей. Слепки не распаковываются.
    // false — журнал не открыть или он не наш (магия, версия); отсутствующий и
    // пустой файл — это пустая история, а не беда.
    bool read(const QString& noteId, Journal* out, QString* error) const;

    // Достать и собрать слепок записи с номером index: если запись — звено
    // цепочки, читается всё её поколение, от полного слепка до неё. Отпечаток
    // сверяется на каждом звене: история, которая молча отдаёт не те байты,
    // хуже истории, которой нет.
    bool snapshotAt(const QString& noteId, int index, QByteArray* out, QString* error) const;

    // Отрезать оборванный хвост, если он есть. Отдельной командой, а не внутри
    // read: чтение обязано работать и на журнале, открытом только для чтения.
    bool trimTail(const QString& noteId, QString* error);

    // Прореживание одного журнала по шкале survivors.
    //
    // Идемпотентно: повторный прогон при том же now ничего не меняет.
    // Переписывает файл целиком и атомарно; если выкидывать нечего, файл не
    // трогается вовсе (иначе прореживание при старте переписывало бы всё
    // хранилище каждый раз). Выжившие перекодируются заново — звено цепочки
    // осмысленно только рядом со своим предшественником, а он мог не выжить.
    bool thin(const QString& noteId, qint64 now, QString* error);

    // Прореживание всех журналов хранилища. Годится для отдельного потока:
    // замок берётся на каждый журнал в отдельности, а не на весь обход, —
    // сохранение заметки не ждёт, пока переберут сотни чужих журналов.
    //
    // dryRun — ничего не писать, только посчитать. Замер по корпусу владельца
    // (269 журналов): полный проход 2.9 с, повторный — 0.03 с, потому что
    // журнал, в котором нечего выкидывать, не переписывается вовсе.
    ThinReport thinAll(qint64 now, bool dryRun = false);

private:
    // Всё, что трогает файлы, живёт здесь и зовётся только из-под замка.
    bool appendLocked(const QString& path, Kind kind, qint64 time, const QByteArray& snapshot,
                      qint64 source, QString* error);
    bool readLocked(const QString& path, Journal* out, QString* error) const;
    bool snapshotAtLocked(const QString& path, int index, QByteArray* out, QString* error) const;
    bool trimTailLocked(const QString& path, QString* error);
    bool thinLocked(const QString& path, qint64 now, QString* error);

    QString root_;
};

}  // namespace zametti::journal

#endif  // ZAMETTI_JOURNAL_H
