// Журнал правок: append-only история одной заметки.
//
// Живёт в хранилище (`history/<id>.log`), а не в кэше: он не восстановим из
// файлов заметок, переживает удаление заметки и однажды поедет в синхронизацию.
// Отсюда три жёстких правила, вынесенные в ассерты и тесты:
//
//   A. журнал только дописывается; между прореживаниями файл строго растёт;
//   B. восстановление из истории — НОВАЯ запись; ни одна операция журнал не
//      укорачивает и не перематывает;
//   C. последняя запись не прореживается никогда — для удалённой заметки это
//      её вечный финальный слепок.
//
// Слепок полный, а не разность (решение владельца): разности потребовали бы
// целостной цепочки, а битая середина цепочки убивает всё, что после неё.
// Каждый слепок сжимается отдельно — журнал целиком не пережимается никогда,
// иначе умерли бы дозапись, частичное чтение и прореживание.
//
// Формат — CBOR-последовательность (RFC 8742) через штатные Qt-читатель и
// писатель: стандартный формат вместо самопального, без кодогенерации.
// Первая запись файла — шапка с магией и версией формата. Ломающие изменения
// поднимают версию; неломающие добавляют ключи в карты, а читатель незнакомые
// ключи пропускает.
//
// **fsync не зовётся никогда** — решение владельца: маленькому приложению
// незачем гонять диск, а дробить дозапись по 700 байт на отдельные коммиты
// файловой системы — прямая порча носителя. Байты уедут штатным writeback-ом
// через несколько секунд сами. Замер, на котором это стоит: fsync — 4.5 мс из
// 6.4 мс всей записи большой заметки (239 КБ) и 5.7 мс из 5.7 мс — малой.
// Без него запись стоит 1.9 мс и 0.04 мс соответственно.
//
// Чем платим: при отключении питания последняя запись журнала может пропасть
// или оборваться. Оба случая штатные — оборванный хвост отрезается при
// открытии, а пропавшая запись обнаружится сверкой отпечатка при следующем
// открытии заметки и допишется как External. Заметку это не портит: её файл
// пишется через QSaveFile, а тот внутри себя fdatasync всё-таки делает
// (проверено strace), так что сама заметка на диске оказывается раньше своей
// записи в журнале — порядок, который нам и нужен.

#ifndef ZAMETTI_JOURNAL_H
#define ZAMETTI_JOURNAL_H

#include "hash.h"

#include <QByteArray>
#include <QString>
#include <QVector>

namespace zametti::journal {

// Версия формата файла. Поднимается только при ломающем изменении: читатель
// отказывается открывать журнал версии, которой не знает, — молча пропустить
// незнакомую историю хуже, чем сказать об этом вслух.
inline constexpr int kFormatVersion = 1;

// Магия в шапке: чтобы «не тот файл» отличался от «битый файл».
inline constexpr char kMagic[] = "zametti-journal";

enum class Kind {
    Save = 1,       // обычное сохранение заметки
    External = 2,   // файл изменили снаружи, мы это увидели
    Restore = 3,    // человек вернул старый слепок
    Tombstone = 4,  // заметку удалили; слепка нет — им остаётся предыдущая запись
};

// Кодек слепка указан в самой записи: v1 пишет только zstd, но читатель
// обязан уметь встретить в старом журнале другой — это страховка на будущее,
// а не гибкость ради гибкости.
enum class Codec {
    None = 0,
    Zstd = 1,
};

// Рамка записи — всё, кроме самих байтов слепка. Таймлайн строится по ней, и
// ради него слепки не распаковываются: у богатой заметки их могут быть сотни.
struct Entry {
    Kind kind = Kind::Save;
    qint64 time = 0;         // UTC, миллисекунды от эпохи
    Digest digest;           // BLAKE3 РАСПАКОВАННОГО слепка
    Codec codec = Codec::Zstd;
    qint64 plainSize = 0;    // размер слепка до сжатия — для таймлайна и буфера
    qint64 packedSize = 0;   // сколько занимает в файле
    qint64 source = 0;       // Restore: время записи-источника; иначе 0

    bool hasSnapshot() const { return kind != Kind::Tombstone; }
};

// Читаемая часть журнала. Оборванный хвост (падение во время записи) — не
// беда, а норма: он отрезается, и об этом говорится вслух. Журнал никогда не
// считается битым из-за последней записи.
struct Journal {
    QVector<Entry> entries;
    bool tailTrimmed = false;  // хвост был неполон
    qint64 goodBytes = 0;      // длина целой части файла
};

// Путь журнала заметки в хранилище.
QString journalPath(const QString& root, const QString& noteId);

// Дописать запись в конец. Шапка пишется сама, если файла ещё нет.
// snapshot — распакованные байты заметки (для Tombstone игнорируется).
// false — и объяснение в error; журнал при отказе остаётся как был.
bool append(const QString& path, Kind kind, qint64 time, const QByteArray& snapshot,
            qint64 source, QString* error);

// Прочитать рамки всех записей. Слепки не распаковываются.
// false — журнал не открыть или он не наш (магия, версия); пустой файл — это
// пустой журнал, а не беда.
bool read(const QString& path, Journal* out, QString* error);

// Достать и распаковать слепок записи с номером index. Хеш сверяется всегда:
// история, которая молча отдаёт не те байты, хуже истории, которой нет.
bool snapshotAt(const QString& path, int index, QByteArray* out, QString* error);

// Отрезать оборванный хвост, если он есть. Отдельной командой, а не внутри
// read: чтение обязано работать и на журнале, открытом только для чтения.
bool trimTail(const QString& path, QString* error);

// Прореживание по логарифмической шкале от now (UTC, мс): последний час — всё,
// сутки — не чаще раза в минуту, неделя — раза в час, месяц — раза в сутки,
// дальше — раза в месяц, навсегда. Последняя запись остаётся всегда.
//
// Идемпотентно: повторный прогон при том же now ничего не меняет.
// Переписывает файл целиком и атомарно; если выкидывать нечего, файл не
// трогается вовсе (иначе прореживание при старте переписывало бы всё
// хранилище каждый раз).
bool thin(const QString& path, qint64 now, QString* error);

// Кого оставит прореживание — номера записей по возрастанию. Вынесено наружу
// ради тестов и ради `zametti-store thin --dry-run`.
QVector<int> survivors(const QVector<Entry>& entries, qint64 now);

}  // namespace zametti::journal

#endif  // ZAMETTI_JOURNAL_H
