namespace zametti::store {

// Роль папки-бюро в шапке (`role: lost`) и ключ, где лежит прежний родитель.
inline constexpr char kLostRole[] = "lost";
inline constexpr char kLostParentKey[] = "lost-parent";

// Прописать сирот в бюро. Возвращает, сколько заметок прописано (0 — сирот не
// было и ничего не записано); -1 — беда, описана в error.
//
// Зовётся при открытии хранилища и по F5/Ctrl+R — то есть ровно там, где
// хранилище и так перечитывается целиком.
int fileOrphans(const QString& root, QString* error);

}  // namespace zametti::store

#endif  // ZAMETTI_STORE_LOST_FOUND_H
