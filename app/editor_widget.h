// Виджет редактора: перевод ввода в глаголы заметки и связь её с историей.
//
// Собственной логики правки здесь нет и быть не должно — она живёт в ZDocument.
// Здесь только: что нажали, какой глагол звать, когда записать шаг истории и
// когда сохранить. Заголовка разметки блоков (editor_ops.h) здесь нет вовсе:
// он внутренность ядра.
//
// Ключевое разделение — содержимое против облика. Правка содержимого заводит
// шаг истории; смена облика (масштаб, шрифт, цвета, отступы) пересобирает
// документ из текущего содержимого и историю не трогает вовсе.

