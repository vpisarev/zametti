    // --- кэш заметок сессии ---
    //
    // Уходя из ЧИСТОЙ заметки, откладываем её целиком: живой документ вместе с
    // историей правок, кареткой и прокруткой. Вернувшись, человек застаёт её
    // ровно такой, какой оставил, и Ctrl+Z отменяет правки прошлого захода.
    //
    // Кладём только чистое и только после записи. Вместе с записью
    // запоминается отпечаток файла; при возврате он сверяется с отпечатком
    // того, что лежит на диске сейчас. Совпал — файл никто не трогал, отдаём
    // отложенное как есть. Не совпал — правил кто-то снаружи, отложенное
    // выбрасываем и собираем с диска заново. Терять при этом нечего: в кэш
    // попало только то, что уже записано в файл.
    // ВСЁ, что относится к одной заметке, — здесь и только здесь.
    //
    // Правило простое: поле, у которого есть ответ на вопрос «какой заметки?»,
    // живёт в этом объекте, а не в редакторе. Переключение заметки — это смена
    // объекта целиком, а не переприсваивание десятка полей. Забыть при этом
    // что-то сбросить нельзя: несброшенного просто не остаётся.
    //
    // Правило родилось на живой ошибке: признак «мы в режиме истории» лежал в
    // редакторе и пережил переход к другой заметке — редактор показывал слепок
    // ПРЕЖНЕЙ заметки, имея путь новой. Пока состояние размазано по объекту
    // приложения, такие рассинхронизации будут появляться снова и снова
    // (наблюдение владельца).
    //
    // Один и тот же тип служит трём вещам: открытой заметке, отложенной в кэш и
    // слепку в режиме истории. Это не экономия, а следствие: все три — заметка
    // со своим состоянием, и разница между ними только в том, кто её держит.
    // Открытая заметка — ZNote (zametti-core/note/znote.h): документ, журнал,
    // шапка, отпечаток, счёт слов, место каретки — всё, что переживает уход и
    // возврат. Здесь её объекта больше нет: он один и живёт через shared_ptr.

    // СОСТОЯНИЕ ТЕКУЩЕЙ ЗАМЕТКИ — всё, что можно спокойно ВЫБРОСИТЬ, уходя на
    // другую (правило владельца).
    //
    // Граница проходит по одному вопросу: переживёт ли это уход из заметки и
    // возврат к ней? Место каретки, отпечаток файла, хвост журнала и собранные
    // блоки — переживают, они в ZNote и едут в кэш вместе с заметкой.
    // Всё здешнее — не переживает и не должно: курсоры уборки указывают в
    // конкретный документ, найденное ищется заново, серия набора кончается
    // уходом.
    //
    // Ради этого разделения оно и заведено: четыре готовых документа разности
    // весят больше самой заметки, а лежали в её объекте — и уезжали бы с ней в
    // кэш отложенных.
    struct CurrentNoteState {
        // --- серия набора: она задаёт ГРАНИЦУ ШАГА ОТМЕНЫ -------------------
        //
        // Qt склеивает подряд идущие вставки в один шаг и рвать эту склейку не
        // умеет: набранный абзац отменялся бы целиком, а владелец на это уже
        // жаловался («буфера на 200 шагов как будто нет»). Управляем границей
        // сами — скобкой правки: серия продолжается, значит
        // joinPreviousEditBlock, кончилась — beginEditBlock. Замер: три слова,
        // каждое в своей скобке, — ровно три нажатия Ctrl+Z.
        //
        // Правил границы четыре, и все взяты у того, как это ощущается в Apple
        // Notes: набран разделитель (он остаётся в текущем шаге, следующая буква
        // начинает новый), каретка ушла в другое место, набрано undoRunChars
        // знаков подряд, наступила тишина.
        int runChars = 0;
        int runCursor = -1;        // где кончилась прошлая набранная буква
        bool runBroken = true;     // следующая буква обязана начать новый шаг
        bool undoRun = false;      // идёт серия отмены — см. NoteEditor::undo

        // Курсоры внутрь документа: живут ровно столько, сколько он.
        QTextCursor lastLine;
        QTextCursor dirty;        // область, накопленная с прошлой уборки

        // Внешняя правка, ждущая ответа человека.
        bool externalPending = false;
        std::string externalText;
        bool externalEmptyRetried = false;
        QString lastComplaint;    // о чём уже жаловались: не повторяться

        int lastCaretPosition = 0;
    };

