// Плашка блока кода в пикселях при данном масштабе.
//
// ОДНА НА ВСЕХ, и это главное в ней. Верхнее поле блока резервирует сборщик
// документа, а рисует в этом резерве отрисовка; посчитай они высоту полоски
// каждый по-своему — полоска налезала бы на предыдущий абзац или висела бы над
// плашкой в воздухе. Из этих же величин складываются левые отступы: плашка
// отодвинута от абзаца на codeIndent, код внутри неё — ещё на codePadLeft, и
// отрисовка находит левый край плашки, вычитая второе из поля блока.
struct CodePlate {
    qreal strip = 0.0;      // высота полоски сверху (в ней имя языка и кнопки)
    qreal padBottom = 0.0;  // поле снизу — меньше верхнего, только под скругление
    qreal padLeft = 0.0;    // отступ кода от левого края плашки
    qreal indent = 0.0;     // отступ самой плашки от отступа абзаца
    qreal radius = 0.0;     // радиус скругления углов
    qreal stripPadding = 0.0;  // поле полоски слева и справа
    qreal ruleWidth = 0.0;     // толщина черты под полоской
    qreal ruleInset = 0.0;     // насколько черта не доходит до правого края
};
CodePlate codePlate(qreal zoom);

