    // та же гарнитура, что у текста.
    QString codeFamily = QStringLiteral("IBM Plex Mono");
    // Кегль кода в пунктах, как и baseFontPoint; ноль — как у текста. Величина
    // абсолютная, а не доля от кегля текста: у текста и у кода гарнитуры
    // разные и чаще всего будут разными, а шкала размеров у каждой своя —
    // одна и та же доля даёт у них разный видимый размер. И блок кода, и код
