    qreal lineHeightFactor = 1.15;
    qreal listLineHeightFactor = 1.05;
    // Отбивки и поля — в высотах строки основного шрифта, а не в пикселях: со
    // сменой гарнитуры и кегля ритм страницы должен идти следом, иначе после
