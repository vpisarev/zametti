// Поиск по истории ОДНОЙ заметки: по всем слепкам её журнала.
//
// Почему синхронно, без потока. Поиск по хранилищу живёт в своём потоке
// (store_search.h) — там 271 заметка и 11 мс, а на десятикратном корпусе уже
// 113 мс, то есть видимый глазом рывок. Здесь другое: журнал одной заметки —
// это десятки слепков одной и той же заметки, распаковка идёт цепочкой, и весь
// проход стоит миллисекунды (замер — в отчёте этапа 10). Заводить ради этого
// поток значило бы платить сложностью за то, чего не видно.
//
// РАСШИРЯЕМОСТЬ ДО КОРПУСНОГО ПРОГОНА заложена в устройстве: функция берёт
// историю и id заметки, а не «открытую заметку», и ничего не знает про виджеты.
// Обойти ею все журналы хранилища — это цикл снаружи плюс поток, как у
// store_search. Самого корпусного прогона в этапе нет (решение владельца:
// пер-заметочный сильно быстрее и востребованнее).
//
// ЖУРНАЛ ЭТА ФУНКЦИЯ НЕ ПРАВИТ. Ленивая миграция — дело вызывающего, и зовётся
// она до поиска: искать надо по уже чистой истории, иначе один и тот же текст
// найдётся в трёх записях-дубликатах.

#ifndef ZAMETTI_HISTORY_SEARCH_H
#define ZAMETTI_HISTORY_SEARCH_H

#include "journal.h"
#include "zstorage.h"
#include "search.h"
#include "store_search.h"

#include <QString>
#include <QVector>

namespace zametti {

// Сколько находок показываем. Тот же порядок, что у поиска по хранилищу:
// список длиннее сотни никто не читает, а обрезать молча нельзя — об этом
// говорит truncated.
inline constexpr int kHistoryHitLimit = 200;

struct HistorySearchReport {
    QVector<SearchResult> hits;
    int snapshots = 0;      // сколько слепков просмотрено
    int withHits = 0;       // в скольких нашлось
    bool truncated = false;
    qint64 elapsedMs = 0;
};

// Найти запрос во всех слепках журнала заметки. Свежие слепки идут первыми:
// человек ищет «где это было», и ближайшее прошлое ему нужнее давнего.
HistorySearchReport searchNoteHistory(ZStorage& storage, const QString& noteId,
                                      const Query& query, int limit = kHistoryHitLimit);

}  // namespace zametti

#endif  // ZAMETTI_HISTORY_SEARCH_H
