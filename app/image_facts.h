// Что известно про вложенную картинку, не разжимая её.
//
// Всё берётся из ЗАГОЛОВКА файла и из самой заметки. Пикселей не трогаем: под
// кареткой картинка меняется на каждое движение, а разжать снимок с телефона —
// это десятки миллисекунд и десятки мегабайт.
//
// Имя исходника здесь не читается из XMP, хотя мы его туда и пишем
// (xmpMM:PreservedFileName): в заметке оно уже есть — это подпись картинки,
// alt. Лезть за ним в файл значило бы читать бокс JXL на каждое движение
// каретки ради того, что лежит в трёх сантиметрах выше.

#ifndef ZAMETTI_IMAGE_FACTS_H
#define ZAMETTI_IMAGE_FACTS_H

#include <QSize>
#include <QString>

namespace zametti {

struct ImageFacts {
    QString path;        // абсолютный путь к файлу вложения
    QString name;        // имя файла: в плоском хранилище это id вложения
    QString caption;     // подпись из заметки — там и живёт имя исходника
    QString format;      // как его назвал Qt: "jxl", "jpeg", "png"…
    QSize size;          // из заголовка, настоящие пиксели
    qint64 bytes = 0;
    int frames = 1;      // больше одного — анимация
    bool exists = false; // файла нет: вложение не приехало или удалено руками
    bool valid = false;  // каретка не на картинке — показывать нечего
};

// Заголовок файла плюс кэш: та же картинка при движении каретки внутри неё
// перечитываться не должна. Кэш сбрасывается сам, если файл сменил время
// правки или размер.
ImageFacts imageFacts(const QString& absolutePath);

// Сколько записей сейчас в кэше. Наружу — набору.
int imageFactsCacheSize();
void clearImageFactsCache();

}  // namespace zametti

#endif  // ZAMETTI_IMAGE_FACTS_H
