// Что известно про вложенную картинку, не разжимая её.
//
// Всё берётся из ЗАГОЛОВКА файла и из самой заметки. Пикселей не трогаем: под
// кареткой картинка меняется на каждое движение, а разжать снимок с телефона —
// это десятки миллисекунд и десятки мегабайт.
//
// Имя исходника здесь не читается из XMP, хотя мы его туда и пишем
// (xmpMM:PreservedFileName): в заметке оно уже есть — это подпись картинки,
// alt. Лезть за ним в файл значило бы читать бокс JXL на каждое движение
// каретки ради того, что лежит в трёх сантиметрах выше.

#ifndef ZAMETTI_IMAGE_FACTS_H
#define ZAMETTI_IMAGE_FACTS_H

#include <QDateTime>
#include <QSize>

class QImage;
#include <QString>

namespace zametti {

struct ImageFacts {
    QString path;        // абсолютный путь к файлу вложения
    QString name;        // имя файла: в плоском хранилище это id вложения
    QString caption;     // подпись из заметки — там и живёт имя исходника
    QString format;      // как его назвал Qt: "jxl", "jpeg", "png"…
    QSize size;          // из заголовка, настоящие пиксели
    // У уже разжатой копии спрашиваем цвет и глубину. Разжимать ради панели
    // нельзя: снимок с телефона это десятки миллисекунд и десятки мегабайт.
    QString colorSpace;
    int bits = 0;        // бит на канал; 0 — не спрашивали
    qint64 bytes = 0;
    int frames = 1;      // больше одного — анимация
    // Когда снимок СДЕЛАН — из EXIF (DateTimeOriginal), а если его нет, из XMP
    // (xmp:CreateDate): тот же порядок источников, что у ввоза, и другого быть
    // не должно — иначе одна и та же картинка получала бы две разные даты.
    //
    // Зоны в EXIF нет вовсе: время местное, каким его записала камера. Так его
    // и показываем — без пересчёта в UTC и обратно, потому что пересчитывать
    // не от чего.
    //
    // Недействительная дата — это НЕ ошибка: у снимка может не быть ни EXIF, ни
    // XMP, и тогда сказать нечего. Молчим.
    QDateTime taken;
    bool exists = false; // файла нет: вложение не приехало или удалено руками
    bool valid = false;  // каретка не на картинке — показывать нечего
};

// Заполняет всё, что видно из ЗАГОЛОВКА файла: имя, формат, размеры, вес,
// число кадров. Своего кэша тут нет и не должно быть — сведения живут в кэше
// картинок вида (NoteView::CachedImage), рядом с разжатой копией и размерами,
// которые тот и так читает. Второй кэш означал бы второй ответ на вопрос
// «что это за файл», и они бы разошлись.
void readImageFacts(const QString& absolutePath, ImageFacts& out);

// Досыпает то, что видно только у РАЗЖАТОЙ копии: цветовое пространство и
// глубину. Зовётся там, где картинку и так разжали для показа.
void addDecodedFacts(const QImage& image, ImageFacts& out);

}  // namespace zametti

#endif  // ZAMETTI_IMAGE_FACTS_H
