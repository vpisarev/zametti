// КЕГЛЬ В ПРОПОРЦИИ 96 DPI — БЕЗ ДРОБНОГО МАСШТАБА ЭКРАНА.
//
// Кегли конфига платформонезависимы (11 pt), но pt Qt переводит в пиксели через
// ЛОГИЧЕСКИЙ DPI платформы: 96 на Linux, 72 на маке — и те же 11 pt на маке
// выходят на четверть мельче. Правится у корня, переменной QT_FONT_DPI, — но у
// неё есть второе дно (найдено 04.09.2026 по следам каретки на маке):
//
//   QT_FONT_DPI, отличный от DPI платформы, Qt 6 применяет НЕ к шрифтам, а ко
//   всему масштабу экрана: 96/72 = 4/3 ложится множителем поверх ретины, и
//   devicePixelRatio виджетов становится 2,667. Кегль при этом остаётся 11 px,
//   а всё окно растёт на треть. Дробный dpr — беда сам по себе: клип рисования
//   Qt переводит в пиксели через qRound, а досклейку кадра из предыдущего
//   IOSurface (Cocoa держит их три) — умножая начало и размер порознь; между
//   двумя округлениями остаётся столбик в один физический пиксель, который
//   никто не перерисовывает. В нём и жил «след каретки» после быстрого набора,
//   а «стёртая полоска в полпикселя посреди букв» — та же граница с другой
//   стороны.
//
// Лечится политикой округления масштаба (Qt::HighDpiScaleFactorRoundingPolicy):
// дробный множитель округляется до целого, а ОСТАТОК Qt отдаёт в логический
// DPI — то есть ровно в шрифты. Замерено на маке: dpr 2, logicalDpi 96,
// 11 pt → 15 px (ступень зума), следов каретки — ноль на шестидесяти буквах;
// без политики — dpr 2,667 и след на четвёртой букве.
//
// ЗВАТЬ ДО СОЗДАНИЯ ПРИЛОЖЕНИЯ: и переменную, и политику Qt читает при старте.
// Заданные снаружи переменные не перебиваются (QT_FONT_DPI — впрямую,
// политику — переменная QT_SCALE_FACTOR_ROUNDING_POLICY, она старше вызова).

#ifndef ZAMETTI_FONT_DPI_H
#define ZAMETTI_FONT_DPI_H

namespace zametti {

// Кегль — через dpi точек на дюйм, масштаб экрана — целый. Набор FontDpi
// держит оба свойства дочерним процессом.
void prepareFontDpi(int dpi);

}  // namespace zametti

#endif  // ZAMETTI_FONT_DPI_H
