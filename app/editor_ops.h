// Операции редактирования — функции над QTextDocument.
//
// Здесь и только здесь документ меняется. Обработчики клавиш и мыши переводят
// ввод в вызовы этих функций и не трогают документ напрямую: иначе правило
// «одна операция — один шаг истории» держать нечем, а инварианты списков
// расползаются по обработчикам событий.
//
// Каждая операция сама заключает себя в beginEditBlock/endEditBlock и сама
// доводит списки до инварианта.

#ifndef ZAMETTI_EDITOR_OPS_H
#define ZAMETTI_EDITOR_OPS_H

#include "ir.h"

#include <QString>

#include <QString>
#include <QTextCharFormat>

class QTextCursor;
class QTextDocument;

namespace zametti {

// Диапазон блоков, включая оба конца. Номера, а не позиции: позиции при правке
// разъезжаются, номера переживают её.
struct BlockRange {
    int first = 0;
    int last = 0;
};

// Enter. Разрезает блок по курсору; на пустом пункте списка вместо этого
// снимает список — повторного нажатия не требуется.
//
// Операция трогает только содержимое, род и уровень блоков. Всё оформление,
// которое из них следует, — поля, отбивку, шрифт — пересчитывает сборщик
// документа: так ни одно свойство не может отстать от рода блока.
//
// Возвращает false, если делать нечего и вызывающему следует поступить штатно.
bool splitBlockAtCursor(QTextDocument& doc, QTextCursor& cursor);

// Backspace в начале пункта списка: пункт становится абзацем, род и уровень
// снимаются. Текст с предыдущим блоком не сливается — иначе одно нажатие
// склеивало бы два пункта, чего никто не ждёт.
//
// Возвращает false во всех прочих случаях: обычный Backspace внутри текста
// штатный.
bool unwrapListItemAtCursor(QTextDocument& doc, QTextCursor& cursor);

// Ctrl+Up / Ctrl+Down: пункт меняется местами с соседним пунктом того же
// уровня. Единица перемещения — пункт вместе со своим поддеревом; поддерево
// соседа при обмене тоже едет целиком.
//
// Сосед ищется в пределах непрерывной списочной области: через абзац операция
// не перепрыгивает. У первого пункта вверх и у последнего вниз — молча ничего.
//
// Работает над IR, а не над курсором: переставить два куска вектора надёжнее,
// чем вырезать и вставлять куски документа, и свойства блоков при этом заведомо
// сохраняются. Виджет собирает документ из возвращённого IR.
struct MoveResult {
    bool done = false;
    Document doc;         // документ целиком, с переставленными пунктами
    int irBlock = 0;      // куда переехал пункт, номером блока IR
    int offsetInBlock = 0;   // где в нём стоял курсор, в кодовых единицах UTF-16
};

MoveResult moveListItem(const QTextDocument& doc, const QTextCursor& cursor, int direction);

// Tab и Shift+Tab: сдвиг пунктов списка на уровень внутрь и наружу.
//
// Двигается пункт вместе со своим поддеревом: все следующие блоки глубже него
// едут с ним, иначе отступ разорвал бы дерево. Отступ разрешён, только если
// предыдущий блок списочный и не мельче текущего — первый пункт списка
// отступать некуда, и операция молча отказывается.
//
// Выделение после операции держится на номерах блоков: текст не меняется,
// поэтому позиции остаются прежними.
bool indentListItems(QTextDocument& doc, QTextCursor& cursor);
bool outdentListItems(QTextDocument& doc, QTextCursor& cursor);

// IR-фрагмент выделения. Свойства блоков переносятся через
// QTextDocumentFragment — проверено, что род, уровень и признак продолжения его
// переживают.
//
// Уровни списка ребейзятся: минимальный становится нулевым, иначе фрагмент,
// вырезанный из глубины, вставлялся бы с провисшим отступом, какого в файле не
// бывает.
//
// Выделение внутри одного блока — это просто текст: род возвращается только
// если блок выделен целиком.
Document selectionToIr(const QTextCursor& cursor);

// Обменный формат — сам markdown, отдельного MIME-типа нет: у нас есть парсер и
// сериализатор, и их идемпотентность гарантирует, что скопированное внутри
// приложения вставится без потерь.
//
// У одиночного абзаца завершающий перевод строки снимается: он не часть текста,
// а разделитель блоков, и в чужом редакторе давал бы лишний перенос.
QString selectionToMarkdown(const QTextCursor& cursor);

// Автозамена в начале блока, по пробелу: "- ", "* " и "+ " делают буллет,
// "1. " и "1) " — нумерованный пункт, "# ".."###### " — заголовок, "[ ] " и
// "[x] " в начале буллета — задачу.
//
// Отдельный шаг истории: первый Ctrl+Z обязан вернуть набранные знаки, а не
// отменить предыдущую правку.
//
// Звёздочка и плюс — только способ ввода: в файл маркер уходит дефисом, канон
// знака маркера не хранит (см. zametti-core-notes.md).
bool applyInputRuleAtCursor(QTextDocument& doc, QTextCursor& cursor);

// Начертание на выделение: жирный, курсив, зачёркнутый. Переключает — если весь
// выделенный текст уже такой, начертание снимается, иначе ставится.
//
// Не действует внутри встроенного кода и в литеральных блоках: там текст
// буквальный, и разметке внутри него взяться неоткуда.
//
// Без выделения делать нечего и операция отказывается: набор с новым
// начертанием — дело виджета, документ при этом не меняется.
bool toggleBold(QTextDocument& doc, QTextCursor& cursor);
bool toggleItalic(QTextDocument& doc, QTextCursor& cursor);
bool toggleStrike(QTextDocument& doc, QTextCursor& cursor);

// Начертание для набора в точке ввода: тот же переключатель, но применительно к
// формату, с которым пойдёт следующая буква.
QTextCharFormat inlineStyleForTyping(const QTextCharFormat& current, int style);

// Смена рода блоков в выделении. Семантика «установить», а не «переключить»:
// смешанное выделение целиком приводится к запрошенному роду.
//
// Литеральные блоки — код и дословные куски — не трогаются: они лежат в
// документе построчно и списком быть не могут.
bool makeBullet(QTextDocument& doc, QTextCursor& cursor);
bool makeOrdered(QTextDocument& doc, QTextCursor& cursor);
bool makeTask(QTextDocument& doc, QTextCursor& cursor);
bool makeParagraph(QTextDocument& doc, QTextCursor& cursor);

// Переключает задачу под курсором: сделана ↔ не сделана. При выделении
// переключаются все задачи в нём, и все — в ту же сторону, что и первая: иначе
// одно нажатие на смешанном выделении оставляло бы его смешанным.
//
// На блоках, которые не задачи, отказывается: превращать буллет в задачу — дело
// команд смены рода, а не переключателя.
bool toggleTaskAtCursor(QTextDocument& doc, QTextCursor& cursor);

// Пересчитывает левые поля списочных блоков. Поле зависит от уровня и от ширины
// маркеров всех родителей, поэтому считать его можно только проходом от начала
// списка — отсюда же и расширение диапазона до целых прогонов.
//
// Живёт рядом с операциями, а не в сборщике документа, потому что нужно обоим:
// правило отступа должно быть записано ровно один раз.
void applyListGeometry(QTextDocument& doc, BlockRange range);

// Нормализующий проход после любой операции: уровни приводятся к допустимым,
// геометрия пересчитывается. Диапазон расширяется до целых списочных прогонов.
//
// В отличие от брифа, объектов QTextList здесь нет вовсе — маркеры мы рисуем
// сами, — поэтому сшивать нечего: остаются уровни и геометрия.
void syncLists(QTextDocument& doc, BlockRange range);

// Приводит блоки-продолжения к допустимому виду: продолжением может быть только
// блок, у которого предыдущий — того же рода (код к коду, дословный к
// дословному) и не начинается новым родом. Нарушивший признак снимается, и блок
// становится началом своего логического блока — то есть отдельным блоком кода.
//
// Нужен после любой операции, которая двигает, режет или склеивает блоки:
// признак продолжения относительный, он говорит про связь с предыдущим блоком,
// а не про сам блок, и операция способна эту связь порвать.
void syncLiteralBlocks(QTextDocument& doc, BlockRange range);

// Инвариант блоков-продолжений: первым в документе продолжение быть не может, и
// предыдущий блок обязан быть того же рода.
bool literalInvariantHolds(const QTextDocument& doc, QString* problem = nullptr);

// Инвариант списков:
//   - уровень первого блока прогона — нулевой;
//   - уровень не прыгает больше чем на единицу вверх от предыдущего блока.
// Возвращает false и объясняет, что не так. Проверяется ассертом после каждой
// операции в отладочной сборке и явно — в тестах.
bool listInvariantHolds(const QTextDocument& doc, QString* problem = nullptr);

}  // namespace zametti

#endif  // ZAMETTI_EDITOR_OPS_H
