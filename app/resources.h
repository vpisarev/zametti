// Вшитое в бинарник: шрифты и иконки.
//
// Зачем это вообще отдельным модулем. Умолчания настроек называют шрифты по
// имени семейства («IBM Plex Mono»), а имя — это просьба, а не гарантия: если
// шрифта в системе нет, Qt молча подставит что найдётся, и вёрстка поедет на
// первом же чужом запуске. Влинкованные начертания превращают просьбу в
// обещание. Список начертаний здесь — единственный источник правды: по нему
// идёт и регистрация, и проверка, и он же сверяется с умолчаниями настроек.
//
// Ресурсы лежат в статической библиотеке (resources.qrc собран в
// zametti-widgets), а не в исполняемом файле: тестам нужны те же шрифты и те же
// иконки. Плата за это — обязательный Q_INIT_RESOURCE, иначе компоновщик имеет
// полное право выбросить объектный файл ресурсов целиком. Он спрятан внутри
// loadEmbeddedFonts() и iconsReady(): достаточно позвать любую из них.

#ifndef ZAMETTI_RESOURCES_H
#define ZAMETTI_RESOURCES_H

#include <QStringList>

#include <span>

namespace zametti {

// Влинкованное начертание: путь в qrc, семейство и стиль, которые обязаны в
// нём оказаться. Обещание держим рядом с файлом, потому что проверять надо
// именно пару: файл с именем «-Bold», в который положили Regular, работает,
// собирается и молчит — а разметка теряет жирный. Стиль — как он записан в
// таблице name шрифта (nameID 2): Regular, Italic, Bold, Bold Italic.
struct EmbeddedFace {
    const char* path;
    const char* family;
    // The style of a static face, or the DEFAULT INSTANCE of a variable one
    // (what nameID 2 of the file says); a variable file brings every weight
    // of its axis as named instances — Regular … Bold, SemiBold among them.
    const char* style;
    bool variable;
};

std::span<const EmbeddedFace> embeddedFaces();

// Регистрирует все начертания из embeddedFaces(). Возвращает пути тех, что Qt
// не приняла; пустой список — всё на месте. Повторный вызов ничего не делает:
// звать можно и из main, и из теста, не сговариваясь.
QStringList loadEmbeddedFonts();

// Иконки тулбара и дерева — имена файлов в :/icons. Список нужен не для
// красоты: без него опечатка в имени становится молча пустой иконкой, а не
// красным набором.
std::span<const char* const> embeddedIcons();

// Лицензия вшитой части: что это, чьё и где лежит текст. Список — тот же
// источник правды, что и у иконок: вкладка «Лицензии» строится по нему, и
// набор по нему же проверяет, что каждый текст на месте и непуст. Пропавшая
// лицензия — это не косметика, а нарушение условий чужой лицензии.
struct EmbeddedLicense {
    const char* path;     // путь в qrc
    const char* name;     // как называется вшитое
    const char* what;     // зачем оно нам
    const char* license;  // под какой лицензией
};

std::span<const EmbeddedLicense> embeddedLicenses();

// ДОКУМЕНТАЦИЯ — ПУТИ К ВШИТЫМ ФАЙЛАМ docs/info/, по именам файлов.
//
// Списка здесь нет и быть не должно: что вшито, решает CMake обходом каталога
// (app/CMakeLists.txt), а мы спрашиваем у самих ресурсов. Второй список рядом
// с первым однажды отстанет — так уже отстал список лицензий, на шесть
// библиотек.
//
// Заголовки строк тоже не наши: заголовок заметки — её первая строка, и у
// документации он берётся оттуда же, откуда у настоящих заметок.
//
// Возвращаются ТОЛЬКО markdown-файлы (*.md); картинки рядом с ними живут в том
// же каталоге ресурсов и находятся по ссылкам внутри документов.
QStringList embeddedDocs();

// Содержимое вшитого файла как UTF-8. Пусто — файла в ресурсах нет (а значит,
// в qrc опечатка): молчать об этом нельзя, поэтому жалоба в stderr.
QString embeddedText(const char* path);

// Гарантирует, что ресурсы подключены, и возвращает путь иконки в qrc.
// Ходить в ":/icons/..." мимо этой функции нельзя: в статической библиотеке
// ресурсов может ещё не быть.
QString iconPath(const char* name);

}  // namespace zametti

#endif  // ZAMETTI_RESOURCES_H
