    QTimer glideStart_;        // ждёт тишины: значит пальцы убрали
    QTimer scrollGlide_;       // и уже он тащит текст с затуханием
    // Система умеет инерцию сама (macOS, Wayland): своей поверх не делаем.
    bool systemGlides_ = false;
