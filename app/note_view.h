    int copiedCodeBlock_ = -1;
    int editedCodeLanguage_ = -1;
    int editedImageCaption_ = -1;
    // Таблицы, показанные сеткой: по номеру первого блока.
    QHash<int, TableRender> tables_;
    int editedTable_ = -1;
    QHash<int, FormulaRender> formulas_;

    QTimer copiedFade_;
    QTimer caretBlink_;
    bool caretOn_ = true;
    QString imageBase_;
    bool syncingImages_ = false;
    // Что менялось в документе с прошлого перемера. Курсором, а не парой
    // чисел: позиции плывут от каждой следующей правки. Пусто — обходить надо
