    // этот признак, чтобы не записать перекладку окна в историю.
    bool changingLayout() const { return changingLayout_ > 0; }

    // ПОМЕТКА «ЭТО ОБЛИК, А НЕ ПРАВКА» — СЧЁТЧИК, А НЕ ПРИЗНАК.
    //
    // Признаком быть нельзя, и это стоило дефекта: syncImageSpace зовётся
    // из-под applyContentWidth (по сигналу textChanged, который шлёт первая же
    // запись полей) и, закончив, ставил флаг в false — гася пометку, поднятую
    // вызывающим. Дальше сигнал доходил до редактора уже «чистым», и перекладка
    // полей записывалась в историю как набор. Пока зум делался пересборкой, всё
    // это накрывалось сверху признаком recordingSuspended_ и наружу не вылезало.
    //
    // Скобка — RAII, а не голые ++/--: у applyContentWidth есть ранний возврат,
    // и на нём парный -- однажды потеряется.
    class LayoutChange {
    public:
        explicit LayoutChange(NoteView* view) : view_(view) {
            if (view_ != nullptr) ++view_->changingLayout_;
        }
        ~LayoutChange() {
            if (view_ != nullptr) --view_->changingLayout_;
        }
        LayoutChange(const LayoutChange&) = delete;
        LayoutChange& operator=(const LayoutChange&) = delete;

    private:
        NoteView* view_;
    };

