    ImageObjectHandler* imageObjects_ = nullptr;
    FormulaObjectHandler* formulaObjects_ = nullptr;

    int imageDragBlock_ = -1;             // номер блока с перетаскиваемым углом
    qreal imageDragWidth_ = 0.0;
