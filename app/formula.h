// Формулы: движок MicroTeX за одной дверью.
//
// Наружу отдаётся ровно то, что нужно показу: картинка, её базовая линия и
// размеры. Ни одного заголовка MicroTeX за пределы formula.cpp не выходит —
// иначе чужие имена (`Render`, `Font`, `Graphics2D`) расползлись бы по всему
// виджетному слою, а движок у нас вендоренный, из ветки без релизов.
//
// ТРИ ЛОВУШКИ, ЗАПИСАННЫЕ РАЗВЕДКОЙ (docs/zametti-brief-m16.md и отчёт
// `zametti-microtex-final-report.md`) — каждая стоила бы дня:
//
//   1. `Render::getBaseline()` возвращает ДОЛЮ ascent от полной высоты, а не
//      пиксели. Базовая линия = getBaseline() * getHeight(). Обжечься на этом
//      легко именно там, где это важнее всего — при посадке инлайн-формулы в
//      строку текста;
//   2. шестой аргумент `parse` — `fillWidth` — по умолчанию `true`, и тогда
//      вёрстка растягивается на всю заданную ширину: формула шириной 43 точки
//      приезжает шириной 779. Ширина для нас — только предел переноса;
//   3. движок молчалив: из десяти заведомо сломанных формул он бросает
//      исключение на трёх, а остальные семь дорисовывает огрызком. Значит
//      предконтроль наш, до вызова (checkLatex ниже).
//
// Инициализация — один раз на процесс, шрифты читаются из qrc. Прогревочный
// холостой рендер там же: первый рендер стоит 26 мс против 4 мс у всех
// следующих (замер разведки), и эти 22 мс не должны достаться первой формуле
// человека.

#ifndef ZAMETTI_FORMULA_H
#define ZAMETTI_FORMULA_H

#include <QColor>
#include <QImage>
#include <QString>

namespace zametti {

// Что вышло из рендера. Пустой error — вышло.
struct FormulaImage {
    QImage image;          // с домноженной альфой, в физических точках (dpr учтён)
    qreal baseline = 0.0;  // от верха картинки до базовой линии, в логических точках
    qreal width = 0.0;     // логические размеры вёрстки, без полей
    qreal height = 0.0;
    qreal depth = 0.0;     // сколько вёрстка свисает ниже базовой линии
    QString error;

    bool ok() const { return error.isEmpty() && !image.isNull(); }
};

// Предконтроль исходника ДО движка: баланс `{}`, парность `\left`/`\right` и
// `\begin`/`\end`. Пусто — можно рисовать; иначе человеческое объяснение для
// рамки ошибки.
//
// Чистая функция от строки: перебирается набором целиком, без движка и без
// картинок.
QString checkLatex(const QString& latex);

// Движок. Один на процесс: у MicroTeX глобальный контекст (статический
// Config*), и заводить второй нельзя.
class Formulas {
public:
    // Поднять движок: шрифты из ресурсов, прогревочный рендер. Зовётся из
    // main один раз; повторный вызов ничего не делает. false — движок не
    // поднялся, и тогда все формулы показываются рамкой ошибки.
    static bool init(QString* error = nullptr);
    static bool ready();

    // Отрисовать формулу. latex — БЕЗ обрамляющих долларов; display — выключная
    // (по центру, крупнее), иначе инлайн.
    //
    // pixelSize — размер em В ПИКСЕЛЯХ, а не в пунктах. Это замер, а не
    // догадка: при textSize=100 движок даёт cap-height 69 и x-height 47
    // пикселей, то есть привычные для шрифта доли от em. Передашь сюда
    // пункты — формула выйдет на треть мельче текста, и разбираться в этом
    // будешь по снимку (я так и сделал: 11 вместо 15 при кегле 11 пунктов на
    // экране 96 dpi).
    //
    // Спрашивать размер надо у Qt: `QFontInfo(font).pixelSize()` — она знает,
    // во сколько пикселей превратился кегль в пунктах на этом экране.
    //
    // dpr — плотность экрана: картинка рисуется в физических точках, а размеры
    // отдаются в логических.
    static FormulaImage render(const QString& latex, bool display, qreal pixelSize,
                               const QColor& colour, qreal dpr);

    // Сколько раз движок и правда рисовал. Счётчик — часть договора, а не
    // отладка: правило «повторный показ заметки не зовёт движок ни разу»
    // иначе не проверить (так же считаются декоды картинок).
    static int renders();
    static void resetRenders();

    // Имя гарнитуры, которой набрана математика: в окно About.
    static QString mathFontName();
};

}  // namespace zametti

#endif  // ZAMETTI_FORMULA_H
