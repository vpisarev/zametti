// Иконки тулбара: SVG из ресурсов в подкрашенный pixmap.
//
// Почему не `QIcon(":/icons/…")` напрямую. Во-первых, цвет: иконки Lucide
// нарисованы штрихом `currentColor`, то есть без цвета вовсе, и раскрашивать их
// должен тот, кто знает палитру. Во-вторых, размер: QIcon отдал бы растр
// логического размера, а на дробном devicePixelRatio его пришлось бы тянуть —
// ровно то мыло, из-за которого на этапе 8 расползались картинки. Здесь SVG
// рисуется СРАЗУ в физический размер.
//
// Рисует QSvgRenderer из Qt6::Svg, а не плагин imageformats: плагин лежит в
// отдельном необязательном пакете qt6-svg-plugins, и на машине без него тулбар
// оказался бы пустым молча. Слинкованный модуль делает зависимость объявленной.

#ifndef ZAMETTI_ICONS_H
#define ZAMETTI_ICONS_H

#include <QColor>
#include <QPixmap>
#include <QString>

namespace zametti {

// Иконка `name` (без расширения, см. embeddedIcons()) стороной `points` точек
// интерфейса, цветом `color`, для экрана с плотностью `dpr`.
//
// Результат кэшируется по всем четырём составляющим: тулбар просит одни и те же
// иконки на каждой перерисовке, а разбор SVG стоит на три порядка дороже, чем
// взять готовое.
QPixmap toolbarIcon(const QString& name, int points, const QColor& color, qreal dpr);

// Сбросить кэш. Зовётся при перезагрузке оформления: цвета и размер меняются, а
// ключ кэша их учитывает — но держать в памяти растры прежней палитры незачем.
void clearIconCache();

// Сколько растров сейчас в кэше. Нужно проверкам: без этого «кэш работает»
// нечем подтвердить, кроме как замером времени, а он шумит.
int iconCacheSize();

}  // namespace zametti

#endif  // ZAMETTI_ICONS_H
