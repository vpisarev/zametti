// Что QTextDocument знает о себе сверх видимого текста.
//
// Договор один на всех: сборщик расставляет эти свойства, читатель по ним
// восстанавливает IR, отрисовка по ним рисует маркеры. Выводить род блока из
// оформления нельзя: заголовок набран жирным целиком, и «жирный» внутри него
// стал бы неотличим от самого заголовка.
//
// Область значений у каждого свойства маленькая и конечная. Это не случайность:
// QTextFormatCollection интернирует форматы, и уникальное значение на блок
// (номер пункта, отметка времени) завело бы отдельный формат на каждый блок.

#ifndef ZAMETTI_DOC_MODEL_H
#define ZAMETTI_DOC_MODEL_H

#include "ir.h"

#include <QTextFormat>

#include <vector>

class QTextBlock;

namespace zametti {

enum DocProperty {
    // Свойства блока.
    KindProperty = QTextFormat::UserProperty,  // int(Kind)
    LevelProperty,                             // int, уровень вложенности списка
    InfoProperty,                              // QString, язык блока кода
    RawProperty,                               // bool, блок выводится дословно
    // bool на ПОСЛЕДНЕМ блоке логического: текст кончался переводом строки.
    // Пустой блок кода и блок из одной пустой строки выглядят одинаково, а в
    // файл выводятся по-разному.
    TrailingNewlineProperty,
    // bool: этот блок продолжает предыдущий, а не начинает новый.
    //
    // Литеральные блоки — код и дословные куски — режутся построчно, по одному
    // QTextBlock на строку. Qt переразмечает целиком тот блок, в который пишут,
    // и без нарезки правка внутри блока кода на 31 480 знаков стоила 4257 мкс
    // против 109 мкс в блоке на сотню знаков.
    //
    // Признак обязателен: без него разрезанный блок кода из двух строк
    // неотличим от двух отдельных блоков кода подряд, а это разный markdown.
    ContinuationProperty,

    // Свойства формата знаков.
    SpanStyleProperty,   // int, биты SpanStyle
    BreakSourceProperty, // int(BreakSource) на самом разделителе строк
};

// Три знака Qt в insertText трактует структурно и рвёт на них блок. Замерено
// перебором: ровно '\n', '\r' и U+2029, больше ничего (U+2028, U+0085, U+000B,
// U+000C, U+001C..U+001E проходят как обычный текст).
//
// Внутрь блока все три попадают разделителем строк U+2028 — он рисуется
// переносом и блок не рвёт, — а какой знак был на самом деле, помнит свойство.
// Без него не обойтись: точно такой же U+2028 может стоять и в самом тексте
// заметки, заметки из Apple Notes им кишат, и превращать его в перевод строки
// значило бы портить текст.
enum BreakSource {
    BreakNewline = 1,
    BreakCarriageReturn = 2,
    BreakParagraph = 3,
};

enum SpanStyle {
    SpanBold = 1,
    SpanItalic = 2,
    SpanStrike = 4,
    SpanCode = 8,
};

bool isRawBlock(const QTextBlock& block);

// Продолжение предыдущего блока: строка внутри блока кода или дословного куска.
bool isContinuationBlock(const QTextBlock& block);
Kind kindOf(const QTextBlock& block);
int levelOf(const QTextBlock& block);
bool isListBlock(const QTextBlock& block);
bool isTaskBlock(const QTextBlock& block);

// Номер пункта в прогоне. Считается обходом назад по тому же правилу, что и в
// сериализаторе: вложенный подсписок прогон не рвёт. Хранить номер в формате
// нельзя — см. про интернирование выше.
//
// Для одиночного блока это дешевле всего; проходя по документу подряд, берите
// ListRuns — там тот же счёт, но за один проход вместо квадрата. Что оба
// способа дают одно и то же, проверяет ops_test.
int ordinalOf(const QTextBlock& block);

// Прогоны списка, по одному на каждый уровень вложенности. Ключ прогона — не
// сам Kind, а его проекция (уровень, нумерованность): Bullet, TaskUnchecked и
// TaskChecked принадлежат одному семейству и прогон не рвут. Прогон переживает
// вложенный подсписок, иначе нумерация начиналась бы заново — "1. 2. 1."
// вместо "1. 2. 3.".
class ListRuns {
public:
    // Список кончился: следующий начнётся с чистого счёта.
    void reset();

    // Начинается ли на этом уровне новый список. Уровень глубже прежнего — это
    // подсписок того же дерева, а другая нумерация на уже открытом уровне
    // означает, что предыдущий список кончился.
    bool startsNewRun(int level, bool ordered) const;

    // Номер следующего пункта на этом уровне; продвигает состояние.
    int next(int level, bool ordered);

private:
    struct Level {
        int ordinal = 0;
        bool ordered = false;
        bool alive = false;
    };
    std::vector<Level> levels_;
};

}  // namespace zametti

#endif  // ZAMETTI_DOC_MODEL_H
