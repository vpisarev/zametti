// Положить картинку в хранилище и сказать, как на неё сослаться.
//
// Прослойка между конвейером импорта (imageio) и редактором. Импорт отвечает
// на вопрос «во что превратить эти байты», а здесь решается, КУДА их деть и
// ПОД КАКИМ ИМЕНЕМ, — и это не одно и то же.
//
// Правила, которые здесь воплощены:
//
//   * ИМЯ БЕССМЫСЛЕННО, как и у заметки: свежий id из четырнадцати знаков плюс
//     расширение. Имя исходника уходит в alt, а не в файл. Иначе две картинки
//     с именем IMG_0001.jpg из разных мест затёрли бы друг друга, а
//     переименование заметки тянуло бы за собой вложения;
//   * СОЗДАЁМ СТРОГО НА СВЕЖЕЕ ИМЯ (O_EXCL). Проверка «файла нет» и создание
//     обязаны быть одним действием ядра: между ними в хранилище может влезть
//     вторая копия программы. Замок при запуске от этого не спасает — он
//     защищает от второй программы, а не от гонки внутри одной;
//   * ВЛОЖЕНИЕ ЛОЖИТСЯ РЯДОМ С ЗАМЕТКАМИ, в тот же плоский каталог. Заметка
//     ссылается на него ОТНОСИТЕЛЬНЫМ именем, поэтому хранилище можно
//     перенести целиком и ничего не сломается;
//   * ПРИ ОТКАЗЕ НЕ ОСТАЁТСЯ МУСОРА. Если импорт не удался, файла не
//     появляется вовсе; если не удалась запись — недописанный файл убирается.
//     Половина картинки в хранилище хуже, чем её отсутствие.
//
// Отмена вставки (Ctrl+Z) вложение НЕ удаляет — это решение владельца из
// брифа. Причина простая: отменённая вставка часто повторяется, а
// восстанавливать удалённый файл неоткуда. Осиротевшие вложения — забота
// отдельной уборки, не редактора.

#pragma once

#include "import_limits.h"

#include <QImage>
#include <QString>

namespace zametti {

struct StoredImage {
    QString fileName;   // "<id>.jxl" — то, чем ссылаться из заметки
    QString alt;        // базовое имя исходника; у битмапа из буфера пусто
    QString message;    // что сделал конвейер: путь, размер, отступы лестницы
    QString error;      // непусто — не вышло, и тогда fileName пуст
    int width = 0;
    int height = 0;

    bool ok() const { return !fileName.isEmpty(); }
};

// Файл с диска: полный конвейер импорта (таблица решений, лестница, цвет).
StoredImage storeImageFile(const QString& sourcePath, const QString& storeDir,
                           const ImportLimits& limits);

// Готовые пиксели: буфер обмена, снимок экрана. Формата у них нет, поэтому
// путь выбирает проба.
StoredImage storeImagePixels(const QImage& image, const QString& storeDir,
                             const ImportLimits& limits);

// Как сослаться на вложение из markdown. Отдельной функцией, потому что зовут
// её из двух мест, а экранирование скобок в alt забыть легко.
QString imageMarkdown(const StoredImage& stored);

// Числа конфига → границы импорта. Отдельной функцией и здесь, а не в
// настройках: настройки описывают ВЕСЬ облик программы и о картинках знать не
// обязаны, а этот файл ровно про них.
ImportLimits limitsFromSettings();

}  // namespace zametti
