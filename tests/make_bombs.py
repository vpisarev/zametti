#!/usr/bin/env python3
"""Фабрика картинок-бомб для проверки границ входа этапа 8.

Бомба — это файл, у которого ЗАГОЛОВОК врёт: он объявляет размеры, под которые
никакой памяти не хватит, а весит при этом килобайты. Настоящих таких не
бывает, их надо делать самому.

Смысл проверки: границы стоят ДО декода. Размеры берутся из заголовка
(QImageReader::size(), без разжатия), и отказ приходит раньше, чем кто-либо
попытается выделить память.

Потолки заявленного (бриф этапа 8):
    сторона > 65 535, либо площадь > 512 Мп, либо ноль/отрицательное → отказ.

Каждая бомба бьёт ровно в одно правило, иначе непонятно, какое сработало.

ЧЕМ СЧИТАТЬ ПЛОЩАДЬ. Бриф говорит «в int64», и этого мало (замечание
владельца). Через QSize размеры приходят как int, и (2^31-1)^2 = 4.6e18 в
int64 влезает. Но если разбирать заголовок самим — в PNG IHDR размеры лежат
как uint32, и (2^32-1)^2 = 1.84e19, то есть ВДВОЕ больше потолка int64:
произведение заворачивается, площадь становится отрицательной и проходит
проверку насквозь. Отсюда два пояса:

  1. считать в double. Точность за 2^53 он теряет, но не заворачивается —
     а нам и не нужна точность, нам нужно сравнение с порогом;
  2. проверять СТОРОНЫ РАНЬШЕ ПЛОЩАДИ. После отказа по стороне площадь
     заведомо не больше 65535^2 = 4.3e9, и тип перестаёт иметь значение.

Бомба «квадрат-предел» стережёт именно это: 65535x65535 даёт 4 294 836 225,
что переполняет уже int32.

    ./make_bombs.py <куда положить>
"""

import struct
import sys
import zlib
from pathlib import Path


def chunk(kind: bytes, data: bytes) -> bytes:
    """Кусок PNG: длина, тип, данные, CRC по типу и данным."""
    return (struct.pack(">I", len(data)) + kind + data
            + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF))


def png(width: int, height: int, *, rows: int = 1) -> bytes:
    """PNG с заявленными width x height и телом на `rows` строк.

    CRC заголовка настоящий: иначе читатель отвергнет файл как битый и мы
    проверим не то. Файл обязан быть правдоподобным ровно до того места, где
    начинается вранье о размере.
    """
    # 8 бит, тип 2 (truecolor RGB), без чересстрочности
    ihdr = struct.pack(">IIBBBBB", width & 0xFFFFFFFF, height & 0xFFFFFFFF, 8, 2, 0, 0, 0)
    # Тело: несколько строк из нулей. Оно заведомо короче заявленного —
    # декодер до конца не дойдёт, но до заголовка дойдёт сразу.
    stride = max(1, min(width, 64)) * 3 + 1
    idat = zlib.compress(b"\x00" * stride * rows, 9)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
            + chunk(b"IDAT", idat) + chunk(b"IEND", b""))


BOMBS = [
    # имя,                        ширина,      высота, во что метит
    ("бомба-миллиард-на-один.png", 1_000_000_000, 1,
     "сторона в миллиард: и потолок стороны, и площадь разом — случай из брифа"),
    ("бомба-сторона.png",          70_000,        100,
     "сторона 70 000 > 65 535, площадь при этом крошечная — бьёт только в потолок стороны"),
    ("бомба-площадь.png",          30_000,        20_000,
     "600 Мп при законных сторонах — бьёт только в потолок площади"),
    ("бомба-квадрат-предел.png",   65_535,        65_535,
     "сторона ровно на пределе, площадь 4295 Мп — проверка, что считаем в int64, а не в int32"),
    ("бомба-нулевая.png",          0,             100,
     "нулевая сторона: деление на ноль в расчёте бюджета не должно случиться"),
]


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    lines = []
    for name, w, h, why in BOMBS:
        data = png(w, h)
        (out / name).write_bytes(data)
        print(f"  {name:<30} {w}x{h}, {len(data)} байт")
        lines.append(f"| `{name}` | {w}×{h} | {len(data)} байт | {why} |")

    (out / "ПРОИСХОЖДЕНИЕ.md").write_text(
        "# Картинки-бомбы\n\n"
        "Сделаны `tests/make_bombs.py`; настоящих таких не бывает.\n\n"
        "У каждой заголовок PNG объявляет размеры, под которые не хватит\n"
        "памяти ни у кого, а сам файл весит меньше килобайта. CRC заголовка\n"
        "настоящий — иначе файл отвергнут как битый и проверено будет не то.\n\n"
        "Границы обязаны сработать **до декода**: размеры берутся из\n"
        "заголовка, математика в int64, отказ приходит раньше, чем кто-то\n"
        "попробует выделить память.\n\n"
        "| файл | заявлено | вес | во что метит |\n|---|---|---|---|\n"
        + "\n".join(lines) + "\n",
        encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
