    canonical("нумерованный список", "1. один\n2. два\n3. три\n");
    canonical("чекбоксы", "- [ ] не сделано\n- [x] сделано\n");
    canonical("смешанный прогон: чекбоксы не рвут маркированный список",
              "- обычный\n- [ ] задача\n- [x] готовая\n- снова обычный\n");
    canonical("вложенность 1 → 2 → 1", "- a\n  - b\n- c\n");
