void testInline() {
    canonical("жирный", "текст **жирный** дальше\n");
    canonical("курсив", "текст _курсив_ дальше\n");
    canonical("зачёркнутый", "текст ~~вычеркнут~~ дальше\n");
    canonical("канон вложенности: strong снаружи, emphasis внутри", "**_оба сразу_**\n");
    canonical("ссылка", "смотри [сюда](https://example.org/x) и всё\n");
    // Голые ссылки разбор опознаёт сам, поэтому и выводятся они голыми:
    // обернув их в угловые скобки, мы переписали бы каждую такую заметку.
    canonical("голая ссылка", "пиши на https://example.org/ когда угодно\n");
    canonical("голый адрес www", "смотри www.example.org вот\n");
    canonical("голая почта", "адрес user@example.org вот\n");
    stable("угловые скобки вокруг ссылки убираются",
           "пиши на <https://example.org/> когда угодно\n",
           "пиши на https://example.org/ когда угодно\n");
    canonical("схема без слэшей остаётся в скобках", "звони <tel:+123> сюда\n");
    // Голой такая ссылка не разберётся — кириллицу в адресе разбор принимает
    // только внутри угловых скобок.
    canonical("не-ASCII в адресе остаётся в скобках",
              "смотри <https://example.org/путь> вот\n");

    std::vector<Block> u = parse("см. https://example.org/x дальше\n").blocks;
    ZT_TRUE("голая ссылка стала спаном",
            u.size() == 1 && u[0].inlines.size() == 1 &&
                u[0].inlines[0].href == "https://example.org/x");
    canonical("жирная ссылка", "**[туда](/a/b)**\n");

    stable("курсив звёздочками приводится к подчёркиванию", "*курсив*\n", "_курсив_\n");
    stable("жирный подчёркиваниями приводится к звёздочкам", "__жирный__\n", "**жирный**\n");
    stable("emphasis снаружи strong перекладывается в канон", "_**оба**_\n", "**_оба_**\n");

    // Смещения спанов — в байтах, и на кириллице это видно.
    std::vector<Block> d = parse("аб **вг** де\n").blocks;
    ZT_TRUE("один спан на кириллице", d.size() == 1 && d[0].inlines.size() == 1);
    if (d.size() == 1 && d[0].inlines.size() == 1) {
        ZT_TRUE("смещение спана в байтах, а не в символах", d[0].inlines[0].offset == 5);
        ZT_TRUE("длина спана в байтах", d[0].inlines[0].length == 4);
    }
}

void testEscaping() {
    canonical("экранированная звёздочка", "буквальная \\*звёздочка\\*\n");
    canonical("звёздочка между пробелами не экранируется", "5 * 3 = 15\n");
    canonical("экранированная решётка в начале строки", "\\# не заголовок\n");
    canonical("экранированный дефис в начале строки", "\\- не список\n");
    canonical("экранированный номер в начале строки", "1\\. не список\n");
    canonical("экранированная цитата", "\\> не цитата\n");
    // Скобки экранируются только когда действительно открывают ссылку: голое
    // "[x]" ссылкой не станет, пока в документе нет определения "[x]: ...".
    canonical("скобки, открывающие ссылку", "буквальное \\[имя](не ссылка)\n");
    stable("закрывающую скобку экранировать незачем",
           "буквальное \\[имя\\](не ссылка)\n", "буквальное \\[имя](не ссылка)\n");
    stable("голые скобки не экранируются", "\\[не ссылка\\]\n", "[не ссылка]\n");
    canonical("экранированный обратный слэш", "путь C:\\\\tmp\n");

    // '_' внутри слова выделения не образует, поэтому и экранировать его не за
    // что: иначе каждый идентификатор в заметках оброс бы слэшами.
    canonical("snake_case не экранируется", "snake_case_name\n");
    canonical("курсив на стыке со словом выводится звёздочкой", "ksize*ksize*/2\n");
    stable("перенос строки не даёт списку слипнуться",
           "текст\n\\- продолжение\n", "текст\n\\- продолжение\n");
}

void testLists() {
    canonical("плоский маркированный список", "- один\n- два\n- три\n");
    canonical("нумерованный список", "1. один\n2. два\n3. три\n");
    canonical("чекбоксы", "- [ ] не сделано\n- [x] сделано\n");
    canonical("смешанный прогон: чекбоксы не рвут маркированный список",
              "- обычный\n- [ ] задача\n- [x] готовая\n- снова обычный\n");
    canonical("вложенность 1 → 2 → 1", "- a\n  - b\n- c\n");
    canonical("чередование уровней 1 → 3 → 2", "- a\n  - b\n    - c\n  - d\n");
    canonical("вложенный список под нумерованным пунктом",
              "1. верх\n   - вложенный\n   - ещё\n2. второй\n");
    canonical("два разнотипных списка подряд без пустой строки",
              "- маркированный\n1. нумерованный\n");
    canonical("пустой элемент списка", "- a\n-\n- b\n");

    // '*' и '+' — разные маркеры, значит два списка; в каноне они сливаются в
    // один, но IR от этого не меняется: те же два пункта нулевого уровня.
    stable("маркеры '*' и '+' приводятся к '-'", "* a\n+ b\n", "- a\n- b\n");
    stable("нумерация приводится к началу с 1", "5. пять\n6. шесть\n", "1. пять\n2. шесть\n");
    stable("делимитр ')' приводится к '.'", "1) один\n2) два\n", "1. один\n2. два\n");
    stable("отступ 4 пробела приводится к 2", "- a\n    - b\n", "- a\n  - b\n");
    // Просторный список остаётся просторным: пустая строка между пунктами —
    // авторская отбивка, и терять её незачем. Раньше канон её сжимал, потому что
    // хранить о ней было негде.
    stable("разреженный список остаётся разреженным", "- a\n\n- b\n", "- a\n\n- b\n");
    stable("список, прерванный абзацем",
           "- a\n- b\n\nабзац\n\n- c\n", "- a\n- b\n\nабзац\n\n- c\n");
}

void testTasksLiteral() {
    // Правило 2: "[x]" после маркера нумерованного списка — литеральный текст.
    canonical("1. [x] остаётся текстом", "1. [x] текст\n");
    canonical("1. [X] сохраняет регистр", "1. [X] текст\n");
    canonical("1. [ ] остаётся текстом", "1. [ ] текст\n");

    std::vector<Block> d = parse("1. [x] текст\n").blocks;
    ZT_TRUE("нумерованный пункт, а не чекбокс",
            d.size() == 1 && d[0].kind == Kind::ListItem && d[0].marker == Marker::Ordered);
    if (d.size() == 1) ZT_EQ("маркер вернулся в текст", "[x] текст", d[0].text);

    // Срез берётся из исходника, а не синтезируется: иначе теряются лишние
    // пробелы и разметка, идущая сразу за маркером.
    d = parse("1. [x]  **жирный** текст\n").blocks;
    ZT_TRUE("жирный не проглочен срезом",
            d.size() == 1 && d[0].inlines.size() == 1 && d[0].inlines[0].bold);
    if (d.size() == 1) ZT_EQ("двойной пробел после маркера сохранён", "[x]  жирный текст", d[0].text);
    canonical("1. [x] с двойным пробелом и разметкой", "1. [x]  **жирный** текст\n");

    // А вот в маркированном списке это настоящий чекбокс.
    d = parse("- [x] текст\n").blocks;
    ZT_TRUE("маркированный пункт с [x] — чекбокс",
            d.size() == 1 && d[0].kind == Kind::ListItem &&
                d[0].marker == Marker::Task && d[0].checked);
    if (d.size() == 1) ZT_EQ("маркер чекбокса в текст не попал", "текст", d[0].text);

    stable("- [X] приводится к нижнему регистру", "- [X] текст\n", "- [x] текст\n");
    stable("- [ ] с двойным пробелом сжимается", "- [ ]  текст\n", "- [ ] текст\n");
}

