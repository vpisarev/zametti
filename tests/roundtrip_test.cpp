// Случаи, найденные прогоном по примерам из спецификаций CommonMark и GFM и по
// мутациям из них. Каждый ломал что-то своё, поэтому лежат отдельно.
void testSpecEdgeCases() {
    // Спан нулевой длины модель не выражает — иначе ссылка исчезла бы целиком.
    Document d = parse("[](./target.md)\n");
    ZT_TRUE("пустая ссылка сохранена дословно", d.size() == 1 && !d[0].rawSource.empty());
    canonical("ссылка с пустым текстом", "[](./target.md)\n");

    // Наружу выносится признак, покрывающий больший кусок.
    stable("выделение, охватывающее вложенное", "***foo** bar*\n", "_**foo** bar_\n");
    canonical("курсив снаружи жирного", "_**foo** bar_\n");

    // Символ-ограничитель у самого края выделения слипся бы с ним.
    canonical("звёздочка вплотную к ограничителю жирного", "foo **\\***\n");
    stable("подчёркивание вплотную к ограничителю курсива", "foo *_*\n", "foo _\\__\n");

    // Скобка внутри текста ссылки разрывает её.
    canonical("скобка внутри текста ссылки", "[link \\[bar](/uri)\n");

    // При наличии определения ссылки любая пара скобок может стать ссылкой.
    canonical("скобки при наличии определения", "\\[foo]\n\n[foo]: /url \"title\"\n");

    // Маркер стоит на своей строке, текст начинается со следующей.
    stable("элемент списка с текстом на следующей строке", "-   \n  foo\n", "- foo\n");

    // Три забора подряд: закрытый пустой блок и следом незакрытый.
    stable("три забора подряд", "```\n```\n```\n", "```\n```\n\n```\n```\n");

    // У блока с info-строкой высота дословного куска считается по содержимому.
    stable("забор с info-строкой и следом ещё один",
           "````;\n````\n````\n", "```;\n```\n\n```\n```\n");

    // Подчёркивание setext-заголовка — его часть, хотя текста в нём нет.
    stable("многострочный setext рядом с разделителем",
           "Foo\nBar\n---\n---\n", "Foo\nBar\n---\n\n---\n");

    // Строка из тильд в начале строки — открывающий забор, а не текст.
    canonical("строка из тильд не всплывает забором", "```\n```\n");

    // Определение ссылки md4c не показывает вовсе, и блок кода не должен на нём
    // усесться.
    stable("определение ссылки перед блоком кода",
           "[foo]: /url\n```\n```\n\n[foo]\n", "[foo]: /url\n\n```\n```\n\n[foo](/url)\n");

    // Код внутри элемента списка списку не по зубам — список уходит дословно
    // целиком, но соседний блок кода при этом не должен в него влезть.
    canonical("список с кодом внутри элемента",
              "-\n  foo\n-\n  ```\n  bar\n  ```\n-\n\n```\n  baz\n```\n");
}


void testInlineCode() {
    canonical("встроенный код", "текст `code` дальше\n");
    canonical("встроенный код внутри жирного", "**`code`**\n");
    canonical("встроенный код как текст ссылки", "[`code`](/u)\n");
    canonical("кавычки внутри встроенного кода", "``a ` b``\n");

    Document d = parse("текст `code` дальше\n");
    ZT_TRUE("код разобран спаном, а не сохранён дословно",
            d.size() == 1 && d[0].rawSource.empty() && d[0].inlines.size() == 1);
    if (d.size() == 1 && d[0].inlines.size() == 1) {
        ZT_TRUE("флаг code выставлен", d[0].inlines[0].code);
        ZT_EQ("кавычки в текст не попали", "текст code дальше", d[0].text);
    }

    // Содержимое кода буквально: экранировать внутри нечего и нельзя.
    canonical("разметка внутри кода не разбирается", "`**не жирный** и _не курсив_`\n");
    stable("пробелы по краям кода требуют подкладки", "` a `\n", "`a`\n");
}

void testQuotes() {
    canonical("цитата", "> цитата\n");
    canonical("цитата в несколько строк", "> первая\n> вторая\n");
    canonical("два абзаца в одной цитате", "> первый\n>\n> второй\n");
    canonical("цитата с разметкой", "> текст **жирный** и [ссылка](/u)\n");
    canonical("цитата между абзацами", "до\n\n> цитата\n\nпосле\n");

    Document d = parse("> цитата\n");
    ZT_TRUE("цитата разобрана, а не сохранена дословно",
            d.size() == 1 && d[0].rawSource.empty() && d[0].kind == Kind::Quote);
    if (d.size() == 1) ZT_EQ("маркер цитаты в текст не попал", "цитата", d[0].text);

    // Внутри цитаты у блока нет ни уровня, ни содержимого сложнее абзаца,
    // поэтому всё остальное остаётся дословным.
    d = parse("> # заголовок\n");
    ZT_TRUE("заголовок в цитате дословен", d.size() == 1 && !d[0].rawSource.empty());
    d = parse("> - пункт\n");
    ZT_TRUE("список в цитате дословен", d.size() == 1 && !d[0].rawSource.empty());
    d = parse("> > вложенная\n");
    ZT_TRUE("вложенная цитата дословна", d.size() == 1 && !d[0].rawSource.empty());

    // Строка ">" в начале строки текста должна экранироваться, иначе абзац
    // превратится в цитату.
    canonical("угловая скобка в начале строки", "\\> не цитата\n");
}

