// Общий вход всех наборов. Один процесс на все проверки — решение владельца,
// и смысл его не в удобстве.
//
// Восемьдесят два отдельных исполняемых файла прятали целый класс бед по
// построению: набор, портящий память или текущий, уносил это с собой в могилу
// вместе со своим процессом. Теперь следующий набор работает в той же памяти,
// и если предыдущий её испортил — это станет видно. Падение в наборе, который
// сам по себе зелёный, отныне повод разобраться, а не пожать плечами.
//
// Обратное тоже осталось: --gtest_filter='Journal.*' гоняет один набор ровно
// так же, как раньше гонялся один бинарник.

#include "test_util.h"

#include "heif_handler.h"
#include "settings.h"

#include <gtest/gtest.h>

#include <QApplication>
#include <QTemporaryDir>

int main(int argc, char** argv) {
    // ПЛАТФОРМА — ДО СОЗДАНИЯ ПРИЛОЖЕНИЯ, иначе Qt её уже выбрал.
    //
    // Раньше это жило свойством ctest ENVIRONMENT и было выписано пятьдесят
    // шесть раз подряд; заодно оно означало, что набор, запущенный руками, а
    // не через ctest, вёл себя иначе. Теперь платформа не зависит от того,
    // кто набор позвал.
    //
    // Под условием, и это не педантизм: заданную снаружи платформу перебивать
    // нельзя — иначе приёмочные снимки под Xvfb молча уехали бы в offscreen.
    if (!qEnvironmentVariableIsSet("QT_QPA_PLATFORM"))
        qputenv("QT_QPA_PLATFORM", "offscreen");

    // КОНФИГ ВЛАДЕЛЬЦА НАБОРАМ НЕ ВИДЕН — ПО ПОСТРОЕНИЮ, А НЕ ПО ВЕЗЕНИЮ.
    //
    // Настройки — это пожелания владельца, и они меняются: другая гарнитура,
    // другой кегль, другое сочетание клавиш, пустое сочетание. Набор, увидевший
    // их, начинает проверять не то, что написано в коде, а то, что сегодня
    // лежит в ~/.config/zametti/config.json, — и приёмочные снимки вместе с ним.
    //
    // Так и было: config_test подменял XDG_CONFIG_HOME временным каталогом, но
    // ВНУТРИ своего набора и обратно не возвращал, а loadSettings(nullptr) зовут
    // ещё четверо (backspace_flat, zoom, caret_scale, tidy_fuzz). Наборы идут
    // одним процессом, порядок задаёт регистрация — то есть «увидит ли набор
    // настоящий конфиг» решал случай, и решал по-разному для разных фильтров.
    //
    // Здесь, рядом с платформой, и безусловно: набору настройки можно, но
    // только СВОЕЙ копией. Каталог живёт до конца процесса; кому нужен конфиг —
    // пишет его сюда же (так делает config_test).
    //
    // ZAMETTI_CONFIG_DIR, А НЕ XDG_CONFIG_HOME. Второй — уговор freedesktop, и
    // под Windows он не значит НИЧЕГО: QStandardPaths там ходит в
    // SHGetKnownFolderPath и переменных среды не смотрит ни одной, то есть
    // набор писал бы прямо в профиль владельца. Свой ключ читает наш configDir()
    // (settings.h), и он одинаков на всех системах.
    static QTemporaryDir configHome;
    qputenv(zametti::kConfigDirVar, configHome.path().toLocal8Bit());

    // QApplication, а не QGuiApplication и не QCoreApplication: он и тот, и
    // другой сразу. Наборов, которым нужны виджеты, больше половины, а платить
    // за них тем, кому хватило бы ядра, — это несколько миллисекунд на весь
    // прогон.
    QApplication app(argc, argv);

    // Декодеры картинок, которых libheif не знает по рождению (AV1 через
    // libgav1). ДО первого потока: реестр плагинов libheif — обычный std::set
    // без замка, а картинки читает и фоновый поток ввоза, и сама libheif в
    // несколько потоков на плиточной сетке.
    zametti::HeifHandler::registerCodecs();

    ::testing::InitGoogleTest(&argc, argv);

    // СЧЁТЧИКИ — ПЕР-НАБОРНЫЕ, И ЭТО НЕ МЕЛОЧЬ.
    //
    // Прежняя обвязка складывала проверки и провалы в две глобальные
    // переменные, а каждый набор в конце возвращал «ноль, если провалов нет».
    // В отдельных процессах это работало; в одном — первый же красный набор
    // красил все следующие, потому что счётчик общий. Первый прогон так и
    // вышел: семь провалов, из них шесть чужих.
    //
    // Сбрасываем здесь, а не в теле каждого набора: место одно, и забыть его
    // в новом наборе нельзя.
    class Reset : public ::testing::EmptyTestEventListener {
        void OnTestStart(const ::testing::TestInfo&) override {
            zt::g_checks = 0;
            zt::g_failures = 0;
            zt::g_reported = 0;
        }
    };
    ::testing::UnitTest::GetInstance()->listeners().Append(new Reset);

    return RUN_ALL_TESTS();
}
