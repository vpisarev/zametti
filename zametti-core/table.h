// Таблица GFM: разбор дословного куска для ПОКАЗА.
//
// Таблицы хранятся дословно (Block::raw), и этот файл ничего в хранении не
// меняет: он только читает кусок и говорит, из чего тот состоит. Обратного
// хода нет вовсе — записывать таблицу обратно некому и незачем (см. бриф
// этапа 12: правка остаётся текстовой).
//
// ПОЧЕМУ НЕ ВТОРОЙ ПРОГОН md4c. Соблазн был: md4c уже умеет таблицы, и
// главный разбор именно от него узнаёт, что перед ним таблица. Но нужен нам
// не разбор ячеек, а ИХ ИСХОДНЫЙ ТЕКСТ: разметку внутри ячейки («жир», код,
// ссылка) рисует наша же машинерия спанов, и кормить её надо тем же
// markdown'ом, что и всё остальное, — то есть звать parse() по тексту ячейки.
// Из колбэков md4c исходный текст ячейки достаётся только сборкой смещений
// вручную, и выходит длиннее и хрупче, чем разрез строки по палкам.
//
// Разрез по палкам не «своя грамматика», а ровно то, что говорит спецификация
// GFM: строка = ряд, ячейки разделены палками, экранированная палка `\|` —
// единственный способ поставить палку внутрь ячейки (даже внутри `кода`).
// Что наш разрез сходится с md4c, проверяет table_test на корпусах: там md4c
// зовётся по-настоящему и сверяется число колонок и ячеек.

#ifndef ZAMETTI_TABLE_H
#define ZAMETTI_TABLE_H

#include <string>
#include <string_view>
#include <vector>

namespace zametti {

// Выравнивание колонки, из строки-разделителя: `:---` слева, `---:` справа,
// `:---:` по центру. Без двоеточий — не задано; вид сам решает, что это значит
// (у нас — по левому краю, как в GitHub).
enum class TableAlign {
    Default,
    Left,
    Center,
    Right,
};

struct Table {
    // Ряды целиком, включая заголовок: rows[0] — шапка, дальше тело. Ячейка —
    // ИСХОДНЫЙ markdown без окружающих пробелов; разметка внутри разбирается
    // потом, тем же parse(), что и весь текст.
    std::vector<std::vector<std::string>> rows;
    std::vector<TableAlign> align;   // по колонке; размер == columns
    int columns = 0;
    // Строки исходника, которые заняла таблица (включая строку-разделитель).
    // Нужны показу: по ним считается, сколько блоков документа спрятать.
    int lines = 0;
    bool valid = false;

    int bodyRows() const { return rows.empty() ? 0 : int(rows.size()) - 1; }
    // Ячейка с прощением: за краем ряда — пустая строка. Ровно так показывает
    // кривые таблицы GitHub, и ровно так договорено в брифе.
    std::string_view cell(int row, int column) const;
};

// Похоже ли начало этого куска на таблицу: первая строка с палкой, вторая —
// строка-разделитель. Тот же признак, по которому таблицу опознаёт md4c.
bool looksLikeTable(std::string_view markdown);

// Разбор. Прощающий: лишние ячейки ряда отрезаются, недостающие считаются
// пустыми, ряды из одних палок законны. valid == false означает «это не
// таблица» — показывать надо как было, дословным текстом.
Table parseTable(std::string_view markdown);

}  // namespace zametti

#endif  // ZAMETTI_TABLE_H
