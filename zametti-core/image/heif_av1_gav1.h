// Декодер AV1 для libheif, сделанный нами поверх libgav1.
//
// ЗАЧЕМ ЭТОТ ФАЙЛ ВООБЩЕ ЕСТЬ. libheif про libgav1 не знает: в её
// libheif/plugins/ лежат декодеры на aom, dav1d, ffmpeg и webcodecs, и ни
// одного на libgav1. А libgav1 выбран нарочно — у него НОЛЬ файлов
// ассемблера при полной векторизации интринзиками, и это единственный
// декодер AV1, который собирается одинаково на всех трёх платформах, куда мы
// идём, без ассемблера в оснастке (см. 3rdparty/libgav1/CMakeLists.txt).
//
// Поэтому декодер пишем сами и отдаём libheif через её ПУБЛИЧНЫЙ
// heif_register_decoder_plugin(). Патча к чужому дереву нет и не будет:
// обновление libheif не порождает конфликтов, а обновление libgav1 трогает
// только этот файл.
//
// Наружу отсюда торчит одна функция, и зовёт её ровно один файл —
// heif_handler.cpp. Это не второй публичный вид операции, а стык двух чужих
// C-ABI: форму диктует подпись libheif.

