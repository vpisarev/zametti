// Запись JPEG XL: единственное место, где картинка превращается в то, что
// ляжет в хранилище.
//
// Что этот слой обязан донести до файла, помимо пикселей:
//
//   * ГЛУБИНУ ИСТОЧНИКА. Десятибитная картинка остаётся десятибитной,
//     шестнадцатибитная режется до потолка конфига (12). Повышать разрядность
//     не имеет смысла — данных от этого не прибавится;
//   * ЦВЕТОВОЕ ПРОСТРАНСТВО ИСТОЧНИКА. Треть снимков в каталогах владельца —
//     Display P3, и загонять их в sRGB значит терять цвета необратимо. sRGB в
//     P3 переводить тоже нельзя: цветов не прибавится, а шаг квантования
//     огрубеет;
//   * МЕТАДАННЫЕ. EXIF, XMP и профиль переносятся боксами контейнера.
//
// Усилие энкодера — 5, и это не умолчание libjxl (там 7). Замер на 4.1 Мп и
// шестнадцати ядрах: e5 даёт 23.6 Мп/с, e7 — 14.8, e9 — 0.53, при выигрыше в
// размере в единицы процентов. Лестница делает до шести энкодов подряд, и
// вдвое дешевле здесь дороже всего.

#pragma once

#include <QByteArray>
#include <QImage>

namespace zametti {

struct EncodeOptions {
    // Качество lossy JXL. Игнорируется, если lossless.
    int quality = 90;
    bool lossless = false;
    // Потолок глубины. Меньшая глубина источника СОХРАНЯЕТСЯ.
    int maxBitsPerChannel = 12;
    // 1..9. Ниже — быстрее и крупнее.
    int effort = 5;
    // Сколько потоков отдать энкодеру. 0 — по числу ядер.
    int threads = 0;
};

// Метаданные, которые уедут в боксы контейнера. Пустые не пишутся: пустой бокс
// хуже отсутствующего — он выглядит как «данные есть», а их нет.
struct EncodeMeta {
    QByteArray exif;   // сырой блоб, начиная с заголовка TIFF
    QByteArray xmp;
    // Профиль берётся из самой картинки (QImage::colorSpace); это поле нужно
    // лишь тогда, когда профиль есть, а Qt его не понял.
    QByteArray icc;
};

// Кодирует картинку. Пустой результат означает ошибку, и тогда в error лежит
// причина.
//
// Глубина берётся из формата картинки: RGBA64/RGBX64 — шестнадцать бит,
// остальное — восемь. Если источник глубже потолка, в заголовок пишется
// потолок, а libjxl ужимает сама — так решил владелец.
QByteArray encodeJxl(const QImage& image, const EncodeOptions& options, const EncodeMeta& meta,
                     QString* error);

// Байт-точный транскод JPEG в JXL. Возвращает пустое, если libjxl отказалась:
// не всякий JPEG к этому пригоден (прогрессивные с редкими настройками, битые
// таблицы).
//
// САМОПРОВЕРКА ОБЯЗАТЕЛЬНА и делается снаружи: транскод принимается только
// после обратной сборки с совпавшим отпечатком (инвариант A этапа 8).
QByteArray transcodeJpegToJxl(const QByteArray& jpeg, QString* error);

// Обратная сборка исходного JPEG из транскода. Ею и проверяется, что транскод
// удался.
QByteArray reconstructJpeg(const QByteArray& jxl, QString* error);

}  // namespace zametti
