// Сравнение двух картинок по SSIMULACRA2.
//
// ЧТО ЗДЕСЬ БЫЛО РАНЬШЕ. Лестница качества: когда картинка не влезала в бюджет
// файла, она ступенями снижала качество, потом разрешение, а арбитр на
// SSIMULACRA2 решал, не зашло ли отступление слишком далеко.
//
// ЛЕСТНИЦЫ БОЛЬШЕ НЕТ, и вот почему. Бюджет файла убран целиком (решение
// владельца): платим за весь объём хранилища, а не за каждую картинку
// поодиночке — одни выходят мельче ожидаемого, другие крупнее, и в сумме это
// ровно то, что нужно. Без бюджета лестнице нечего ловить: она вся была про
// «не влезло».
//
// Опасение «а вдруг одна картинка займёт гигабайты» снято замером: у формата
// есть свой потолок, и он невысок. Худший мыслимый случай — шум ровно нашего
// целевого размера 3527×2352 (8.3 Мп):
//
//     гауссов шум σ=80, цветной, q90 ...... 8.07 МБ
//     равномерный шум, q90 ................ 8.20 МБ
//     он же при q100 ..................... 21.19 МБ
//
// Восемь мегабайт на картинку, которой в природе не бывает. Реальный максимум
// на выборке владельца (321 файл, шесть каталогов) — 3.58 МБ при медиане 1.44.
// Дистанция, заданная качеством, ограничивает энтропию сверху сама.
//
// Сравнение осталось: оно нужно стендам и наборам — вопрос «насколько эти две
// картинки различаются» никуда не делся.

#pragma once

#include <QImage>

namespace zametti {

// Оценка SSIMULACRA2 между двумя картинками ОДНОГО размера. Шкала CID22: 90 и
// выше — глазом не отличить, 80–90 — очень хорошо, 70–80 — хорошо.
//
// Разные размеры или пустая картинка — возвращает величину меньше −900: это
// «сравнить нельзя», а не «очень плохо», и путать их нельзя.
//
// АЛЬФА. Картинки с прозрачностью сравниваются НЕ КАК ЕСТЬ: под прозрачными
// областями цвет не определён, и SSIMULACRA2 выдаёт бессмыслицу (замер: −403.84
// на прозрачном PNG). Поэтому они сперва накладываются на ровный серый фон —
// одинаковый для обеих, так что сравнение остаётся честным.
double compareSsimulacra2(const QImage& a, const QImage& b);

}  // namespace zametti
