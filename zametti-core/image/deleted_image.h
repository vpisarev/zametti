// ПОСМЕРТНОЕ ПРЕВЬЮ ВЛОЖЕНИЯ.
//
// Вложение, уходящее вместе с удалённой заметкой, не стирается: на его месте
// остаётся мини-версия с пометкой «удалено». Причина устройственная, а не
// сентиментальная — удаление обязано ДОЕХАТЬ до других устройств, а «файла
// нет» доехать не может: чтобы сказать «его больше нет», нужен файл, который
// это говорит. Заодно снимок остаётся узнаваем в рамке «удалено» у слепков
// истории, которые на него ссылаются.
//
// Размер — тот же квадратный бюджет S², что у ввоза, только S берётся из
// `images().maxDeletedImageSize()` (по умолчанию 100, то есть ≤10 000
// пикселей). Апскейла нет: картинка мельче бюджета остаётся собой.
//
// ФОРМАТ ВСЕГДА JXL (решение владельца): писатель у нас ровно один, а метку
// «удалено» обязано нести любое вложение — иначе синхронизация про его смерть
// не узнает. Значит `<id>.webp` превращается в `<id>.jxl`, и старый файл
// уходит; заботой вызывающего.

#ifndef ZAMETTI_DELETED_IMAGE_H
#define ZAMETTI_DELETED_IMAGE_H

#include "import_limits.h"

#include <QByteArray>
#include <QString>

namespace zametti {

// Байты посмертного превью: то же изображение, уменьшенное по правилу площади,
// с меткой zametti:Deleted и ревизией на единицу больше прежней.
//
// limits — обычные пределы ввоза, у которых maxSize подменён на S посмертного
// превью: правило площади и запрет апскейла у них общие, и заводить второе
// такое правило было бы ошибкой.
//
// Пусто — не смогли (не наш формат, битый файл), и тогда причина в error.
// Вызывающему в этом случае остаётся старое поведение: стереть файл.
QByteArray makeDeletedImage(const QByteArray& file, const ImportLimits& limits, QString* error);

}  // namespace zametti

#endif  // ZAMETTI_DELETED_IMAGE_H
