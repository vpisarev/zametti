// Пережатие уже лежащих в хранилище картинок.
//
// ЗАЧЕМ. Настройки импорта не ретроактивны: сменил человек S с 1600 на 2400 —
// уже вставленные картинки от этого не изменятся. Эта команда даёт пройтись по
// хранилищу и привести их к новым числам.
//
// ЭТО ДЕЙСТВИЕ СТРАШНОЙ СИЛЫ, и оно необратимо: выброшенные при уменьшении
// пиксели не вернуть ничем. Поэтому:
//
//   * без --id команда не запускается вовсе; чтобы обработать все картинки,
//     надо явно сказать `--id all` (поправка владельца к брифу). Забыть ключ и
//     переехать всё хранилище одной опечаткой не должно быть возможно;
//   * есть --dry-run, и он показывает ровно то же, что сделал бы настоящий
//     прогон;
//   * в вывод всегда идёт напоминание, что эталонное дерево импорта стоит
//     сохранить, пока не проверил результат глазами.
//
// ИДЕМПОТЕНТНОСТЬ (инвариант D этапа 8): повторный прогон с теми же числами не
// меняет ни байта. Со сдвигом на один прогон: первый может, например,
// перевести webp в JXL, а второй уже не тронет ничего.
//
// Файл перезаписывается ПОД ТЕМ ЖЕ id: ссылки в заметках и слепки в журнале
// остаются целы, а кэш картинок сам заметит смену mtime.

#pragma once

#include "import_limits.h"

#include <QString>
#include <QStringList>

namespace zametti {

struct RecompressOptions {
    QString root;
    // Пусто — команда не работает. "all" — все картинки. Иначе id одной.
    QString id;
    bool dryRun = false;
    ImportLimits limits;
};

struct RecompressReport {
    int examined = 0;
    int rewritten = 0;
    int untouched = 0;
    int failed = 0;
    qint64 bytesBefore = 0;
    qint64 bytesAfter = 0;
    QStringList lines;   // по строке на картинку: что с ней сделали и почему
    QStringList problems;
};

// Возвращает false, если что-то пошло не так; отчёт заполняется в любом случае.
bool recompressStore(const RecompressOptions& options, RecompressReport& report);

}  // namespace zametti
