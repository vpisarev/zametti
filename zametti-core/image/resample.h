// Изменение размера картинки: Lanczos-3 в обе стороны.
//
// Раньше здесь жили два фильтра — усреднение по площади на уменьшение и Lanczos
// на увеличение. Усреднение снято решением владельца (этап 17): на выборке оно
// показало себя хуже, и боевой тракт (ввоз, посмертная мини-версия) давно
// идёт только через Lanczos. Второго пути больше нет, чтобы стенд не мерил не
// то, что работает.
//
// ЗАЧЕМ СВОЙ, а не QImage::scaled. Уменьшение — главная и необратимая потеря
// всего импорта: восстановить выброшенные пиксели потом нельзя ничем. Сглажи-
// вание Qt при сильном уменьшении грубое, и мелкие текстуры мылятся сильнее
// необходимого.
//
// Считаем в float. В линейное пространство НЕ переводим: значения приходят с
// гаммой, и перевод туда-обратно — два лишних прохода по всей картинке.
// Разница на фотографиях мала; если однажды окажется, что она видна глазу, это
// отдельная правка с отдельным замером.

#pragma once

#include <QImage>

namespace zametti {

// Lanczos-3: уменьшение и увеличение. Тот же размер — та же картинка (без
// копирования пикселей); пустой вход или неположительный размер — пустая.
QImage resampleLanczos(const QImage& src, int width, int height);

}  // namespace zametti
