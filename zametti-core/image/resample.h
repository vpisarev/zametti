// Изменение размера картинки. Два разных фильтра на два разных дела.
//
// УМЕНЬШЕНИЕ — усреднение по площади. Каждый выходной пиксель есть точное
// среднее своего следа на входе, с учётом дробного перекрытия по краям. Это
// правильный подавитель наложения: ни одного входного пикселя не теряется, и
// звона на резких границах не бывает вовсе, потому что веса неотрицательны.
//
// ВОССТАНОВЛЕНИЕ — Lanczos-3. При увеличении усреднять нечего, там нужна
// интерполяция, и Lanczos держит резкость лучше билинейного.
//
// Указание владельца, и оно же — обычная практика: у Lanczos отрицательные
// лепестки ядра, и на уменьшении они дают ореолы вокруг контрастных границ.
// В OpenCV по той же причине для уменьшения советуют INTER_AREA, а не
// INTER_LANCZOS4.
//
// ЗАЧЕМ СВОЙ, а не QImage::scaled. Уменьшение — главная и необратимая потеря
// всего импорта: восстановить выброшенные пиксели потом нельзя ничем. Сглажи-
// вание Qt при сильном уменьшении грубое, и мелкие текстуры мылятся сильнее
// необходимого.
//
// Считаем в float. В линейное пространство НЕ переводим: значения приходят с
// гаммой, и перевод туда-обратно — два лишних прохода по всей картинке.
// Разница на фотографиях мала; если однажды окажется, что она видна глазу, это
// отдельная правка с отдельным замером.

#pragma once

#include <QImage>

namespace zametti {

// Уменьшение усреднением по площади. Если запрошенный размер больше исходного
// хоть по одной оси, по ней делается интерполяция — но в конвейере такого не
// бывает: апскейла у нас нет ни на каком пути.
QImage resampleArea(const QImage& src, int width, int height);

// Увеличение Lanczos-3. Годится и для уменьшения, но для него есть
// resampleArea, и пользоваться надо им.
QImage resampleLanczos(const QImage& src, int width, int height);

// Выбирает сам: меньше — площадью, больше — Lanczos. Для случаев, когда
// направление заранее неизвестно.
QImage resample(const QImage& src, int width, int height);

}  // namespace zametti
