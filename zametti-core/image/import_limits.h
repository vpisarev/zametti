// Границы входа и целевой размер: всё, что решается ДО разжатия картинки.
//
// Почему это отдельно от самого импорта. Потому что здесь нет ни Qt, ни
// кодеков — одна арифметика, и она обязана быть проверяемой сама по себе.
// Ошибка тут стоит дороже прочих: пропущенная бомба съедает память до отказа,
// а неверный целевой размер портит все картинки разом и необратимо.
//
// Правило, которое здесь воплощено: РЕШАЕМ ПО ЗАГОЛОВКУ. Размеры картинки
// известны из первых десятков байт файла, и выяснять, что она не влезает,
// после того как под неё выделили гигабайт, — поздно.

#pragma once

#include <cstdint>

namespace zametti {

// Числа из конфига (группа images). Здесь копия, а не ссылка на глобальное
// оформление: этому слою Qt не нужен, а тестам удобно подставлять своё.
struct ImportLimits {
    // S: сторона «квадратного бюджета». Обоснование всех чисел — в
    // app/settings.h, там таблицы замера; здесь только копия умолчаний, чтобы
    // этому слою не требовался Qt.
    //
    // КОПИЯ ОБЯЗАНА СОВПАДАТЬ С ОРИГИНАЛОМ (images.maxImportedImageSize), и это
    // сторожит набор: разъехавшись, копия начинает врать — слой без Qt режет
    // картинки не так, как окно. Один раз они уже разъехались молча.
    int maxSize = 2160;
    int quality = 90;              // lossy JXL
    // ФОРА ТОЧНОЙ ВЕРСИИ: во сколько раз lossless разрешено быть тяжелее lossy,
    // чтобы мы всё-таки взяли точную. Обоснование числа — в settings.h, рядом с
    // настройкой images.losslessThreshold; здесь копия её умолчания, и копия
    // ОБЯЗАНА с ним совпадать — это сторожит набор.
    double losslessThreshold = 1.15;
    int maxBitsPerChannel = 12;    // потолок глубины
    int maxDecodeMemoryMb = 1024;  // потолок памяти под разжатую картинку

    double decodeBudgetBytes() const {
        return static_cast<double>(maxDecodeMemoryMb) * 1024.0 * 1024.0;
    }
};

// Почему вход отвергнут. Не bool: человеку надо сказать, что именно не так, —
// «не вставилось» без причины хуже, чем не вставилось.
enum class Refusal {
    None,
    NoSize,        // читатель не смог назвать размеры
    Empty,         // ноль или отрицательное в заголовке
    SideTooBig,    // сторона больше 65535
    AreaTooBig,    // площадь больше 512 Мп
    TooMuchMemory, // разжатая не влезает в потолок памяти
};

// Жёсткие потолки ЗАЯВЛЕННОГО в заголовке. Числа из брифа этапа 8.
inline constexpr int kMaxSide = 65535;
inline constexpr double kMaxArea = 512.0 * 1000000.0;

// Проверка размеров из заголовка.
//
// ПОЧЕМУ ВСЁ В double, а не в int64. Бриф говорил «в int64», и этого мало
// (замечание владельца). Через QSize размеры приходят как int, и (2^31-1)^2 =
// 4.6e18 в int64 влезает. Но при собственном разборе заголовка они лежат как
// uint32 — а (2^32-1)^2 = 1.84e19, то есть ВДВОЕ больше потолка int64:
// произведение заворачивается, площадь становится отрицательной и проходит
// проверку насквозь. double за 2^53 теряет точность, но НЕ заворачивается, а
// нам нужно лишь сравнение с порогом.
//
// И второй пояс: стороны проверяются РАНЬШЕ площади. После отказа по стороне
// площадь заведомо не больше 65535² = 4.3e9, и тип перестаёт иметь значение.
//
// bitsPerSample — глубина ИСТОЧНИКА: глубокая картинка стоит в памяти вдвое
// дороже, и 16-битный TIFF 6000×4000 просит 183 МБ там, где восьмибитный
// обошёлся бы 92-мя.
Refusal checkSource(int width, int height, int bitsPerSample, const ImportLimits& limits);

// Целевой размер: min(бюджет S², потолок стороны 3S), пропорции сохраняются.
//
// Для соотношения a:1 ширина выходит S·√a, пока a ≤ 9; дальше режет потолок
// стороны — это про ленты и скриншоты переписок. Панорама 3:1 при S=1600
// живёт на бюджете и даёт 2771×924.
//
// АПСКЕЙЛА НЕТ НИ НА КАКОМ ПУТИ: картинка мельче бюджета идёт как есть.
struct Size {
    int width = 0;
    int height = 0;
    bool operator==(const Size& o) const { return width == o.width && height == o.height; }
};

Size targetSize(Size src, const ImportLimits& limits);

// Сколько памяти попросит разжатая картинка. Считается так же, как её меряет
// Qt: четыре канала, вдвое больше при глубине сверх восьми бит.
double decodedBytes(int width, int height, int bitsPerSample);

}  // namespace zametti
