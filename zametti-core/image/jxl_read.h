// Чтение JPEG XL через вендоренную libjxl.
//
// JXL — основной формат хранения картинок zametti, и декод обязан быть
// одинаковым на всех машинах. Дистрибутивный плагин где-то есть, где-то нет,
// где-то другой версии — поэтому читаем сами.
//
// Что читатель обязан донести, помимо пикселей:
//
//   * ГЛУБИНУ. Источник в 10 или 12 бит не имеет права стать восьмибитным по
//     дороге — это была бы потеря, которой никто не просил. Всё, что глубже
//     восьми, читается в шестнадцатибитный формат Qt;
//   * ЦВЕТОВОЕ ПРОСТРАНСТВО. Профиль забирается из потока и ставится картинке.
//     Треть снимков в каталогах владельца — Display P3; молча объявить их sRGB
//     значит переврать цвета;
//   * ПОВОРОТ. JXL несёт ориентацию в заголовке, пронумерованную как в EXIF.
//     Мы её только СООБЩАЕМ; поворачивает тот, кто показывает.

#pragma once

#include "exif.h"

#include <QByteArray>
#include <QImage>
#include <QSize>

namespace zametti {

// Всё, что известно о картинке ДО разжатия пикселей. На этом стоят границы
// входа: они обязаны срабатывать до декода, а не после.
struct JxlHeader {
    QSize size;
    int bitsPerSample = 8;
    bool hasAlpha = false;
    Orientation orientation = Orientation::Normal;
    // Пространство, в котором картинка БЫЛА. Именно оно интересно человеку.
    QByteArray icc;
    // Пространство, в котором декодер отдаёт пиксели. У lossy-файла оно СВОЁ,
    // линейное, и с исходным не совпадает — см. длинный разбор в decodeJxl.
    QByteArray iccOfData;

    bool valid() const { return !size.isEmpty(); }
};

JxlHeader readJxlHeader(const QByteArray& bytes);

// Разжатие целиком. Уменьшать по дороге не просим: наш путь этого никогда не
// делал (обработчик не объявлял ScaledSize, и Qt ужимал уже разжатое), и
// вводить это заодно с переездом значило бы менять две вещи разом.
QImage decodeJxl(const QByteArray& bytes);

// Опознать JXL. Подпись бывает двух видов — голый поток и контейнер ISOBMFF;
// спрашиваем саму libjxl, а не сверяем байты руками: она же потом и читает.
bool looksLikeJxl(const QByteArray& head);

}  // namespace zametti
