#ifndef ZAMETTI_SERIALIZER_H
#define ZAMETTI_SERIALIZER_H

#include "ir.h"
#include "../doc/document_pieces.h"

// Умирающие подписи сборки от представления приезжают вместе с этими:
// потребители у них одни и те же, и менять их до сноса IR незачем.
#include "../doc/ir_bridge.h"

#include <string>
#include <string_view>
#include <vector>

namespace zametti {

// IR → markdown. Вывод всегда канонический: '-' для маркированных списков,
// нумерация с 1, ATX-заголовки, огороженный код.
std::string serialize(const Document& doc);

// Лишние неразрывные пробелы — обычными.
//
// Неразрывный пробел у нас ЗНАЧИМ, но не везде:
//
//   * ведущие держат ОТСТУП — обычный пробел markdown в начале строки съедает;
//   * СЕРИЯ из двух и более в середине держит ВЫРАВНИВАНИЕ («int a␠␠␠= 5»):
//     подряд идущие обычные пробелы markdown схлопывает в один;
//   * ОДИНОЧНЫЙ в середине не значит ничего и приезжает мусором из чужих
//     выгрузок;
//   * В БЛОКЕ КОДА неразрывных не бывает вовсе — ни ведущих, ни прочих: там
//     значим сам пробел, его копируют в терминал, и держать отступ хитрым
//     знаком незачем.
//
// Правило выведено замером по корпусу владельца (274 заметки): ведущих 179,
// одиночных в середине 346, серий — ни одной. Поэтому одиночные в середине
// заменяются обычными, остальные не трогаются.
//
// Живёт в ядре, а не в слое записи, потому что зовут её двое: открытие заметки
// и ввоз чужого .md. Второй о Qt не знает вовсе.
std::string normaliseSpaces(std::string_view text);

}  // namespace zametti

#endif  // ZAMETTI_SERIALIZER_H
