#ifndef ZAMETTI_SERIALIZER_H
#define ZAMETTI_SERIALIZER_H

#include <QString>

namespace zametti {

// Неразрывные пробелы — обычными (решение владельца, 03.09.2026).
//
// В файле U+00A0 НЕ БЫВАЕТ, с одним исключением. Отступы и выравнивание
// («int a␠␠␠= 5») живут ОБЫЧНЫМИ пробелами: пишем как есть, читаем как есть,
// считаем как есть — тот же канон, что у пустых строк (Kind::VSpace).
// Держится это двумя опорами чтения: NOINDENTEDCODEBLOCKS (4+ ведущих
// пробела — не код-блок; код только заборный) и keepDecorativeIndent
// (md4c срезает ведущие — отступ достаётся из сырого исходника); серии в
// середине md4c отдаёт дословно. Плата: маркеры распознаются на любой
// глубине отступа, и писатель экранирует первый значащий знак строки
// (замер — пробник md-spaces).
//
// Всякий приезжающий U+00A0 — наш старый (прежний канон держал им отступы;
// файлы мигрируют сами при первом сохранении) или чужой типографский —
// становится обычным пробелом.
//
// ИСКЛЮЧЕНИЕ (до фазы 2): пустая строка ВНУТРИ ЦИТАТЫ держится одиночным
// неразрывным сразу за «>» — резать цитату пустой строкой нельзя, а другого
// способа выразить её у нынешнего писателя нет. Писатель держит зеркальное
// правило (withNbspThatSurvives), иначе круг файла разошёлся бы.
//
// Живёт в ядре, а не в слое записи, потому что зовут её трое: открытие заметки,
// вставка из буфера и ввоз чужого .md. Текст, не байты: всё, что в памяти, —
// QString, а байты файла переводятся в текст до неё, один раз.
QString normaliseSpaces(const QString& text);

// РАЗДЕЛИТЕЛИ СТРОК ЮНИКОДА (U+2028, U+2029) — ПЕРЕВОДЫ СТРОКИ (решение
// владельца 04.09.2026). В файле заметки они не живут: так пишет Apple Notes,
// так же их вставлял Qt-шный Shift+Enter мимо пометки, — а для заметки это
// перевод строки и ничего больше. Зовёт normaliseSpaces (файл, ввоз, вставка
// разбором) и вставка буквой в букву (replaceRange): все двери — одна.
QString normaliseLineSeparators(const QString& text);

}  // namespace zametti

#endif  // ZAMETTI_SERIALIZER_H
