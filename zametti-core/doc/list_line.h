// СТРОКА ПУНКТА СПИСКА В ИСХОДНИКЕ — одно определение на всех.
//
// Подсветчик (маркер акцентом), правила клавиш режима исходника (Enter
// продолжает пункт, Tab двигает его, Ctrl+D переключает задачу) — все они
// спрашивают одно и то же: «эта строка начинается маркером пункта, и где у него
// что». Пока ответ жил регэкспами внутри подсветчика, второму спрашивающему
// пришлось бы завести свои — и однажды они разошлись бы. Поэтому разбор строки
// живёт здесь, и регэкспов в подсветчике больше нет.
//
// Правила — CommonMark/GFM, как их понимает md4c: отступ из пробелов и табов;
// буллет `-`/`*`/`+` с пробельным знаком за ним; номер из 1..9 цифр с `.` или
// `)` и пробельным знаком; задача — буллет, необязательный один пробел, `[ ]`
// / `[x]` / `[X]` и пробельный знак или конец строки (краткая запись `-[ ]` —
// та же, что у автозамены обычного вида).
//
// Чистые функции над QStringView: виджетов нет, документа нет — ядру так и
// положено, а набор спрашивает их без окна.

#ifndef ZAMETTI_LIST_LINE_H
#define ZAMETTI_LIST_LINE_H

#include "block_kind.h"

#include <QChar>
#include <QString>
#include <QStringView>

namespace zametti {

struct ListLine {
    bool item = false;        // строка начинается маркером пункта
    int indentChars = 0;      // ЗНАКОВ отступа (пробелы и табы) — чтобы резать и класть
    int indent = 0;           // КОЛОНОК отступа (таб — до ближайшего стопа) — чтобы сравнивать
    Marker marker = Marker::Bullet;
    QChar bullet;             // '-', '*', '+' — у буллета и у задачи
    int ordinal = 0;          // у номера
    QChar delimiter;          // '.' или ')' — у номера
    bool checked = false;     // у задачи
    // Индекс знака ЗА маркером: за буллетом, за разделителем номера, за `]`
    // задачи. Ровно то, что красит подсветчик.
    int markerEnd = 0;
    // Индекс первого знака содержимого: markerEnd + 1, если за маркером стоит
    // пробельный знак, иначе markerEnd (задача `- [ ]` в конце строки).
    int contentStart = 0;
    // Колонка содержимого пункта: отступ + ширина маркера + один пробел.
    // Чекбокс задачи НЕ в счёт — в CommonMark он содержимое, а не маркер:
    // вложенный пункт под `- [ ] a` стоит в колонке 2, а не 6 (шесть — это уже
    // блок кода с отступом).
    int contentColumn = 0;
    bool emptyBody = false;   // от contentStart до конца — пусто или одни пробелы
};

// Разбор одной строки исходника (без перевода строки). tabStop — ширина стопа
// табуляции для счёта колонок.
ListLine parseListLine(QStringView line, int tabStop = 4);

// Маркер СЛЕДУЮЩЕГО пункта за этим — то, что Enter ставит на новой строке:
// "- ", "* ", "3. ", "4) ", "- [ ] " (задача продолжается незакрытой, в
// каноничной записи с пробелом). Для не-пункта — пустая строка.
QString nextMarker(const ListLine& line);

// Сколько ведущих знаков строки — пробелы и табы.
int leadingWhitespace(QStringView line);
// Ширина первых chars знаков строки в колонках (таб — до ближайшего стопа).
int columnOf(QStringView line, int chars, int tabStop = 4);
// Строка пустая или из одних пробелов и табов.
bool isBlankLine(QStringView line);

}  // namespace zametti

#endif  // ZAMETTI_LIST_LINE_H
