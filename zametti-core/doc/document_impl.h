// Внутренний интерфейс ZDocument: то, что видят его собственные части, и
// больше никто.
//
// Заголовок нужен потому, что заметка не помещается в один файл: разбор,
// запись, поиск и счёт — разные предметы, и складывать их в document.cpp
// значило бы получить тот самый ком, от которого мы уходим. Каждая часть
// включает ЭТОТ заголовок и реализует свои методы класса.
//
// Наружу отсюда не уходит ничего: в zametti-core он есть, за его пределами —
// нет. Всё, что нужно снаружи, названо в document.h глаголами.

#pragma once

#include "document.h"
#include "note_header.h"

#include <QTextDocument>

namespace zametti {

// ЖИВАЯ МОДЕЛЬ — QTextDocument, и только он. Шапка живёт рядом: в документе её
// нет и быть не должно, редактор её не видит.
struct ZDocument::Data {
    QTextDocument text;
    NoteHeader header;

    Data() {
        // Вёрстка выключена: пока заметку не показывают, считать строки и глифы
        // незачем. Вид включит её сам, когда возьмёт документ себе.
        text.setLayoutEnabled(false);
    }
};

}  // namespace zametti
