// Внутренний интерфейс ZDocument: то, что видят его собственные части, и
// больше никто.
//
// Заголовок нужен потому, что заметка не помещается в один файл: разбор,
// запись, поиск и счёт — разные предметы, и складывать их в document.cpp
// значило бы получить тот самый ком, от которого мы уходим. Каждая часть
// включает ЭТОТ заголовок и реализует свои методы класса.
//
// Наружу отсюда не уходит ничего: в zametti-core он есть, за его пределами —
// нет. Всё, что нужно снаружи, названо в document.h глаголами.

#pragma once

#include "document.h"
#include "formula_object.h"
#include "settings.h"

#include <QTextDocument>

#include <memory>

namespace zametti {

// ЖИВАЯ МОДЕЛЬ — QTextDocument, и только он. Шапки здесь нет: конверт файла
// держит заметка (ZNote), документ — чистое тело .md.
struct ZDocument::Data {
    QTextDocument text;
    // Исходник заметки сейчас правят снаружи (режим правки исходника). Флаг
    // живёт при документе, а не при виде: о нём обязаны знать все, кто заметку
    // правит и записывает.
    bool sourceEditing = false;

    Data() {
        // Вёрстка выключена: пока заметку не показывают, считать строки и глифы
        // незачем. Вид включит её сам, когда возьмёт документ себе.
        text.setLayoutEnabled(false);
        // Вёрстка формул — часть заметки, а не вида: кэш по содержимому живёт
        // здесь и прикреплён к документу (как стиль), обработчик объектов —
        // ребёнок документа. Так формулы рисуются и без окна вовсе (вывоз в
        // PDF из командной строки); условия вёрстки (кегль, цвет, плотность)
        // документу сообщает тот, кто показывает.
        attachFormulaCache(text, std::make_shared<FormulaObjects>());
        registerFormulaHandlers(text);
    }
};

}  // namespace zametti
