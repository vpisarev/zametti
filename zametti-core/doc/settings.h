// их ждёт config.json. Нужен ключу --dump-config: раз приложение конфиг не
// пишет, посмотреть, что вообще можно покрутить, надо как-то иначе.
QByteArray defaultSettingsJson();

// Приводит наш конфиг к строгому JSON: срезает //-комментарии и висячие
// запятые перед } и ]. Ровно две поблажки, и обе — то, что человек пишет
// руками на самом деле. Ни /* */, ни продолжений строк, ни одинарных кавычек:
// каждая следующая вольность — это ещё один способ ошибиться молча.
//
// Внутри строковых литералов не трогается ничего: иначе первый же путь вида
// "https://" молча обрезался бы наполовину. Экранированная кавычка внутри
// строки учитывается. Переводы строк сохраняются все до одного — иначе номера
// строк в сообщении об ошибке разбора указывали бы не туда.
QByteArray stripJsonSugar(const QByteArray& json);

// Текст конфига-шаблона: все параметры со значениями по умолчанию, но целиком
// закомментированные. Файл при этом разбирается в пустой объект — то есть
// «отклонений нет», и философия «конфиг = отклонения» не нарушается. Им
