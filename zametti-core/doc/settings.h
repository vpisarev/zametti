// Действующее оформление. Меняется только при загрузке конфига, на старте.
// НАСТРОЙКИ ПРИЛОЖЕНИЯ — ТОЛЬКО ЧТЕНИЕ. Меняет их загрузчик конфига (здесь же,
// в settings.cpp) и никто больше в боевом коде. Приложение — синглетон, потому
// доступ глобальной функцией, а не полем объекта (решение владельца); имя
// settings(), а не appearance(): облик — лишь один из разделов.
const ZSettings& settings();
// ПРАВКИ НАСТРОЕК В БОЕВОМ КОДЕ НЕТ (решение владельца: ZSettings — только для
// чтения; настройки меняются внешним редактором и перечитываются). Нужен
// другой стиль на время — берётся КОПИЯ (`ZDocStyle paper = settings().style();
// paper.setFontFamily(…)`) и передаётся явно тому, кто её потребляет: сборщику
// (BuildOptions::style), виду (NoteView::setStyle), заметке
// (ZDocument::setStyle). Так делает вывоз на бумагу.
//
// Наборам нужен люк — он объявлен только в tests/settings_hook.h.

// Плашка блока кода в пикселях.
//
// ОДНА НА ВСЕХ, и это главное в ней. Поля блока резервирует сборщик документа,
// а рисует в этом резерве отрисовка; посчитай они высоту полоски каждый
// по-своему — полоска налезала бы на следующий абзац или висела бы под плашкой
// в воздухе. Полоска живёт в НИЖНЕМ поле последней строки блока, воздух под
// скругление — в верхнем поле первой. Из этих же величин складываются левые
// отступы: плашка отодвинута от абзаца на codeIndent, код внутри неё — ещё на
// codePadLeft, и отрисовка находит левый край плашки, вычитая второе из поля.
struct CodePlate {
    qreal strip = 0.0;    // высота полоски снизу (в её правом углу язык и кнопка)
    qreal padTop = 0.0;   // поле сверху — меньше полоски, только под скругление
    qreal padLeft = 0.0;  // отступ кода от левого края плашки
    qreal indent = 0.0;   // отступ самой плашки от отступа абзаца
    qreal radius = 0.0;   // радиус скругления углов
    qreal stripPadding = 0.0;  // поле полоски справа
    qreal langGap = 0.0;       // просвет между именем языка и значком
    qreal iconSide = 0.0;      // сторона значка копирования (от кегля подписи)
};
// Геометрия плашки кода — по ОБЛИКУ и МАСШТАБУ; без аргументов — по облику
// настроек в масштабе 1.
//
// МАСШТАБ ЗДЕСЬ НЕ УКРАШЕНИЕ, НО И НЕ ВСЕСИЛЕН. Документ собирается один раз в
// пикселях базового кегля, а зум — это setDefaultFont: текст растёт, а поля
// блоков остаются, и в НИЖНЕМ ПОЛЕ живёт полоска. Переписать поля под масштаб
// нельзя: всякая запись формата — шаг в стеке отмены (замерено; по той же
// причине вид центрирует колонку полями вьюпорта, а не документа), а Ctrl+=
// правкой не является.
//
// Поэтому полоска остаётся высотой резерва, а её содержимое — подпись языка и
// значок копирования — растёт с масштабом, пока в этот резерв помещается (см.
// NoteView::plateScale). Владелец увидел прежнее поведение как «размер шрифта
// языка блока кода не масштабируется с зумом»; полный рост плашки требует
// другого резерва (объектом, как таблица и формула) — назван долгом в
// known_bugs.md.
CodePlate codePlate(const ZDocStyle& style, qreal scale = 1.0);
inline CodePlate codePlate() { return codePlate(settings().style()); }

// Шрифт имени языка в полоске: своя гарнитура и кегль из стиля, умноженный на
// масштаб показа. От него же считаются высота полоски и значок (codePlate).
QFont codeLangFont(const ZDocStyle& style, qreal scale = 1.0);
QFont codeLangFont();


// КАТАЛОГ НАШЕГО ХОЗЯЙСТВА — ОДИН ОТВЕТ НА ВЕСЬ ПРОЕКТ. Здесь лежат
// config.json, state.json, бухгалтерия синка и оба журнала (err.log,
// sync.log). Раньше это место спрашивали у QStandardPaths ПЯТЬ разных файлов,
// и разошлись бы они первой же правкой.
//
// ЗАЧЕМ ЕЩЁ — ИЗОЛЯЦИЯ НАБОРОВ, И ЭТО НЕ УДОБСТВО. Наборы обязаны не видеть
// конфиг владельца (настройки — его пожелания, и набор, увидевший их, проверяет
