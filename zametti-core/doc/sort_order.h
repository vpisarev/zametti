// Порядок сортировки заметок: чем меряем и в какую сторону.
//
// Отдельным крошечным модулем, потому что величина эта ходит по всей программе
// и в трёх видах сразу: перечислением внутри (дерево, список), строкой в шапке
// папки (`sort: created-desc`) и строкой в state.json. Разбор и запись обязаны
// быть ОДНИ: разойдись они — папка с меткой читалась бы иначе, чем писалась, и
// узнали бы мы об этом только от владельца.
//
// Модуль чистый: ни моделей, ни виджетов, ни файлов. Поэтому круг «строка →
// порядок → строка» проверяется набором целиком, включая чужие и битые
// значения.

#ifndef ZAMETTI_SORT_ORDER_H
#define ZAMETTI_SORT_ORDER_H

#include "note_header.h"

#include <QString>
#include <QStringView>

#include <optional>

namespace zametti {

// Чем меряем. Три ключа, и третий — главное приобретение этапа 13: дневник
// упорядочен ТОЛЬКО датой создания. Имя не годится (заголовки вида «12 августа
// 2026г» без ведущих нулей), правка не годится тем более — опечатка в
// прошлогодней записи телепортирует её наверх.
enum class SortKey {
    Name,       // заголовок, с учётом языка и чисел
    Modified,   // последняя правка; у папки — самая свежая в поддереве
    Created,    // дата создания из шапки: единственная неподвижная хронология
};

struct SortOrder {
    SortKey key = SortKey::Modified;
    // Направление задаётся ОДНИМ признаком на все три ключа, и слово «вверх»
    // значит для них разное: у имени это A→Z, у дат — сначала старые. Чтобы
    // человек не гадал, наружу оно выходит только человеческим названием
    // (sortOrderTitle), а числом живёт здесь.
    bool ascending = false;

    bool operator==(const SortOrder& other) const {
        return key == other.key && ascending == other.ascending;
    }
    bool operator!=(const SortOrder& other) const { return !(*this == other); }
};

// Направление по умолчанию для ключа: имя — по возрастанию, даты — новые
// сверху. Это то, что человек получает, впервые нажав кнопку (бриф этапа 13).
bool defaultAscending(SortKey key);
SortOrder defaultOrder(SortKey key);

// Значение для шапки папки и для state.json: "name-asc", "created-desc", ...
QString sortOrderToString(SortOrder order);

// Разбор. Пусто — ключа нет вовсе (не ошибка). Неизвестное значение — тоже
// пусто, и это НАРОЧНО: хранилище правится чужими руками и синхронизируется, и
// метка из будущей версии не должна ни ронять программу, ни молча
// подменяться — папка просто наследует порядок, как если бы метки не было.
// Жалобу пишет вызывающий: модулю некуда.
std::optional<SortOrder> parseSortOrder(QStringView text);

// Человеческое название целиком: «По дате создания, новые сверху». Идёт и в
// тултип кнопки, и в подсказку строки.
QString sortOrderTitle(SortOrder order);

// ЧТО ЗНАЧИТ НАЖАТИЕ КНОПКИ. Нажали кнопку другого ключа — включаем его в
// направлении по умолчанию; нажали кнопку действующего — переворачиваем
// направление. Отжать нельзя: сортировки «никакой» не бывает.
//
// Правило отдельной чистой функцией, а не тремя строчками в обработчике: оно
// перебирается набором целиком (три ключа × шесть состояний), и разойтись с
// кнопками ему негде.
SortOrder pressedSort(SortOrder now, SortKey pressed);

// Метка в шапке заметки-папки: поставить или (пустой order) убрать. Ключ
// `sort`, значение — sortOrderToString.
//
// Правит ТОЛЬКО свой ключ: неизвестные строки шапки переживают правку
// дословно (это forward compatibility формата), а `modified` не трогается
// вовсе — пометка порядка не редактирование содержимого, и всплывать наверх
// списка папка от неё не должна (правило этапа 7).
void applySortMark(NoteHeader& header, std::optional<SortOrder> order);

}  // namespace zametti

#endif  // ZAMETTI_SORT_ORDER_H
