// Сколько в заметке слов и строк и на какой строке каретка.
//
// Считаем ПО IR и только в те мгновения, когда IR и так строится целиком:
// автосохранение и полная пересборка документа. Оба и без нас стоят миллисекунды,
// и счёт в них тонет. На нажатие клавиши не считается ничего: статистика —
// вторичная выдумка, тормозить из-за неё набор недопустимо.
//
// Почему по IR, а не по документу: замер на заметке в 239 КБ (RelWithDebInfo,
// taskset -c 0) — обход QTextDocument стоит 3.2 мс, из них 1.2 мс уходит на
// QString на каждый блок и 1.1 мс на распознавание фотографий; по IR текст
// лежит сплошным UTF-8, и те же числа выходят втрое дешевле. Для сравнения:
// документ→IR 4.3 мс, IR→файл 2.5 мс, IR→документ 19 мс.
//
// Обход документа остался — documentStats. Он не запасной путь, а ЭТАЛОН: тем
// же самым числам, посчитанным двумя разными способами, положено совпадать, и
// набор сверяет их на всём корпусе владельца.
//
// Что считается словом — см. countWords. Что считается строкой — см. NoteStats.

#ifndef ZAMETTI_TEXT_STATS_H
#define ZAMETTI_TEXT_STATS_H

#include "document_pieces.h"

#include <QStringView>

#include <vector>

class QTextBlock;
class QTextCursor;
class QTextDocument;

namespace zametti {

// Слова в куске текста.
//
// Слово — непрерывная цепочка букв и цифр. Всё остальное слова разделяет:
// "3.14" — два слова, "по-русски" — два, "don't" — два. Это нарочно: правило
// без исключений одинаково честно к русскому, английскому и к строке кода, а
// любая попытка угадать «внутрисловный дефис» упирается в язык.
//
// Единственное исключение — знаки, которых на экране нет самих по себе:
// комбинирующие (Mn, Mc, Me — умляуты, краткие, подчёркивания) и невидимые
// служебные (Cf — мягкий перенос, соединители эмодзи). Они не буквы и не
// цифры, но и не разделители: "и" + U+0306 — это "й", одно слово, а не два.
//
// Суррогатные пары разбираются: буквы за пределами BMP считаются буквами.
int countWords(QStringView text);


// Строки в куске текста ЗА ВЫЧЕТОМ первой: сколько раз текст переведён на
// новую строку внутри одного блока. Перевод внутри блока — U+2028 (см.
// BreakSource в doc_model.h): абзац из трёх строк исходника это один блок с
// двумя такими знаками.
int countLineBreaks(QStringView text);

// Слова и переводы строк одного блока. Блок с фотографией — ноль слов: путь к
// файлу и подпись вложения словами заметки не являются.
struct BlockStats {
    int words = 0;
    int breaks = 0;    // переводов строки ВНУТРИ блока; всего строк — breaks + 1
    bool image = false;   // блок занят фотографией
};
BlockStats blockStats(const QTextBlock& block);

// Сводка по всей заметке. Строк всегда хотя бы одна: пустой документ — это
// одна пустая строка, а не ноль строк.
//
// Строка — это строка ФАЙЛА, а не абзац и не то, что вышло из переноса по
// ширине окна. Мягкий перенос внутри абзаца (Shift+Enter, многострочный абзац
// исходника) строку начинает: на экране он выглядит новой строкой, и не считать
// его было бы враньём. В корпусе владельца такие переносы — 4.6% всех строк, а
// в одной заметке из 274 их 84%, так что «строка = блок» ошибалась бы заметно.
struct NoteStats {
    int words = 0;
    int lines = 1;
    // Блоков в документе, который собрался бы из этого IR. Не для показа:
    // сверять с QTextDocument::blockCount() — самая дешёвая проверка того, что
    // счёт по IR разошёлся с документом.
    int blocks = 1;
    // Фотографий в заметке. Слова в них не считаются (путь к файлу и подпись —
    // не слова заметки), но сказать, что они есть, надо: картинка стоит тысячи
    // слов, а в счёте слов она стоит нуля.
    int images = 0;

    // Где внутри блоков стоят мягкие переносы. Только блоки, в которых они
    // есть: в заметке на 4182 блока таких 96, а в половине заметок ни одного.
    // Без этого номер строки каретки стоил бы обхода всего документа.
    struct Mark {
        int block;    // номер блока документа
        int before;   // переносов во ВСЕХ блоках до него
    };
    std::vector<Mark> marks;

    bool valid = false;   // считали ли вообще
};

// ВТОРОЙ СУДЬЯ, А НЕ РАБОЧИЙ ПУТЬ (комментарий отстал от кода: программа
// считает documentStats — и окно, и ZDocument::getStats).
// Счёт по ЛОГИЧЕСКИМ БЛОКАМ, как их отдал разбор, — то есть по второму пути,
// независимому от обхода живого документа. В этом весь смысл: два счёта,
// сошедшиеся из разных мест, и есть проверка, а расхождение объявляет счёт
// неизвестным. Однажды оно нашло живую беду, и терять второго судью нельзя.
NoteStats pieceStats(const std::vector<Piece>& blocks);

// Номер строки каретки и знак в ней, оба с единицы. Считается по указателю
// строк: два двоичных поиска и проход по текущему блоку, документ целиком не
// трогается.
//
// Между пересчётами указатель отстаёт: набранный только что мягкий перенос в
// нём ещё не значится. Ошибиться номер может лишь на число переносов, которые
// человек успел набрать с прошлого пересчёта, — и не дольше, чем до ближайшего
// автосохранения.
struct CaretPlace {
    int line = 1;
    int column = 1;
};
CaretPlace caretPlace(const NoteStats& stats, const QTextCursor& caret);

// ЧИСЛА ОБХОДОМ ЖИВОГО ДОКУМЕНТА — рабочий путь: так считают и окно, и
// ZDocument::getStats.
NoteStats documentStats(const QTextDocument& doc);

}  // namespace zametti

#endif  // ZAMETTI_TEXT_STATS_H
