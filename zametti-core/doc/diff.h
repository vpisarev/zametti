// Разность двух версий заметки. Чистая логика, без виджетов: проверяется без
// дисплея, а рисуют по ней и вид «как под капотом», и вид с полосками на поле.
//
// ЕДИНИЦА СРАВНЕНИЯ — СТРОКА КАНОНИЧЕСКОГО MARKDOWN. Не блок и не слово:
// строка — это то, что человек правит и что он видит в файле, и оба вида
// диффа обязаны говорить об одном и том же. Канонического — потому что обе
// стороны прогоняются через наш сериализатор: разница в оформлении (звёздочка
// против дефиса в списке) не является изменением заметки, и показывать её как
// изменение было бы враньём.
//
// МЕТА В СРАВНЕНИЕ НЕ ИДЁТ. В шапке живёт строка modified, она меняется при
// каждой записи — и всякий дифф начинался бы с «изменилась одна строка», всегда
// одна и та же. Тем же правилом живёт восстановление слепка (оно сравнивает
// тела) и чистка истории.
//
// АЛГОРИТМ ЧУЖОЙ — dtl, Майерс (3rdparty/dtl). Своя реализация была бы либо
// наивной динамикой с квадратом по памяти, либо месяцем работы.

#ifndef ZAMETTI_DIFF_H
#define ZAMETTI_DIFF_H

#include "document_pieces.h"

#include <QHash>
#include <QString>
#include <QStringList>
#include <QVector>

#include <string>
#include <string_view>

namespace zametti::diff {

// Что стало со строкой.
//
// Changed — не выдумка поверх «удалили и добавили», а то, как человек это
// видит: строку правили, она осталась на месте. Пара «удалено + добавлено» в
// одном месте и есть правка строки; лишнее сверх пары остаётся удалением или
// добавлением.
enum class Mark { Same, Added, Removed, Changed };

// Строка сравнения. Держит ОБЕ стороны сразу: по Alt показывается вторая, и
// перебирать сравнение заново ради этого нельзя — мигать должно мгновенно.
struct Row {
    Mark mark = Mark::Same;
    int before = -1;   // номер строки в базе; -1 — её там нет
    int after = -1;    // номер строки в слепке; -1 — её там нет
    QString textBefore;
    QString textAfter;
};

struct Result {
    QVector<Row> rows;
    int changed = 0;   // строк тронуто: добавлено + удалено + изменено
    // Те же строки по сторонам — как `git diff --numstat`: изменённая строка
    // это одна убранная и одна добавленная, поэтому считается в обе. Баннеру
    // истории нужны именно они: «+m/−n» читается, «±k» — нет (владелец).
    int added = 0;     // строк, которых нет в базе (Added + Changed)
    int removed = 0;   // строк базы, которых нет в слепке (Removed + Changed)
    bool identical() const { return changed == 0; }

    // Номера тронутых строк СЛЕПКА (сторона after). Ими сверяются два вида:
    // расхождение множеств — баг соответствия «строка ↔ блок», а не мелочь
    // оформления.
    QVector<int> changedAfterLines() const;
};

Result compare(const QStringList& base, const QStringList& shown);

// Строки сравнения из БАЙТОВ ФАЙЛА (слепок журнала, свежая версия): шапка
// отбрасывается, тело приводится к канону и режется по '\n'; хвостовой пустой
// строки нет — текст кончается переводом строки, строкой файла эта пустота не
// является. Единственный путь «байты → строки сравнения»: и слепок, и база, и
// свежая версия идут через него, иначе разница в оформлении однажды сойдёт
// за изменение.
QStringList linesOf(std::string_view fileBytes);
// Каноническое тело тех же байт (без шапки) — то, что восстанавливается.
std::string bodyOf(std::string_view fileBytes);

// Текст слепка построчно плюс карта блоков: какие строки занял каждый
// логический блок.
struct Text {
    QStringList lines;
    QVector<BlockLines> blocks;   // по логическому блоку, в том же порядке
};
Text textOf(const std::vector<Piece>& blocks);

// Разметка для вида с полосками: что стало с каждым БЛОКОМ ПОКАЗАННОЙ стороны
// (стороны after этого сравнения) и сколько строк на ней не хватает.
//
// Блок тронут, если тронута хоть одна его строка: полоска на поле отвечает на
// вопрос «сюда смотреть?», а не «сколько именно тут поменялось».
//
// СТОРОНА ЗАДАЁТСЯ САМИМ СРАВНЕНИЕМ, а не флажком. Показываем базу — значит и
// сравнение берём обратное (`compare(слепок, база)`), и тогда зелёное всегда
// значит «есть здесь и нет у соперника», а красное — наоборот, с какой бы
// стороны человек ни смотрел. Решение владельца: «нажимаем TAB — сравнение
// идёт в противоположном направлении, что было зелёным, становится красным».
// Два прогона DTL вместо одного стоят 9 мс на самой большой заметке и
// считаются один раз на слепок.
struct BlockMarks {
    QVector<Mark> blocks;          // Same / Added / Removed / Changed по блокам
    QHash<int, int> gapBefore;     // перед блоком N нет столько строк
    int gapAtEnd = 0;              // и столько — после последнего блока
};
BlockMarks blockMarks(const Result& result, const QVector<BlockLines>& blocks);

}  // namespace zametti::diff

#endif  // ZAMETTI_DIFF_H
