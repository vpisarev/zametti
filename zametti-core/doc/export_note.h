// Отдать заметку наружу: markdown с картинками или PDF.
//
// Экспорт — это НЕ копия файла хранилища. В хранилище всё устроено удобно для
// программы: имя заметки — четырнадцать знаков идентификатора, вложения лежат
// в общей плоской куче рядом с заметками. Человеку наружу нужно другое: файл
// назван так, как заметка называется, а картинки лежат рядом с ним.
//
// Отсюда три правила.
//
// ИМЯ — ИЗ ЗАГОЛОВКА. То же имя, которое человек видит в средней колонке,
// причёсанное до того, что выдержит любая файловая система. Причёсывание
// смотрит не только на текущую (в ext4 запрещён один знак — '/'), а на все
// разом: экспортированный файл для того и делают, чтобы отдать его дальше.
//
// КАРТИНКИ СОХРАНЯЮТ ИМЕНА, но чужие файлы не гибнут. Имя вложения — свежий
// id, столкнуться оно может ровно с прошлым вывозом той же картинки. Поэтому
// сперва сверяем содержимое: совпало побайтово — файл уже на месте, копировать
// нечего. Не совпало — заводим соседнее имя, а ссылку в markdown правим.
//
// ССЫЛКУ ПРАВИМ ЧЕРЕЗ IR, А НЕ ПОИСКОМ ПО БАЙТАМ. Замена подстроки в файле
// нашла бы имя и внутри блока кода, и внутри обычного текста. Но круг
// «разобрать — собрать» побайтово точен не на всяком входе (три давних красных
// фаззера ровно про это), поэтому он и не делается просто так: пока
// переименовывать нечего, файл копируется байт в байт. А когда всё-таки надо —
// круг сперва ПРОВЕРЯЕТСЯ на этой самой заметке, и только если он сошёлся,
// заметка пересобирается. Не сошёлся — вывоз отменяется с внятным отчётом,
// потому что молча отдать наружу не то, что лежит в хранилище, нельзя.

#ifndef ZAMETTI_EXPORT_NOTE_H
#define ZAMETTI_EXPORT_NOTE_H

#include <QString>
#include <QStringList>

namespace zametti {

// Что вышло. Пустой error — вышло; иначе не создано ничего (см. ниже про
// незавершённый вывоз).
struct ExportReport {
    QString error;            // непусто — не вышло
    QStringList notes;        // что стоит сказать человеку: переименования, пропажи
    int imagesCopied = 0;     // сколько вложений легло рядом
    int imagesReused = 0;     // сколько уже лежало там же и совпало побайтово
    int imagesMissing = 0;    // на сколько заметка ссылается, а файла нет
    int pages = 0;            // страниц вышло (у PDF; у markdown ноль)
    // НА КАКОЙ ШИРИНЕ СВЁРСТАНО и какова ширина полосы набора страницы. Числа
    // диагностические, но не праздные: они обязаны совпадать. Разошлись — часть
    // строк не влезла в страницу, и её отсекло уже при отрисовке. Именно так
    // строки и обрезались на полуслове, а по самому PDF этого не видно: глифы в
    // файл попадают все, их режет отсечение (pdftotext показывает целый текст).
    qreal layoutWidth = 0.0;
    qreal pageWidth = 0.0;

    bool ok() const { return error.isEmpty(); }
};

// Заголовок заметки → имя файла без расширения. Пустой заголовок превращается
// в «Без названия»: файла без имени не бывает.
QString fileNameFromTitle(const QString& title);

// Что подставить в диалог вывоза: ПОЛНЫЙ путь, а не одно имя.
//
// QFileDialog::selectFile с относительным именем ставит файл в каталог по
// умолчанию, а не в тот, что задан диалогу: каталог сбрасывался на «Документы»
// и при открытии диалога, и при каждой смене формата (нашёл владелец). Правило
// записано функцией, чтобы у обоих мест — открытия и смены фильтра — оно было
// одно.
QString exportTargetPath(const QString& dir, const QString& base, bool paper);

// Вывезти заметку как markdown. targetPath — полный путь к .md, каталог обязан
// существовать. Картинки ложатся в тот же каталог.
//
// keepMeta — «сохранять имя и метаданные» (галочка диалога, этап 15):
//
//   false (по умолчанию) — наружу уезжает ЧИСТЫЙ markdown: шапка `<!-- zametti
//     … -->` срезается, имя файла человеческое, из заголовка. Так вывозят, чтобы
//     отдать текст кому-то, кто про zametti не знает вовсе;
//   true — файл уезжает как есть, с шапкой, и зовётся `<id>.md`. Такой файл,
//     положенный в чужое хранилище zametti, приезжает туда со своей историей
//     происхождения: `parent` в нём чужой, и заметка попадает в бюро находок.
//     Это и есть обмен заметками без всякой share-механики.
//
// Шапка срезается БАЙТОВОЙ хирургией, а не пересборкой документа: пересборка
// заметки, у которой круг «разбор → запись» не сходится (а такие в хранилище
// есть), подменила бы человеку текст молча.
ExportReport exportMarkdown(const QString& notePath, const QString& targetPath,
                            bool keepMeta = false);

}  // namespace zametti

#endif
