// Что показывает режим истории — и почему это НЕ сам слепок.
//
// АРХИТЕКТУРА (решение владельца). Два markdown'а — абсолютная истина: либо
// «текущая версия и запись N», либо «запись N и N−1». Они разбираются в IR,
// сравниваются DTL в обе стороны — и на этом их роль кончается: ходьба по
// истории их не трогает вовсе, они лежат отдельно и неизменны.
//
// Показываем мы ВСЕГДА ИЛЛЮСТРИРОВАННУЮ КОПИЮ: полную копию IR слепка, в
// которую дорисовано наше — вспомогательные строки «удалено: N строк», а
// дальше по мере надобности цветные спаны, плюсы и минусы на полях, подсветка
// изменённых слов. Из копии строится QTextDocument, по нему идут показ, Tab и
// поиск.
//
// Отсюда главное свойство: то, что человек ВИДИТ, и то, что программа МОЖЕТ
// ЗАПИСАТЬ, — разные объекты, и перепутать их негде. Восстановление берёт
// исходный слепок; иллюстрированная копия на диск не уходит ни по какому пути.
//
// Обещаний тут мало было бы: подпись «удалено: 2 строки» уже нашлась однажды
// посреди живой заметки владельца — тогда показывался сам слепок, в который
// заглушки вставлялись блоками, и запись при выходе унесла их на диск.

#ifndef ZAMETTI_DIFF_VIEW_H
#define ZAMETTI_DIFF_VIEW_H

#include "diff.h"

#include <QString>
#include <QVector>

class QTextDocument;

namespace zametti::diff {

// «удалено: 3 строки» — с правильным окончанием.
//
// ПОДПИСЬ ОДНА НА ОБЕ СТОРОНЫ, и это не упрощение, а единственный честный
// вариант. Пропуск всегда значит одно: ЗДЕСЬ ЭТИХ СТРОК НЕТ, у соперника они
// есть. Он и красный — красное у нас ровно об этом. Была у меня попытка
// подписывать пропуск на старой стороне «добавлено: N строк» — владелец
// справедливо сказал, что такого в диффе быть не может: добавленные строки
// показывают сами себя зелёным, а не пустотой красным.
QString gapLabel(int lines);

// Иллюстрированная копия слепка: то, что показывается.
struct Illustrated {
    Document ir;               // копия слепка плюс вспомогательные блоки
    QVector<Mark> blockMark;   // метка каждого блока ЭТОЙ копии, по порядку
    // Откуда взялся блок копии: номер блока ИСХОДНОГО слепка или -1 у
    // дорисованного. Без этой карты не найти, какой строке слепка отвечает
    // блок на экране: у копии номера свои, и всё, что ниже дорисовки, съезжает.
    QVector<int> sourceBlock;
};

// Собрать копию: исходный слепок не меняется ни на байт (он передан по
// константной ссылке и копируется целиком, вместе с ареной).
Illustrated illustrate(const Document& snapshot, const BlockMarks& marks);

// Собрать документ вида «как под капотом» — тоже отдельный артефакт, не слепок:
// в нём строки сравнения, включая те, которых в показанной версии нет.
// markOfBlock заполняется по номерам блоков.
void buildPlainDocument(const Result& result, QTextDocument& target,
                        QVector<Mark>* markOfBlock);

}  // namespace zametti::diff

#endif  // ZAMETTI_DIFF_VIEW_H
