// Поиск по тексту заметок.
//
// Главное правило: поиск видит ровно то, что видит человек. Искомая единица —
// текст блока живого документа, то есть содержимое без маркеров разметки;
// метаданные не ищутся вовсе (их в документе нет — они живут в шапке заметки),
// синтаксис эмфазиса не ищется (в тексте блока его уже нет). Совпадение не
// пересекает границу блока: это осознанное ограничение, а не недосмотр — блок и
// есть единица текста. ОБЪЕКТЫ (таблица, формула) ищутся ПО ИСХОДНИКУ (решение
// владельца, сессия 5): «gamma» найдёт \gamma, слово в ячейке — ячейку.
//
// Сам поиск — глаголы заметки: ZDocument::find и ZDocument::hitLine. Здесь
// только то, чем спрашивают и что отвечают.
//
// Виджетов здесь нет намеренно: поиск гоняется в тестах без дисплея и
// исполняется в отдельном потоке, где виджетам делать нечего.

#ifndef ZAMETTI_SEARCH_H
#define ZAMETTI_SEARCH_H

#include <QRegularExpression>
#include <QString>

#include <functional>
#include <vector>

class QTextBlock;
class QTextDocument;

namespace zametti {

// Кусок текста, занятый объектом (строчная формула) — из doc_model.h. Здесь
// нужен только указателем, поэтому заголовок целиком не тянем: search.h входит
// в document.h, а тот — почти всюду.
struct ObjectSpan;

// Smart case: запрос целиком в нижнем регистре — ищем без учёта регистра;
// есть хоть одна заглавная — с учётом. Сравнение юникодное, через QString:
// наивный ASCII-tolower не знает про кириллицу, и «Дом» не находил бы «дом».
//
// РЕГУЛЯРНОЕ ВЫРАЖЕНИЕ — тот же запрос, только с поднятым признаком: словарь
// поиска один, и признак доезжает до всех, кто ищет (заметка, исходник,
// хранилище, история), сам собой. Выражение разбирается ЗДЕСЬ И ОДИН РАЗ:
// собирать его на каждом блоке значило бы платить разбором за каждый блок
// заметки.
struct Query {
    QString needle;
    bool caseSensitive = false;
    bool regex = false;
    // Разобранное выражение; годно только при regex && valid.
    QRegularExpression pattern;
    // Выражение разобралось. У обычного запроса всегда истина: годным его
    // делать нечему. Ложь — человек ещё дописывает скобку, и это НЕ ошибка,
    // а промежуточное состояние набора: искать нечего, сказать нечего,
    // панель красит буквы запроса и ждёт дальше.
    bool valid = true;

    bool isEmpty() const { return needle.isEmpty(); }
    // Есть что искать: запрос непуст и (если это выражение) разобрался.
    bool usable() const { return !isEmpty() && valid; }
    // Шумовой порог: один знак находится в каждой второй заметке, толку от
    // такого списка нет.
    bool tooShort() const { return needle.size() < 2; }
    Qt::CaseSensitivity sensitivity() const {
        return caseSensitive ? Qt::CaseSensitive : Qt::CaseInsensitive;
    }
};

Query makeQuery(const QString& text, bool regex = false);

// Совпадение внутри одной заметки.
struct Hit {
    int block = 0;      // номер блока в документе
    int offset = 0;     // смещение в тексте блока (или в исходнике объекта), в QChar
    int length = 0;
    int ordinal = 0;    // какое это совпадение по счёту в заметке, с нуля
    // Совпадение ВНУТРИ ОБЪЕКТА (таблица, формула): в тексте блока стоит один
    // U+FFFC, а offset/length — смещения в его исходнике (searchableTextOf).
    // Подсветку такого совпадения рисует вид поверх объекта, замену делает
    // rewriteObjectSource.
    bool inObject = false;
};

// МЕСТО ОДНОГО ВХОЖДЕНИЯ В ЖИВОМ ДОКУМЕНТЕ — всё, из чего каждый спрашивающий
// строит своё: ZDocument::find — Hit, NoteSearch — курсор, замена — правку.
struct HitPlace {
    int blockIndex = 0;
    const QTextBlock* block = nullptr;
    // Текст, по которому искали: у объекта — исходник, мягкие переносы
    // приведены к переводу строки (см. forEachHit).
    const QString* text = nullptr;
    // Строчные объекты этого блока (формулы), если они в нём есть.
    const std::vector<ObjectSpan>* objects = nullptr;
    bool inObject = false;   // весь блок — объект (таблица, выключная формула)
    int span = -1;           // номер строчного объекта или −1
    int offset = 0;          // в text
    int length = 0;
    // Совпадение целиком — только в режиме выражения; нужно замене, чтобы
    // развернуть группы. Вне его пусто.
    const QRegularExpressionMatch* match = nullptr;
};

// ВХОЖДЕНИЯ ЗАПРОСА В ЖИВОМ ДОКУМЕНТЕ — ОДИН ОБХОД НА ВСЕХ.
//
// Правил тут больше, чем кажется: текст берётся у объекта исходником, мягкий
// перенос приводится к переводу строки (иначе якоря выражения зависели бы от
// того, чем перенос записан), вхождение через границу объекта не считается,
// пустое совпадение не считается тоже, а шаг идёт через длину найденного —
// перекрывающихся вхождений у нас нет. Пока это было написано трижды (поиск по
// заметке, кэш поиска вида, замена по всей заметке), правила успевали
// разойтись: счётчик считал перекрытия, а замена — нет.
//
// sink возвращает ложь — обход прекращается (заголовок заметки спрашивают, не
// дочитывая её до конца).
void forEachHit(const QTextDocument& doc, const Query& query,
                const std::function<bool(const HitPlace&)>& sink);

// Вхождения в ПЛОСКОМ тексте (вид исходника, поиск по хранилищу в режиме
// markdown): тот же счёт вхождений и те же правила про пустое и про шаг, но
// без блоков и объектов. Отдаёт пары «смещение, длина».
struct FlatHit {
    int offset = 0;
    int length = 0;
    QRegularExpressionMatch match;
};
// limit > 0 — остановиться, набрав столько вхождений; capped (если спросили)
// скажет, что остановились по потолку, а не потому, что текст кончился.
std::vector<FlatHit> findInText(const QString& text, const Query& query, int limit = 0,
                                bool* capped = nullptr);

// ЗАМЕНА: развернуть шаблон по совпадению.
//
// В обычном поиске замена БУКВАЛЬНА — «$1» это доллар и единица, и никак иначе:
// человек, меняющий «цена $1» на «цена $2», не должен получать сюрприз. Группы
// разворачиваются только у выражения:
//
//   $1…$9, ${12}, \1…\9 — обе записи (владелец: годится любая); $0 и $& — всё
//     совпадение; группы, которой не было в совпадении, — пустота, как в perl;
//   \U … \E — верхний регистр до конца или до \E, \L … \E — нижний,
//   \u и \l — одна следующая буква,
//   \n, \t — перевод строки и таб; \$ и \\ — сами знаки.
QString expandReplacement(const Query& query, const QRegularExpressionMatch& match,
                          const QString& tmpl);

// Строка с совпадением для списка результатов: сама строка блока, обрезанная
// по краям, и место совпадения внутри неё (для подсветки).
struct HitLine {
    QString text;
    int offset = 0;
    int length = 0;
};

// То же для ПЛОСКОГО текста (поиск по хранилищу в режиме markdown): правило
// одно с ZDocument::hitLine — строка вокруг совпадения, многоточия по краям,
// длина подсветки прижата к показанной строке.
HitLine hitLineInText(const QString& text, int offset, int length, int radius = 48);

}  // namespace zametti

#endif  // ZAMETTI_SEARCH_H
