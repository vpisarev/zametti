// Картинка, которую блок просит показать. Модель текста об этом не знает:
// блок остаётся обычным абзацем, а фотография — дело вида, как линия у
// черты. Распознаются две формы: image-спан целым абзацем (ширина — из
// "#w=N" в пути, если есть) и вики-вложение "![[путь]]"/"![[путь|ширина]]",
// которое модель хранит дословным текстом.
// ImageAlign живёт в block_kind.h — рядом с родом и маркером.

struct BlockImageRef {
    QString path;
    QString alt;             // подпись; у вики-вложения её нет
    qreal widthHint = 0.0;   // 0 — своя ширина картинки; логические пиксели
    ImageAlign align = ImageAlign::Center;
    bool wiki = false;       // форма записи: вики-вложение или image-спан
    bool valid = false;

    // Подпись, которую показывают под снимком: пусто у вики-вложения и у
    // безымянной подписи (см. isNonameCaption). В файл всегда уходит alt.
    QString shownCaption() const;
};

// БЕЗЫМЯННАЯ ПОДПИСЬ — та, что под снимком не показывают (решение владельца,
// 17.08.2026: «хорошие имена показывать, дурацкие скрывать/переименовывать в
// то, что не показывается»). Безымянной подпись делают три вещи:
//   * она пуста (или одни пробелы);
//   * она СПРЯТАНА человеком одним знаком спереди — «~подпись» или «-подпись».
//     Знак не портит надпись и даёт её вернуть: убрал знак — подпись видна.
//     На этом стоит клавиша «спрятать подпись» (`~` на выбранной картинке);
//   * она подходит под регэксп settings().style().imageNonameCaption(): «IMG_1234»,
//     «image 3», «Изображение», «DSC343453_DXO» — имя, которое дала камера,
//     а не человек.
// В файл подпись уходит как есть в любом случае: правило решает только показ.
bool isNonameCaption(const QString& caption);

// Спрятать подпись знаком спереди или вернуть спрятанную: «подпись» ⇄
// «~подпись». Спрятанная любым из двух знаков возвращается снятием этого
// знака; открытая прячется знаком mark.
QString captionWithHidingToggled(const QString& caption, QChar mark = QLatin1Char('~'));

// Разбор и сборка одного атрибута выравнивания: "align=left". Пусто — не оно.
ImageAlign imageAlignFromText(QString text, bool* ok = nullptr);
QString imageAlignText(ImageAlign align);

// Как эта картинка выглядит в файле: дословный текст строки для вики-вложения
