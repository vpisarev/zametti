enum DocProperty {
    // Свойства блока.
    KindProperty = QTextFormat::UserProperty,  // int(Kind)
    MarkerProperty,                            // int(Marker), только у пункта списка
    CheckedProperty,                           // bool, отметка задачи
    LevelProperty,                             // int, уровень вложенности списка
    InfoProperty,                              // QString, язык блока кода
    RawProperty,                               // bool, блок выводится дословно
    // bool на ПОСЛЕДНЕМ блоке логического: текст кончался переводом строки.
    // Пустой блок кода и блок из одной пустой строки выглядят одинаково, а в
    // файл выводятся по-разному.
    TrailingNewlineProperty,
    // int(diff::Mark): что стало с этой строкой сравнения. Стоит только у
    // блоков документа-разности (ZDocument::fromDiff) — у заметки его нет и
    // быть не должно. Семантика, а не цвет: красит по нему ВИД, и по нему же
    // ходит F4 от изменения к изменению.
    DiffMarkProperty,
    // ЗДЕСЬ СТОЯЛО ContinuationProperty — «этот блок продолжает предыдущий»:
    // дословные куски (таблицы, HTML, непонятое) резались построчно, по
    // QTextBlock на строку. Больше не режутся (сессия 5 refactor2): всякий
    // литеральный блок — код и дословное — ОДИН QTextBlock, строки внутри
    // разделяет U+2028 с пометкой BreakSourceProperty (как мягкий перенос в
    // абзаце), и «1 блок markdown == 1 QTextBlock» держится без исключений.
    // Номер свойства оставлен пустым нарочно: свойства — числа в форматах,
    // и сдвиг перенумеровал бы всё, что после.
    RetiredContinuationProperty,

    // Свойства формата знаков.
    SpanStyleProperty,   // int, биты SpanStyle
    BreakSourceProperty, // int(BreakSource) на самом разделителе строк
    SpanTitleProperty,   // QString, заголовок картинки (осмыслен только при SpanImage)

    // --- ОБЪЕКТЫ -----------------------------------------------------------
    //
    // Объект занимает в тексте ОДИН знак — U+FFFC, — а чем он на самом деле
    // является, говорит objectType его формата. Размер объекта Qt спрашивает у
    // QTextObjectInterface (intrinsicSize), и потому месту под объект не нужно
    // никакой записи в документ: именно ею вид загрязнял стек отмены.
    //
    // U+FFFC НЕ ПОКИДАЕТ QTextDocument. В файл, в буфер обмена и в журнал
    // уходит настоящий исходник, и хранится он здесь же, рядом с объектом:
    // обход документа (walkPieces) кладёт обратно ровно его. Инцидент №15
    // (заглушка «удалено: 2 строки» утекла в живую заметку владельца) стоил
    // этого правила, и оно железное.
    ObjectSourceProperty,   // QString, дословный исходник — то, что уйдёт в файл
    ObjectAltProperty,      // QString, подпись картинки (текст спана)
};

// Роды объектов. Начинаются с QTextFormat::UserObject: до него номера
// принадлежат Qt (её собственные картинки и таблицы).
enum ObjectKindType {
    ImageObject = QTextFormat::UserObject + 1,
    // Выключная формула (`$$…$$`) — тот же приём: один знак U+FFFC, исходник в
    // ObjectSourceProperty. Строчная объектом НЕ бывает: она живёт внутри
    // строки текста, и правила у неё свои.
    FormulaObject,
    // Таблица GFM (сессия 5): дословный кусок (RawProperty), в тексте — один
    // знак U+FFFC, исходник — в ObjectSourceProperty без хвостового перевода
    // строки (тот держится TrailingNewlineProperty, как у кода). Раскрытая на
    // правку таблица — обычный дословный блок с этим же текстом.
    TableObject,
    // СТРОЧНАЯ формула (`$…$` внутри строки текста): один знак U+FFFC на
    // КАЖДОЕ вхождение, исходник с долларами — в ObjectSourceProperty. Атом в
    // строке: каретка перешагивает, Backspace убирает целиком. Раскрытая на
    // правку — текст спана с битами SpanMath|SpanMathOpen (см. SpanStyle).
    InlineFormulaObject,
};

// Три знака Qt в insertText трактует структурно и рвёт на них блок. Замерено
// перебором: ровно '\n', '\r' и U+2029, больше ничего (U+2028, U+0085, U+000B,
// U+000C, U+001C..U+001E проходят как обычный текст).
//
// Внутрь блока все три попадают разделителем строк U+2028 — он рисуется
// переносом и блок не рвёт, — а какой знак был на самом деле, помнит свойство.
// Без него не обойтись: точно такой же U+2028 может стоять и в самом тексте
// заметки, заметки из Apple Notes им кишат, и превращать его в перевод строки
// значило бы портить текст.
enum BreakSource {
    BreakNewline = 1,
    BreakCarriageReturn = 2,
    BreakParagraph = 3,
};

enum SpanStyle {
    SpanBold = 1,
    SpanItalic = 2,
    SpanStrike = 4,
    SpanCode = 8,
    // Картинка: текст спана — подпись (alt), путь лежит в anchorHref, заголовок
    // — в SpanTitleProperty. Пока картинки в виде не рисуются, подпись видна
    // как текст ссылки.
    SpanImage = 16,
    // Строчный HTML-комментарий: текст спана — внутренность без скобок,
    // буквальная. Скобки — структура, рисуется серым.
    SpanComment = 32,
    // Формула: текст спана — ЛИТЕРАЛЬНЫЙ исходник вместе с долларами, ровно как
    // в файле. Ни один знак внутри не структура — потому и правится он как
    // обычный текст. ЗАКРЫТАЯ цельная формула текстом не живёт вовсе — сборщик
    // делает из неё объект (InlineFormulaObject); текстом с этим битом стоит
    // только РАСКРЫТАЯ на правку (вместе с SpanMathOpen) и кусок, переставший
    // быть формулой до пересборки.
    SpanMath = 64,
    // Раскрытая строчная формула: правится на месте как текст, сборщик её в
    // объект не сворачивает. Ходит только вместе с SpanMath (см. InlineMathOpen
    // в block_kind.h). Участвует в undo: Ctrl+Z после сворачивания возвращает
    // раскрытую.
    SpanMathOpen = 128,
};

// Здесь стояла kObjectsShown — «временный шаг назад», при котором фото, сетка
// таблицы и вёрстка формулы не рисовались, потому что место под них вид
// резервировал записями в живой документ. Все три — объекты (размер отдаёт
// intrinsicSize), записей вида в документ не осталось, константа снята
// (сессия 5).

// Формула, которую блок просит показать. Как и у картинки, модель текста об
// этом не знает: блок остаётся абзацем, а показ — дело вида.
//
// display — выключная (`$$…$$`): она стоит отдельным абзацем и потому
// показывается объектом. Строчная (`$…$`) объектом не бывает: она живёт внутри
// строки текста.
struct BlockFormulaRef {
    QString source;    // исходник с долларами, как в файле
    QString latex;     // тело без долларов — то, что уходит в движок
    bool display = false;
    bool valid = false;
};

// Формула, занимающая абзац ЦЕЛИКОМ. Иначе — пустая справка.
BlockFormulaRef blockFormulaRef(const QTextBlock& block);

// ТЕКСТ БЛОКА ТАКИМ, КАКИМ ОН ЛЕЖИТ В ФАЙЛЕ: разделители строк U+2028
// возвращены в те знаки, из которых пришли (BreakSourceProperty), а чужой
// U+2028 из самого текста остаётся собой. Блок кода лежит одним QTextBlock, и
// его строки — ровно такие переносы; копировать код в буфер надо этим текстом,
// а не block.text(). У блока-объекта ТАБЛИЦЫ в тексте стоит U+FFFC — отдаётся
// исходник из свойства: для писателя, поиска и буфера таблица и есть свой
// исходник.
QString sourceTextOf(const QTextBlock& block);

// Исходник таблицы-объекта (без хвостового перевода строки); пусто — блок не
// таблица-объект (в том числе раскрытая на правку таблица: она обычный
// дословный блок).
QString tableSourceOf(const QTextBlock& block);
bool isTableObjectBlock(const QTextBlock& block);

// Есть ли в блоке РАСКРЫТАЯ на правку строчная формула (кусок с SpanMathOpen).
// По ней Esc и уход каретки зовут судью closeInlineFormula, а сохранение
// сворачивает раскрытое перед записью.
bool hasOpenInlineFormula(const QTextBlock& block);

// Стоит ли на этой позиции документа знак строчной формулы-объекта.
bool isInlineFormulaChar(const QTextDocument& doc, int position);

// Строчный объект в тексте поиска: [from, to) — его исходник в ОТДАННОМ
// тексте, position — позиция знака U+FFFC в документе. Карта нужна, потому что
// смещения текста поиска не равны позициям документа: на месте исходника в
// блоке стоит один знак.
struct ObjectSpan {
    int from = 0;
    int to = 0;
    int position = 0;
};

// ТЕКСТ БЛОКА ДЛЯ ПОИСКА: у обычного блока — его текст, у объекта (таблица,
// формула) — ИСХОДНИК из свойства (решение владельца: поиск ищет по исходнику).
// В тексте блока-объекта стоит один U+FFFC, и без этого правила Ctrl+F, поиск
// по хранилищу и по истории не видели бы ни одной таблицы и формулы. Смещения
// в отданном тексте — смещения в исходнике; inObject говорит, что это он.
//
// СТРОЧНЫЕ формулы-объекты внутри обычного блока подставляются исходником на
// месте знака; какие куски отданного текста — объекты, говорит карта objects
// (если её спросили). inObject при этом ЛОЖЬ: блок — текст с вкраплениями.
QString searchableTextOf(const QTextBlock& block, bool* inObject = nullptr,
                         std::vector<ObjectSpan>* objects = nullptr);

// Классификация вхождения [from, to) в тексте поиска: −1 — целиком в обычном
// тексте, i ≥ 0 — целиком внутри objects[i], −2 — пересекает границу объекта.
// Пересекающее НЕ СЧИТАЕТСЯ вхождением нигде (ни в счёте, ни в подсветке):
// исходник объекта и соседние буквы стоят рядом только в тексте поиска, на
// экране между ними вёрстка. Правило одно на ZDocument::find и NoteSearch —
// иначе счётчик «3/17» разошёлся бы с F3.
int hitSpanIndex(const std::vector<ObjectSpan>& objects, int from, int to);

// Позиция документа для смещения в тексте поиска — для вхождений ВНЕ объектов:
// каждый объект левее занимает в документе один знак вместо исходника.
int docPositionOf(const QTextBlock& block, const std::vector<ObjectSpan>& objects,
                  int textOffset);

// --- ЛЕСТНИЦА КЕГЛЕЙ --------------------------------------------------------
//
// В документе НЕТ НИ ОДНОГО АБСОЛЮТНОГО КЕГЛЯ. Размер знака задаётся ступенью
// QTextFormat::FontSizeAdjustment — множителем от шрифта документа. Тогда весь
// шрифтовой зум это один setDefaultFont: форматы не трогаются, стек отмены
// чист, пересборки нет (замерено пробником: setDefaultFont стека отмены не
// касается, а объекты пересчитывают свой размер сами).
//
// Ступеней ровно семь, и они принадлежат Qt, а не нам. Замерено пробником
// (tests/zoom_probe.cpp, «zametti-bench zoom»):
//
//     −2 → 0.7   −1 → 0.8   0 → 1.0   +1 → 1.2   +2 → 1.5   +3 → 2.0   +4 → 2.4
//
// +5 и выше дают то же, что +4. Промежуточных значений не бывает: 1.45 задать
// нечем, и это цена относительности, принятая владельцем.
constexpr int kFontStepMin = -2;
constexpr int kFontStepMax = 4;

// Во сколько раз ступень крупнее шрифта документа.
qreal fontStepFactor(int step);

// Ставит ступень в формат знака. Ноль тоже ставится явно: без свойства формат
// наследует ступень соседа, и знак, набранный сразу после заголовка, выходил
// бы крупным.
void setFontStep(QTextCharFormat& format, int step);

// НАЗНАЧЕННАЯ ВЫСОТА СТРОКИ БЛОКА, В ПИКСЕЛЯХ.
//
// Спрашивать QTextBlockFormat::lineHeight() напрямую — ловушка: он отдаёт сырое
// свойство, а оно может быть и пикселями, и ДОЛЕЙ (у нас доля, 115). Прочитанная
// как пиксели, доля давала плашке блока кода лишние девяносто два пикселя, и
// полоска налезала на соседний абзац.
//
// ТОЧНОСТЬ — ОКОЛО ПИКСЕЛЯ, и это не наша небрежность. Долю Qt считает от
// естественной высоты строки, а наружу отдаёт её ОКРУГЛЁННОЙ вверх
// (QTextLine::height): замер пробником дал шаг 19.547 при height 17.000, то
// есть настоящая основа была 16.997. Неокруглённого значения публичного
// доступа нет, поэтому здесь мы всегда чуть выше правды. Сравнивать с
// измеренной геометрией с допуском мельче пикселя нельзя.
qreal assignedLineHeight(const QTextBlock& block);

// Метка разности у блока; -1 — блок не из документа-разности.
int diffMarkOf(const QTextBlock& block);

bool isRawBlock(const QTextBlock& block);

// Пустая строка — ровно одна, отдельным блоком (см. Kind::VSpace в block_kind.h).
//
// Для строения списка такой блок прозрачен: прогон он не рвёт, нумерацию не
// сбивает, отступа не имеет. Так же на него смотрит и сериализатор — "- раз",
// пустая строка, "- два" остаются одним списком, просто просторным.
bool isVSpaceBlock(const QTextBlock& block);

// Слипнутся ли эти два блока документа, окажись они в файле подряд без пустой
