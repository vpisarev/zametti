// Оси, по которым различаются блоки заметки. Только семантика — ни разбора, ни
// хранения, ни Qt.
//
// Жила эта семантика в ir.h, вместе с ареной и координатными пространствами
// промежуточного представления. Представление умерло — оси остались: они
// описывают не то, КАК блок хранится, а то, ЧТО он такое, и ровно эти значения
// лежат в свойствах QTextBlockFormat (см. doc_model.h).

#pragma once

#include <cstdint>

namespace zametti {

// Род блока — что это за блок, и только. Чем помечен пункт и на каком уровне он
// стоит, родом не выражается: это отдельные оси (Marker, level).
//
// Родов нарочно мало, и ветки default в switch по роду быть не должно. Тогда
// -Wswitch при -Werror сам перечисляет места, где новый род не разобран, — иначе
// код рос бы по квадрату от числа родов, а забытое место молча делало бы не то.
enum class Kind : uint8_t {
    Paragraph,
    Heading,          // headingLevel = 1..6
    Code,             // info = язык или пусто
    Quote,
    // Пустая строка — ровно одна. Столько же блоков, сколько пустых строк в
    // файле: пять строк подряд — пять блоков.
    //
    // Отдельным родом, а не полем «сколько пустых строк перед блоком», ради
    // правки: выделение, удаление и перемещение работают с ними как с любыми
    // другими блоками, и «выделили две пустые строки из пяти» не требует
    // особого случая.
    VSpace,
    ListItem,         // marker, checked, level
    // Тематический разрыв. Канонический вывод — ровно "___": подчёркивание —
    // единственный из трёх знаков, не конфликтующий ни с setext-заголовками,
    // ни с буллетами; вход "---", "***" и длинные варианты приводятся.
    // Осторожно: "Foo" + "---" следующей строкой — setext-заголовок по
    // спецификации, он и остаётся заголовком.
    Divider,
    // ВЫКЛЮЧНАЯ ФОРМУЛА, стоящая отдельным блоком: `$$…$$` или одиночная
    // `$…$`, занимающая абзац целиком. Текст ЛИТЕРАЛЬНЫЙ и вместе с долларами —
    // ровно как в файле, как у блока кода.
    //
    // Родом, а не спаном в абзаце, и это решение владельца, оплаченное бедой:
    // спан внутри абзаца попадает под все правила нормализации абзацев, и одно
    // из них (ведущие пробелы → неразрывные) молча испортило ему заметку —
    // многострочная матрица уехала в файл с U+00A0 между столбцами. У блока
    // таких правил нет по определению: литеральное литерально.
    Math,
    // Понятый HTML-блок. Каких видов бывает — ось HtmlKind (как маркер у
    // пункта): сейчас это только законченный комментарий. Непонятый HTML
    // остаётся дословным куском, как и был.
    Html,
};

// Вид понятого HTML-блока.
enum class HtmlKind : uint8_t {
    // "<!-- внутренность -->": в тексте блока — внутренность без скобок и
    // крайних пробелов, скобки — структура и повредить их правкой нельзя.
    // Канон: "<!-- " + текст + " -->".
    Comment,
};

// Чем помечен пункт. Выполненность — отдельный признак, а не свой вид маркера:
// переключение задачи это смена bool, а не подмена рода блока.
enum class Marker : uint8_t {
    Bullet,
    Ordered,
    Task,
};

// Куда прижимать фотографию в колонке. По умолчанию — по центру: так страница
// выглядит по-книжному. Умолчание в файл не пишется вовсе, поэтому Center стоит
// первым и означает «не задано».
//
// Живёт здесь, рядом с родом и маркером, а не в модели текста: об этом
// спрашивают заметку глаголом (setImageAlign), а модель текста наружу не
// выходит.
enum class ImageAlign : uint8_t {
    Center,
    Left,
    Right,
};

inline bool isList(Kind k) { return k == Kind::ListItem; }

// Слипнутся ли эти два блока, если поставить их в файле подряд БЕЗ пустой
// строки между ними. Проверено на ядре: абзац после абзаца читается одним
// абзацем, абзац после пункта и после цитаты — их ленивым продолжением. Всё
// прочее — заголовок, список, код, цитата после абзаца — прекрасно стоит
// вплотную.
//
// Отсюда инвариант разбора: между такими блоками обязан стоять VSpace. Тогда
// писателю не нужно вставлять пустую строку от себя, и одна пустая строка в
// файле — это ровно один блок VSpace, в обе стороны.
//
// ПРАВИЛО ОДНО НА ВСЕХ, и живёт оно здесь, а не у разбора и не у документа:
// спрашивают его двое — разбор (сложились ли блоки так, что понадобится
// пустая строка) и живой документ (можно ли слить два блока правкой), — и
// разойдись они хоть в одном случае, круг «прочитали — записали» перестал бы
// быть неподвижной точкой.
//
// previousClosedComment — предыдущий блок это ЗАКОНЧЕННЫЙ HTML-комментарий:
// "-->" завершает блок сам, и любой сосед начинается заново (замерено на md4c
// для кода, абзаца, черты, таблицы и второго комментария). Он прозрачен для
// соседства, в отличие от прочего дословного.
//
// nextLevel — уровень следующего блока в списке (-1 снаружи списка). Спрашивается
// он ради одного случая, найденного замером на md4c: литеральный блок ВНУТРИ
// пункта прячется за отступ, и отступ этот неотличим от отступа продолжения
// текста. Строка "   ```" сразу за строкой пункта читается ленивым продолжением
// пункта, а не забором, и весь кусок падает в дословный. Значит между пунктом и
// его литеральным содержимым обязана стоять пустая строка. За абзацем внутри
// пункта тот же забор читается прекрасно — там текст уже стал абзацем, а
// забор абзац прерывает.
// nextEmpty — у следующего блока нет содержимого (пустой пункт «-» без текста).
// Спрашивается ради одного случая, замеренного на md4c: пустой пункт СРАЗУ за
// абзацем файл съедает — "текст\n-" читается setext-заголовком второго уровня,
// "текст\n1." просто добирается к тексту абзаца. После цитаты, после другого
// пункта и через пустую строку такой пункт цел.
inline bool wouldMerge(Kind previousKind, bool previousRaw, bool previousClosedComment,
                       Kind nextKind, bool nextRaw, int nextLevel, bool nextEmpty) {
    if (previousClosedComment) return false;
    if (nextEmpty && !nextRaw && isList(nextKind) && !previousRaw &&
        previousKind == Kind::Paragraph)
        return true;
    // Дословный кусок с уровнем (таблица, HTML внутри пункта) — та же
    // литеральность: строка с палками сразу за строкой пункта читалась бы её
    // ленивым продолжением, а не таблицей.
    if (nextLevel >= 0 && (nextRaw || nextKind == Kind::Code || nextKind == Kind::Math) &&
        isList(previousKind) && !previousRaw)
        return true;
    // Kind::Html — комментарий, понятый моделью, — прозрачен так же; снизу его
    // защищает то, что HTML-блок второго типа прерывает абзац по спецификации.
    if (!previousRaw && previousKind == Kind::Html) return false;
    // Два блока кода подряд: их заборы спарились бы не так, как надо, — канон
    // ведь дописывает закрывающий забор незакрытому. Два дословных куска
    // подряд — по той же причине непрозрачности.
    const bool previousLiteral = previousRaw || previousKind == Kind::Code;
    const bool nextLiteral = nextRaw || nextKind == Kind::Code;
    if (previousLiteral && nextLiteral) return true;
    // Разделитель ("___") стоит вплотную к любому соседу: подчёркивание не
    // бывает setext-подчёркиванием — замерено для абзаца, пункта, цитаты,
    // заголовка, комментария и второго разделителя. Ровно ради этого канон и
    // выбрал "___", а не "---".
    if (nextKind != Kind::Paragraph) return false;
    return previousKind == Kind::Paragraph || previousKind == Kind::Quote ||
           isList(previousKind);
}

// Начертание куска строки. Битами, а не полями: признаки перечислены в одном
// месте, а кусок строки остаётся мелким.
enum InlineFlag : uint8_t {
    InlineBold    = 1u << 0,
    InlineItalic  = 1u << 1,
    InlineStrike  = 1u << 2,
    // Встроенный код: содержимое буквальное, разметки внутри нет.
    InlineCode    = 1u << 3,
    // Картинка: текст куска — подпись (alt), href — путь, title — заголовок.
    InlineImage   = 1u << 4,
    // Строчный HTML-комментарий: текст — внутренность без скобок, буквальная.
    InlineComment = 1u << 5,
    // Формула: текст — ЛИТЕРАЛЬНЫЙ исходник вместе с долларами, как в файле.
    InlineMath    = 1u << 6,
    // РАСКРЫТАЯ строчная формула: человек правит её исходник на месте, и
    // сборщик оставляет такой кусок ТЕКСТОМ, а не объектом. Бит ходит только
    // вместе с InlineMath (math() у раскрытой истинен — потому писатель отдаёт
    // её литерально и не наращивает косые, даже если запись случится в
    // раскрытом виде). В файле бита нет: читатель раскрытых не порождает.
    InlineMathOpen = 1u << 7,
};

}  // namespace zametti
