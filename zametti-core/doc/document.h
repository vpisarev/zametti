// ZDocument — живая заметка целиком: шапка, содержимое, отпечаток.
//
// ОДНА ЖИВАЯ МОДЕЛЬ. Внутри лежит QTextDocument, и это единственное
// представление заметки в памяти. Промежуточного представления (арены блоков и
// спанов) больше нет: две изменяемые модели одного и того же — это постоянная
// работа по их сверке и постоянный источник расхождений.
//
// QTextDocument НАРУЖУ НЕ ОТДАЁТСЯ, и это решение владельца. Соблазн отдать
// его велик: вид всё равно хочет рисовать, операции правки хотят курсор. Но
// стоит открыть дверь — и высокоуровневый API писать перестают, а ходят по
// блокам сами, каждый по-своему. Закрытая дверь заставляет спрашивать заметку
// глаголами, и именно глаголы переживут переезд на Android, где никакого
// QTextDocument может не быть вовсе.
//
// КОПИРУЕТСЯ ДАРОМ. Внутренность за shared_ptr, поэтому конструктор копии и
// присваивание не написаны вовсе — они и так делают ровно то, что нужно.
// Копия РАЗДЕЛЯЕТ содержимое: ZDocument это ручка к заметке, а не её слепок.
// Нужен независимый слепок — есть clone().

#pragma once

#include "block_kind.h"
#include "hash.h"
#include "search.h"
#include "sort_order.h"

#include <QString>

#include <functional>
#include <optional>
#include <memory>
#include <string>
#include <string_view>
#include <vector>

namespace zametti {

// Ссылка на вложение, как она видна в тексте.
struct Attachment {
    QString id;        // «01jd7f0kq2m8xa.webp» — имя файла в хранилище
    QString alt;       // подпись
    int width = 0;     // ширина показа, 0 — не задана
    QString align;     // left | center | right, пусто — по умолчанию
};

// Строка канонического markdown и то, какому блоку она принадлежит. Нужна
// разности версий: единица сравнения — строка файла, а полоски на поле
// рисуются по блокам.
struct SourceLine {
    QString text;
    int block = 0;
};

// Сводка по заметке: слова, строки, блоки, фотографии.
struct Stats {
    int words = 0;
    int lines = 1;
    int blocks = 1;
    int images = 0;
    bool valid = false;
};

// Один блок глазами того, кто заметку ПОКАЗЫВАЕТ или ПРАВИТ, но не хочет знать
// про QTextBlock. Значение, а не ручка: сделали снимок — работаете со снимком.
struct BlockInfo {
    int index = 0;
    Kind kind = Kind::Paragraph;
    Marker marker = Marker::Bullet;
    int level = 0;          // вложенность пункта списка
    int headingLevel = 0;   // 1..6 у заголовка
    bool checked = false;   // отметка задачи
    bool raw = false;       // выводится дословно
    bool continuation = false;  // продолжает предыдущий блок
    QString info;           // язык блока кода
    QString text;           // текст блока, как его видит человек
};

class ZDocument {
public:
    ZDocument();

    // Копирование и присваивание НЕ ОБЪЯВЛЕНЫ нарочно: за shared_ptr они и так
    // верны. Копия разделяет содержимое — это ручка, а не слепок.

    // Независимый слепок. Нужен там, где заметку правят «на пробу»: показать
    // разность, примерить операцию, сравнить с собой прежней.
    ZDocument clone() const;

    // --- круг с диском ----------------------------------------------------

    // Байты файла целиком, вместе с шапкой.
    bool loadMarkdown(std::string_view bytes);

    // Канонические байты, вместе с шапкой. Это ровно то, что уйдёт в файл.
    std::string toMarkdown() const;

    // Отпечаток канонических байтов. Истина — он: mtime и etag лишь подсказки.
    Digest digest() const;

    // Совпадают ли канонические байты с исходными. Так проверяется ДРЕЙФ.
    bool isCanonical(std::string_view original) const;

    // --- шапка, по-человечески --------------------------------------------
    //
    // Ключи шапки названы здесь один раз. ЧУЖИЕ КЛЮЧИ НЕ ТРОГАЮТСЯ НИКОГДА:
    // круг чтение-запись побайтовый, включая порядок строк и незнакомые ключи.

    QString parentId() const;
    void setParentId(const QString& id);   // пусто — заметка в корне

    bool isFolder() const;
    bool isLost() const;
    bool isArchived() const;
    void setArchived(bool archived);

    QString created() const;
    QString modified() const;
    // Поднять modified «сейчас». Только при правке СОДЕРЖИМОГО: перенос,
    // архивация и прописка в бюро находок — не редактирование.
    void stampModified();

    // Произвольный ключ — для того, что не заслужило своего глагола (sort,
    // lost-parent). Пустое значение снимает ключ.
    QString headerValue(const QString& key) const;
    void setHeaderValue(const QString& key, const QString& value);
    bool hasHeader() const;

    // ПОРЯДОК СОРТИРОВКИ ПАПКИ. Метка живёт в шапке ключом `sort`, но наружу
    // ходит значением: голых литералов ключей за пределами заметки не бывает.
    // Пустой порядок снимает метку — папка снова наследует порядок родителя.
    //
    // Правит только свой ключ: неизвестные строки шапки переживают правку
    // дословно, а `modified` не трогается вовсе — пометка порядка не
    // редактирование содержимого, и всплывать наверх списка папка от неё не
    // должна (правило этапа 7).
    std::optional<SortOrder> sortOrder() const;
    void setSortOrder(std::optional<SortOrder> order);

    // --- о чём заметка ----------------------------------------------------

    // Заголовок: первая строка первого содержательного блока.
    QString title() const;
    // Первые строки после заголовка — для списка заметок.
    QString snippet(int limit = 200) const;
    // Стаб для архива: шапка плюс строка заголовка.
    std::string archiveStub() const;
    // Пуста ли заметка по существу: ни одного блока, кроме пустых строк.
    bool isEmpty() const;

    Stats stats() const;

    // --- блоки, но БЕЗ ходьбы по ним --------------------------------------
    //
    // Спросить о строении заметку можно, а лазить в её внутренности — нет.
    // Всё, что здесь есть, отдаётся значениями.

    int blockCount() const;
    BlockInfo blockAt(int index) const;
    std::vector<BlockInfo> blocks() const;

    // Канонический текст построчно, с картой «строка → блок». На этом стоит
    // разность версий.
    std::vector<SourceLine> sourceLines() const;

    // --- вложения ---------------------------------------------------------

    std::vector<Attachment> attachments() const;
    // Переписать ссылки. Возвращает, сколько переписано.
    int rewriteAttachments(const std::function<QString(const QString&)>& rename);

    // --- поиск ------------------------------------------------------------

    std::vector<Hit> find(const Query& query) const;
    HitLine hitLine(const Hit& hit, int radius = 48) const;

    // --- сравнение --------------------------------------------------------

    // Совпадают ли строение и текст. Разметка внутри строки не сравнивается:
    // голую ссылку человек набирает текстом, а файл читает её ссылкой. На этом
    // стоит самопроверка записи.
    bool sameSkeleton(const ZDocument& other) const;
    // То же, но игнорируя шапку целиком: нужен истории, где `modified` меняется
    // при каждой записи и иначе всякая разность начиналась бы с неё.
    bool sameBody(const ZDocument& other) const;

protected:
    struct Data;
    // shared_ptr, а не unique_ptr: с ним копирование и присваивание работают
    // сразу и правильно, и писать их не нужно вовсе.
    std::shared_ptr<Data> d_;
};

}  // namespace zametti
