// ZDocument — живая заметка целиком: шапка, содержимое, отпечаток.
//
// ЗАЧЕМ ОН. Сегодня заметка размазана: метаданные в NoteMeta, содержимое в
// zametti::Document (арена IR), живой вид в QTextDocument, а согласие между
// ними держится руками. Две изменяемые модели одного и того же — это
// постоянная работа по их сверке и постоянный источник расхождений.
//
// ZDocument оставляет ОДНУ живую модель — QTextDocument, — и владеет ею.
// Не наследует: у заметки есть то, чего у rich-text документа нет и не должно
// быть (шапка, id, путь, отпечаток, состояние синхронизации).
//
// ИНТЕРФЕЙС СОБРАН ИЗ ГЛАГОЛОВ, а не из устройства ir.h. Низкоуровневые обходы
// (blocks, spans, арена, Range) наружу не выходят вовсе — они и есть то, от
// чего мы уходим. Каждый метод здесь отвечает на вопрос, который КТО-ТО УЖЕ
// ЗАДАЁТ в дереве: разбор мест вызова показал 28 таких вопросов, и вот они.
//
// ЧЕГО ЗДЕСЬ НЕТ НАРОЧНО:
//
//   * архивации и восстановления. Они работают ПО БАЙТАМ, без разбора вовсе, и
//     это правило владельца: испорченную заметку убрать в архив обязано
//     получиться, раз шапка на месте. ZDocument на этот путь не встаёт;
//   * записи на диск. Её делает хранилище: у записи свой порядок —
//     сериализация, самопроверка, отпечаток, атомарная замена, журнал.

#pragma once

#include "hash.h"
#include "ir.h"
#include "search.h"

#include <QString>
#include <QTextDocument>

#include <functional>
#include <memory>
#include <string>
#include <string_view>
#include <vector>

namespace zametti {

// Порядок сортировки папки — уже есть свой тип, тащить его сюда незачем.
class SortOrder;

// Ссылка на вложение, как она видна в тексте.
struct Attachment {
    QString id;        // «01jd7f0kq2m8xa.webp» — имя файла в хранилище
    QString alt;       // подпись
    int width = 0;     // ширина показа, 0 — не задана
    QString align;     // left | center | right, пусто — по умолчанию
};

class ZDocument {
public:
    ZDocument();
    ~ZDocument();
    ZDocument(ZDocument&&) noexcept;
    ZDocument& operator=(ZDocument&&) noexcept;
    ZDocument(const ZDocument&) = delete;
    ZDocument& operator=(const ZDocument&) = delete;

    // --- круг с диском ----------------------------------------------------

    // Байты файла целиком, вместе с шапкой. Ложь возвращается только когда
    // разобрать нечего вовсе.
    bool loadMarkdown(std::string_view bytes);

    // Канонические байты, вместе с шапкой. Это ровно то, что уйдёт в файл.
    std::string toMarkdown() const;

    // Отпечаток канонических байтов. Истина — он: mtime и etag лишь подсказки.
    Digest digest() const;

    // Совпадают ли канонические байты с исходными. Так проверяется ДРЕЙФ: то,
    // что лежит на диске, обязано равняться serialize(parse(x)), и verify
    // ищет расхождение именно этим вопросом.
    bool isCanonical(std::string_view original) const;

    // --- шапка, по-человечески --------------------------------------------
    //
    // Ключи шапки сегодня рассыпаны голыми литералами по девяти файлам
    // («parent», «role», «archived», «sort»…). Здесь они названы один раз.
    //
    // ЧУЖИЕ КЛЮЧИ НЕ ТРОГАЮТСЯ НИКОГДА — правило хранилища: круг чтение-запись
    // побайтовый, включая порядок строк и незнакомые ключи.

    QString parentId() const;
    void setParentId(const QString& id);   // пусто — заметка в корне

    bool isFolder() const;      // role: folder — и это на всю жизнь заметки
    bool isLost() const;        // role: lost — бюро находок
    bool isArchived() const;
    void setArchived(bool archived);

    QString created() const;
    QString modified() const;
    // Поднять modified «сейчас». Только при правке СОДЕРЖИМОГО: перенос,
    // архивация и прописка в бюро находок — не редактирование.
    void stampModified();

    // Незнакомые ключи и всё прочее — для тех, кому нужен сырой доступ.
    const NoteMeta& meta() const;
    NoteMeta& meta();

    // --- о чём заметка ----------------------------------------------------

    // Заголовок: первая строка первого содержательного блока. Сегодня это
    // правило написано ТРИЖДЫ — в поиске по хранилищу, в дереве и в архиве.
    QString title() const;

    // Первые строки после заголовка — для списка заметок.
    QString snippet(int limit = 200) const;

    // Стаб для архива: шапка плюс строка заголовка. Чистая функция от
    // разобранного документа. Байтовый путь архивации — отдельно и мимо нас.
    std::string archiveStub() const;

    // Пуста ли заметка по существу: ни одного блока, кроме пустых строк.
    bool isEmpty() const;

    // --- вложения ---------------------------------------------------------

    std::vector<Attachment> attachments() const;

    // Переписать ссылки на вложения. Вызывается при ввозе чужого дерева, где
    // имена файлов меняются на id. Возвращает, сколько переписано.
    int rewriteAttachments(const std::function<QString(const QString&)>& rename);

    // --- поиск и счёт -----------------------------------------------------

    std::vector<Hit> find(const Query& query) const;
    HitLine hitLine(const Hit& hit, int radius = 48) const;

    // --- живой документ ---------------------------------------------------
    //
    // Явный люк, а не протёкший наружу член: вид и операции правки работают с
    // QTextDocument напрямую, и прятать его за сотней прокси-методов незачем.
    QTextDocument& textDocument();
    const QTextDocument& textDocument() const;

    // --- переходное -------------------------------------------------------
    //
    // Пока живы оба представления, ядру нужен доступ к IR: на нём стоят разбор,
    // запись, разность и счёт слов. Уйдёт вместе с ir.h.
    const Document& ir() const;
    void setIr(Document doc);

protected:
    struct Data;
    std::unique_ptr<Data> d_;
};

}  // namespace zametti
