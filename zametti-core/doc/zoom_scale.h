// ШКАЛА МАСШТАБА — ЦЕЛОЕ ЧИСЛО СТУПЕНЕЙ, А НЕ НАКОПЛЕННОЕ ПРОИЗВЕДЕНИЕ.
//
// Масштаб задаётся одним целым k, а сам множитель считается из него:
//
//     scale(k) = 2^(k/12)
//
// Двенадцать ступеней дают ровно ×2, одна — 5.95 %. Раньше было
// `zoom *= 1.1`, и у этого две беды сразу. Первая — грубость: между 100 % и
// 110 % промежутка нет вовсе, а владельцу нужны деления помельче. Вторая —
// накопленный мусор: в state.json лежали 1.1000000000000003 и
// 0.8264462809917357, потому что источником правды было САМО ПРОИЗВЕДЕНИЕ, и
// каждое нажатие домножало прежний результат. Отсюда правило: хранится и
// правится ТОЛЬКО k, множитель выводится из него заново каждый раз.
//
// Границы соответствуют прежним 0.5…4.0 ровно: 2^(-12/12) = 0.5,
// 2^(24/12) = 4.0. Настройками они больше не являются — прежние zoom.step,
// zoom.min и zoom.max из конфига убраны: шаг у шкалы один по построению, а
// пределы — свойство программы, а не вкуса.

#ifndef ZAMETTI_ZOOM_SCALE_H
#define ZAMETTI_ZOOM_SCALE_H

#include <algorithm>
#include <cmath>

namespace zametti {

// Полтона вниз ×12 и вверх ×24 — те же 50 % и 400 %, что были.
inline constexpr int kZoomStepsMin = -12;
inline constexpr int kZoomStepsMax = 24;

// Во сколько раз крупнее базового кегля показывает ступень k.
inline double zoomScale(int k) {
    return std::exp2(double(std::clamp(k, kZoomStepsMin, kZoomStepsMax)) / 12.0);
}

// Обратный ход: какой ступени отвечает множитель. Нужен миграции старых
// state.json (там лежит дробное число) и наборам, которые задают масштаб
// множителем. Ноль и отрицательные — ступень 0: молча возводить в логарифм
// мусор нельзя.
inline int zoomStepsFor(double scale) {
    if (!(scale > 0.0)) return 0;
    const double steps = 12.0 * std::log2(scale);
    return std::clamp(int(std::lround(steps)), kZoomStepsMin, kZoomStepsMax);
}

}  // namespace zametti

#endif  // ZAMETTI_ZOOM_SCALE_H
