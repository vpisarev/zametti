// РАМКА-МИШЕНЬ ВЫБРАННОГО ОБЪЕКТА — ОДНИМ КЛАССОМ (решение владельца,
// сессия 6): четыре уголка вокруг фотографии, вёрстки формулы, сетки таблицы и
// того, что будет. Геометрия и отрисовка живут вместе, и вместе с ними — ответ
// на вопрос «как далеко рамка выходит за прямоугольник объекта»: этим ответом
// отсечение перерисовки берёт запас, и прокрутка не оставляет обрубков.
//
// История дефекта: у каждого объекта был свой код рамки. Фотография резервирует
// вынос уголков в СОБСТВЕННОЙ полосе (imageBoxFor) — и дефекта не имеет;
// формула и таблица рисовали уголки за прямоугольником блока, а отсечение в
// paintEvent шло по нему без запаса — узкая полоса перерисовки при прокрутке
// закрашивала кусок рамки текстом. Полосы формул при этом не трогаем: их вид
// владелец назвал превосходным (бриф строчных формул), поэтому чинит не резерв,
// а запас отсечения — взятый у ЭТОГО класса, у того же кода, который рисует.

#ifndef ZAMETTI_OBJECT_FRAME_H
#define ZAMETTI_OBJECT_FRAME_H

#include <QPainter>
#include <QRectF>
#include <QtGlobal>

namespace zametti {

class ObjectFrame {
public:
    // Насколько уголки выходят за переданный прямоугольник: отступ наружу плюс
    // толщина пера (пороги владельца в настройках облика). Место под этот вынос
    // фотография резервирует в своей полосе ВСЕГДА, выбрана она или нет: иначе
    // резерв менялся бы от выделения.
    static qreal overhang();

    // Дополнительный отступ рамки ФОРМУЛЫ наружу от вёрстки: впритык обнимающие
    // дробь уголки читаются как часть формулы, а не как «выбрано» (решение
    // владельца, сессия 5).
    static qreal formulaPad() { return overhang(); }

    // Самый дальний вынос отрисовки рамок за прямоугольник объекта — на него
    // берёт запас отсечение перерисовки (paintEvent и бумага): всё, что рисуется
    // за краем блока, обязано быть не дальше этого.
    static qreal sweep() { return overhang() + formulaPad(); }

    // Четыре уголка-мишени по краям box — снаружи его пикселей, цветом каретки.
    static void paintCorners(QPainter& painter, const QRectF& box);
};

}  // namespace zametti

#endif  // ZAMETTI_OBJECT_FRAME_H
