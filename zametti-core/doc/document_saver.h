// Чем отвечает запись заметки: исход, отпечаток, байты.
//
// Путь один: QTextDocument → логические блоки → приведение к тому, что файл
// умеет выразить → байты. Никакого второго способа получить текст файла нет и
// быть не должно, и зовётся он глаголами заметки (см. ниже).
//
// Перед тем как заменить файл, записанный текст разбирается обратно и
// полученные блоки сравниваются с блоками документа. Не совпало — старый файл не
// трогается вовсе, а буфер уходит в аварийный файл рядом. Это последний рубеж
// против потери данных, и он не отключается.

#ifndef ZAMETTI_DOCUMENT_SAVER_H
#define ZAMETTI_DOCUMENT_SAVER_H

#include "document_pieces.h"
#include "hash.h"

#include <QByteArray>
#include <QString>

#include <functional>

class QTextDocument;

namespace zametti {

enum class SaveResult {
    Unchanged,   // на диске уже ровно это — не трогаем даже mtime
    Written,     // записано
    Rescued,     // самопроверка не прошла: файл цел, буфер в аварийном файле
    Failed,      // записать не удалось вовсе
};

struct SaveOutcome {
    SaveResult result = SaveResult::Failed;
    QString message;      // человеку, при Rescued и Failed
    QString rescuePath;   // непусто при Rescued
    // Как записанное прочтётся обратно. Обычно это ровно то, что было в
    // документе, но не всегда: голую ссылку человек набирает текстом, а файл
    // читает её ссылкой. Виджет догоняет документ этим содержимым.
    std::vector<Piece> reread;
    bool differsFromDocument = false;
    // Отпечаток того, что теперь лежит в файле. Считается здесь, по тому самому
    // буферу, который уходит на диск, — перечитывать файл после записи не надо
    // вовсе. Пустой (все нули) — записи не было и отпечатку взяться неоткуда:
    // так выглядят Failed и Rescued.
    Digest digest;
    // Те самые байты, что ушли в файл. Нужны истории: слепок обязан быть ровно
    // тем, что лежит на диске, а не пересобранным заново — пересборка второй
    // раз это ещё один способ ошибиться. При Unchanged здесь тоже байты файла:
    // мы их посчитали, чтобы понять, что писать нечего.
    QByteArray written;
};

// reader подменяется только тестом самопроверки: испортить читателя иначе
// нечем, а проверять последний рубеж обязательно.
using DocumentReaderFn = std::function<std::vector<Piece>(const QTextDocument&)>;

// ЧТО УЙДЁТ В ФАЙЛ И САМА ЗАПИСЬ — ГЛАГОЛАМИ ЗАМЕТКИ: ZDocument::fileBytes,
// ZDocument::saveTo, ZNote::save (там же и объяснения к их параметрам).
// Свободных функций записи наружу больше нет: они жили здесь с тех времён,
// когда заметки как объекта не было, и звал их один только набор — то есть
// проверялся обходной путь, а не рабочий. В этом заголовке остались лишь ТИПЫ,
// которыми глаголы отвечают.
//
// «одно ли это содержимое, если не считать штампов» спрашивают у шапки
// (`NoteHeader::sameFileApartFromStamps`): тем же правилом живут и запись в
// историю, и её чистка, а двух реализаций одного правила не бывает — бывает
// одна и её копия, которая однажды отстанет.

// Отметка времени для имени аварийного файла: вынесена наружу, чтобы тест не
// зависел от часов.
QString rescueTimestamp();

}  // namespace zametti

#endif  // ZAMETTI_DOCUMENT_SAVER_H
