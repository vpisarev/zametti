// Правила истории: что считать тем же самым состоянием и какой хвост лишний.
//
// ПОЧЕМУ ОТДЕЛЬНО ОТ ЖУРНАЛА. `journal.*` — механика: дописать, укоротить,
// переписать атомарно. Про содержимое слепков она не знает ничего — у неё
// безымянные байты. А «одна ли это версия заметки» — вопрос про ФОРМАТ
// ЗАМЕТКИ: в шапке живёт строка modified, она меняется на каждой записи и сама
// изменением не является. Этот раздел уже разъезжался на этапе 9 (там
// `replaceLast` превратился в `truncate` ровно по этой причине), и здесь та же
// граница: механика в journal.*, правило здесь.
//
// ПРАВИЛО ОДНО НА ДВА РЕЖИМА, и различаются они ровно одним полем — сторожем
// свежести (`Rules::ignoreAge`):
//
//   живая запись (этап 9) смотрит только на свежие записи: вернуться к
//     состоянию месячной давности — законное дело, и стирать за это месяц
//     истории было бы разбоем;
//   миграция (этап 10) чистит ретроактивно, на возраст не глядя, — иначе
//     старые дубликаты не вычистились бы никогда.
//
// Всё остальное у них общее, и общее оно не на словах, а одной функцией:
// `decideStep` зовёт и автосохранение, и миграция.

#ifndef ZAMETTI_HISTORY_RULES_H
#define ZAMETTI_HISTORY_RULES_H

#include "journal.h"

#include <QByteArray>
#include <QString>
#include <QVector>

#include <functional>

namespace zametti {

// Одно ли это содержимое, если не считать строки modified в шапке.
//
// Штамп меняется на каждой записи и сам изменением заметки не является. Без
// этой оговорки «изменилось ли» отвечало бы «да» всегда, и каждая пауза в
// наборе давала бы на диске новую копию, а в истории — запись, отличающуюся
// одной цифрой в дате.
bool sameApartFromModified(const QByteArray& a, const QByteArray& b);

// Насколько две версии разошлись — в знаках, считая и дописанное, и стёртое.
//
// Меряется куском, который изменился: общее начало и общий хвост
// отбрасываются, остаётся то, что человек тронул. Разницы длин мало — два
// текста одной длины бывают разными целиком.
int changedChars(const QByteArray& a, const QByteArray& b);

namespace history {

struct Rules {
    // Мелкая свежая правка заменяет прошлую запись, а не ложится рядом.
    int mergeChars = 100;
    int mergeHours = 24;
    // СТОРОЖ СВЕЖЕСТИ — единственное, чем миграция отличается от живой записи.
    // Ставится не руками вызывающего: `compressJournal` включает его сам.
    bool ignoreAge = false;
};

// Слепок записи по номеру; пусто (isNull) — не собрался, дальше не заглядывать.
using SnapshotOf = std::function<QByteArray(int)>;

// Решение об ОДНОЙ новой записи против журнала, уже вычищенного этими же
// правилами. Это и есть весь свод правил этапа 9 в одном месте.
struct Step {
    int keep = 0;          // сколько записей журнала остаётся
    bool writeNew = true;  // писать ли новую
    int dropped = 0;       // ушло возвратом к уже записанному состоянию
    int merged = 0;        // ушло слиянием мелкой правки (0 или 1)
};

Step decideStep(const journal::ZJournal& journal, const SnapshotOf& snapshotOf,
                const QByteArray& fresh, journal::Kind kind, qint64 now, const Rules& rules);

// Полная пересборка журнала: те же решения, прогнанные по всем записям подряд,
// как будто их дописывали по одной в уже чистый журнал.
struct Plan {
    QVector<int> keep;     // номера остающихся записей по возрастанию
    int duplicates = 0;    // сколько ушло возвратом к уже записанному
    int merged = 0;        // сколько ушло слиянием мелкой правки
    int passes = 0;        // сколько проходов понадобилось до неподвижности
};
Plan planFor(const journal::ZJournal& journal, const QVector<QByteArray>& snapshots,
             const Rules& rules);

// Что сделала чистка — для люка и для отчётов.
struct Report {
    QString versionBefore;   // пусто — v0, «не чищен»
    QString versionAfter;
    int recordsBefore = 0;
    int recordsAfter = 0;
    int duplicates = 0;
    int merged = 0;
    bool rewritten = false;  // false — файл не тронут ни байтом
};

// ЛЕНИВАЯ ЧИСТКА ЖУРНАЛА ЗАМЕТКИ. Единственный путь чистки во всей программе:
// и автосохранение, и вход в историю, и тестовый люк зовут эту функцию.
// Параллельной реализации нет нигде — люк форсирует боевой путь, а не свой.
//
// force — чистить и уже чищенный журнал (люк). Без него журнал версии
// kCleanVersion не трогается вовсе.
//
// Зовётся ТОЛЬКО ПЕР-ЗАМЕТОЧНО. Корпусные читатели (verify и будущий поиск по
// всем заметкам) журналы не переписывают никогда: иначе первый же обход стал
// бы той самой глобальной утилитой через чёрный ход. Чистоту показа они
// получают тем же `planFor`, применённым в памяти.
bool compressJournal(journal::History& history, const QString& noteId, const Rules& rules,
                     bool force, Report* report, QString* error);

}  // namespace history
}  // namespace zametti

#endif  // ZAMETTI_HISTORY_RULES_H
