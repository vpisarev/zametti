// Плоское хранилище заметок: init / new / import / verify.
//
// Библиотека, а не только CLI: тесты зовут функции напрямую, main — тонкий
// разбор аргументов. Правило безопасности: импорт НИКОГДА не пишет в
// источник — новое хранилище создаётся рядом, старое дерево остаётся эталоном.

#ifndef ZAMETTI_STORE_H
#define ZAMETTI_STORE_H

#include "import_limits.h"

#include <QString>
#include <QStringList>

namespace zametti::store {

// Отчёт — человекочитаемые строки; беды считаются отдельно, по ним код
// возврата. Молчаливых пропусков нет: всё несопоставившееся — в отчёт.
struct Report {
    QStringList lines;
    int problems = 0;

    void note(const QString& line) { lines.append(line); }
    void problem(const QString& line) {
        lines.append(QStringLiteral("PROBLEM: ") + line);
        ++problems;
    }
};

// Пустое хранилище: каталог, служебные ".zametti/" и ".rescue/" (побитые
// файлы редактора; на сервер не синхронизируется) и "history/" (история
// заметок; синхронизируется). Отказывается работать в непустом каталоге.
// false — и объяснение в error.
bool initStore(const QString& dir, QString* error);

// Пустая заметка с корректным id и каркасом метаданных (created — сейчас;
// parent — если задан и существует). Возвращает путь к файлу; пусто — ошибка.
QString newNote(const QString& root, const QString& parentId, QString* error);

// Один .md-файл в хранилище. Источник НЕ трогается: делается копия под
// свежим id, с нашей шапкой метаданных и в каноническом виде — то есть
// serialize(parse(x)). Канонизация сразу, а не когда-нибудь: человек должен
// увидеть результат импорта немедленно, а не через первое сохранение.
//
// Времена берутся из шапки источника, если она наша; иначе из файловой
// системы. id и role источника не наследуются никогда: id принадлежит этому
// хранилищу, а role сделал бы из заметки папку.
//
// Возвращает путь созданной заметки; пусто — ошибка, объяснение в error.
QString importNote(const QString& root, const QString& parentId, const QString& sourcePath,
                   QString* error);

struct ImportOptions {
    QString root;
    QString from;
    QString appleManifest;   // пусто — манифеста нет
    bool dryRun = false;
};

// Импорт дерева .md: подкаталог → заметка-каталог, файл → заметка, иерархия
// через parent, содержимое через parse/serialize ядра (импорт и есть
// нормализация). Хранилище плоское до конца: вложения получают такие же
// 14-значные id, как заметки, и ложатся в тот же каталог ("<id>.webp");
// одинаковое содержимое — один файл. png перегоняется в webp без потерь
// (cwebp), heic — в webp q90 (heif-convert + cwebp), jpeg и webp — байт в
// байт; без кодеков — копия как есть и беда в отчёте. Вики-вложения
// ("![[attach/x|W]]", "[[attach/x]]") переписываются в канон image-спана
// "![родное-имя](<id>.ext#w=W)"; прочие wikilinks не трогаются. Ссылки на
// .md внутри набора — на "<id>.md". Отчёт соответствия кладётся рядом с
// хранилищем: "<root>.import-report.txt" (не внутрь: verify считает чужие
// файлы бедой).
bool importTree(const ImportOptions& options, Report& report);

// Полная проверка: id-имена у заметок и вложений, метаданные, ноль дрейфа
// serialize(parse(x)), ссылки parent и циклы, существование целей
// ![...]-ссылок, осиротевшие вложения (отчёт, не удалять). Служебные
// .zametti/, .rescue/ и history/ прозрачны.
bool verifyStore(const QString& root, Report& report);

// Какие вложения уйдут вместе с этими заметками.
//
// КОРЗИННОСТЬ ВЛОЖЕНИЯ ВЫВОДИТСЯ, А НЕ ХРАНИТСЯ (решение владельца):
//
//     вложение «в корзине» ⇔ все ссылающиеся на него заметки — в корзине
//
// Поэтому при переносе заметки в корзину и при восстановлении над вложениями не
// делается НИЧЕГО: семантика «картинки следуют за заметкой туда и обратно»
// получается сама собой, и рассинхронизироваться тут нечему. Физическое
// расставание — ровно один момент, очистка корзины, и вот он.
//
// Как считается: сперва собираются вложения, упомянутые в очищаемых заметках,
// потом каждая ОСТАЮЩАЯСЯ заметка (живая или корзинная) читается ОДИН РАЗ и
// вычёркивает из этого набора всё, что в ней упомянуто. Поиск байтовый, по
// 14-значному id: разбирать markdown ради этого незачем, а ложное срабатывание
// (id текстом в блоке кода) ошибается в безопасную сторону — файл остаётся.
//
// История в расчёт НЕ идёт сознательно: слепок со ссылкой на исчезнувшее
// деградирует штатной рамкой «файл не найден», а иначе ни одна картинка не
// покинула бы хранилище никогда.
QStringList attachmentsLeavingWith(const QString& root, const QStringList& noteIds);

// Убрать файл вложения из хранилища — в корзину ОС, как и заметки.
bool deleteAttachmentFile(const QString& root, const QString& name, QString* error);

// ПОХОРОНИТЬ ВЛОЖЕНИЕ: на месте файла остаётся посмертная мини-версия с меткой
// «удалено» и выросшей ревизией (см. image/deleted_image.h).
//
// Стереть файл было бы проще — и неверно: удаление обязано ДОЕХАТЬ до других
// устройств, а «файла нет» доехать не может. Чтобы сказать «его больше нет»,
// нужен файл, который это говорит.
//
// Формат превью всегда JXL (писатель у нас один), поэтому `<id>.webp`
// превращается в `<id>.jxl`, а исходник уходит в корзину ОС. Идемпотентно: уже
// помеченный файл не трогается ни байтом — иначе ревизия росла бы вечно, а
// картинка ужималась при каждом заходе.
//
// Не смогли прочесть картинку (чужой формат, битый файл) — старое поведение:
// файл уходит в корзину ОС, а причина остаётся в error.
bool retireAttachmentFile(const QString& root, const QString& name, const ImportLimits& limits,
                          QString* error);

// Удалить файл заметки насовсем.
//
// Порядок обязателен: сначала надгробие в историю, потом файл. Наоборот было
// бы окно, в котором заметки уже нет, а истории о её смерти ещё нет, — и
// падение в этот миг оставило бы журнал, обрывающийся на живой заметке.
//
// Журнал при этом НЕ удаляется никогда: последний слепок вместе с надгробием
// остаётся в истории навсегда, и по нему заметку можно воскресить. Своего
// слепка у надгробия нет — им служит предыдущая запись.
//
// Файл уходит в корзину ОС; нет её (сеть, голый сервер) — удаляется. Отказ
// записать надгробие удаление НЕ останавливает: человек попросил убрать
// заметку, и упираться из-за истории неправильно, — но в error об этом
// сказано, и вызывающий обязан пожаловаться.
bool deleteNoteFile(const QString& root, const QString& noteId, QString* error);

// ПОДНЯТЬ УДАЛЁННУЮ ЗАМЕТКУ из её журнала.
//
// Удаление насовсем — второе осознанное решение подряд (сперва в архив, потом
// удалить из архива), поэтому полная история после него не хранится: остаются
// последний слепок и надгробие. Этого хватает, чтобы заметку вернуть, и вот
// этим она и возвращается.
//
// ВОЗВРАЩАЕТСЯ В АРХИВ, как и лежала: слепок пишется как есть, а в нём стоит
// `archived: yes` — её ведь удаляли из архива. Отменяется ровно одно решение из
// двух; доставать ли заметку из архива, человек решает сам. Картинки у неё —
// посмертные, уменьшенные: это принятая цена.
//
// Файл на месте — отказ: заметка не удалена, и перетирать её нечем. Головой
// журнала не надгробие — тоже отказ, по той же причине.
bool resurrectNote(const QString& root, const QString& noteId, QString* error);

}  // namespace zametti::store

#endif  // ZAMETTI_STORE_H
