// ZSystem — ЕДИНСТВЕННАЯ ДВЕРЬ НАРУЖУ: в файловую систему на разрушение и в
// чужие программы.
//
// ПОЧЕМУ ОНА ЕСТЬ. 30.08.2026 программа снесла каталог владельца. Сложилось из
// двух половин, каждая из которых по отдельности выглядела безобидно: поле
// адреса облака резолвило относительный путь по РАБОЧЕМУ КАТАЛОГУ ПРОЦЕССА
// (набранное «../..» стало домашним каталогом), а стирание облака считало
// «манифеста нет — значит облако безымянное, значит наше». Ни одна из половин
// не спрашивала «а точно ли это наше» у чего-то одного: спрашивать было не у
// кого — QFile::remove рассыпан по пятнадцати файлам.
//
// Отсюда правило владельца, вписанное первыми строками CLAUDE.md: удаление и
// переименование файлов и каталогов, а также запуск чужих программ идут ТОЛЬКО
// через этот класс. Прямые QFile::remove / QFile::rename / QFile::moveToTrash /
// QDir::rmdir / removeRecursively / ::unlink / ::rename / std::remove / system /
// exec* / QProcess за его пределами — ТАБУ, и это не обещание, а сборка:
// tests/file_ops_check.cmake ходит по исходникам и краснеет.
//
// ЧТО СЮДА НЕ ВХОДИТ И ПОЧЕМУ. Создание и запись — QSaveFile, mkpath, QFile::copy
// на несуществующее имя — остаются свободными. Они ничего не теряют: худшее, что
// делает промах, — лишний файл. Таб'у держится узким нарочно: правило, которое
// запрещает всё, перестаёт читаться как правило.
//
// КАК ЭТО РАБОТАЕТ. Разрушение всегда происходит ВНУТРИ ОБЛАСТИ, и область
// называется явно при постройке объекта: корень хранилища, каталог-облако или
// свой временный каталог. Путь вне области не удаляется и не переименовывается
// НИКОГДА — вместо этого отказ словами. Класс не спрашивает разрешения у
// человека и не гадает: он сверяет два канонизованных пути.
//
// КАТАЛОГ — ОСОБЫЙ СЛУЧАЙ. Дверь у сноса каталога ровно одна, статическая, и
// она требует доказательства: каталог обязан быть хранилищем zametti (метка
// .zametti/ на месте). Каталог, который хранилищем не является, программа не
// сносит ни при каких доводах — слово владельца.

#ifndef ZAMETTI_STORE_ZSYSTEM_H
#define ZAMETTI_STORE_ZSYSTEM_H

#include <QString>
#include <QStringList>

namespace zametti {

class ZSystem {
public:
    // Чем область объявлена, тем она и проверяется на входе. Три вида — это не
    // украшение: у каждого свой ответ на вопрос «что тут вправе исчезнуть».
    enum class Area {
        // Корень хранилища zametti: заметки, вложения, history/, .zametti/.
        Storage,
        // Каталог-облако: плоский, в нём только наши блобы. Хранилищем НЕ
        // является (метки .zametti/ там нет) — оттого и отдельный вид.
        Cloud,
        // Каталог хозяйства программы: config.json, state.json, бухгалтерия
        // синка, err.log и sync.log. Хранилищем НЕ является и лежит совсем в
        // другом месте — этим он и отличается от Storage. Отдельным видом стал
        // не сразу: сперва бухгалтерию синка стирали областью хранилища, и
        // набор SyncEngine немедленно покраснел, потому что путь до неё лежит
        // вне корня.
        Config,
        // Свой временный каталог (QTemporaryDir и подобное): мы его завели, нам
        // его и разбирать.
        Scratch,
    };

    // Область без корня не бывает: безымянная область — это и есть та самая
    // дыра размером с файловую систему. Пустой корень оставляет объект
    // БЕССИЛЬНЫМ: covers() всегда false, а значит ни одно разрушение не пройдёт.
    ZSystem(Area area, const QString& root);

    Area area() const { return area_; }
    // Канонизованный корень области; пусто — область не состоялась.
    const QString& root() const { return root_; }

    // ЛЕЖИТ ЛИ ПУТЬ ВНУТРИ ОБЛАСТИ. Строго внутри: сам корень области — не
    // «внутри», его этой дверью не снести. Сверяются канонизованные пути, и
    // канонизуется РОДИТЕЛЬ цели, а не сама цель: удаляемого файла может уже не
    // быть, а симлинк-родитель обязан быть развёрнут.
    bool covers(const QString& path) const;

    // --- РАЗРУШИТЕЛЬНОЕ ------------------------------------------------------
    //
    // Все три отвечают false и пишут в error, когда путь вне области. Отсутствие
    // файла бедой не считается: удаление идемпотентно.

    // Сперва в корзину, и лишь если система не умеет — насовсем. Так удаляются
    // вещи ЧЕЛОВЕКА: заметки, вложения, журналы. Промах программы тогда ещё
    // можно поправить руками.
    bool remove(const QString& path, QString* error = nullptr) const;

    // Насовсем, мимо корзины. Так удаляется СЛУЖЕБНОЕ: замок, бухгалтерия
    // синка, недописанный .part, блоб в каталоге-облаке. Корзина, забитая
    // облачными блобами, — не сохранность, а мусор.
    bool removeForever(const QString& path, QString* error = nullptr) const;

    // Оба конца обязаны лежать внутри области: переименование наружу — это
    // перемещение, а перемещать этой дверью нечего.
    bool rename(const QString& from, const QString& to, QString* error = nullptr) const;

    // --- КАТАЛОГИ ------------------------------------------------------------

    // Похоже ли на корень хранилища zametti (есть ли метка .zametti/).
    static bool looksLikeStorage(const QString& dir);

    // ЖИЛАЯ ЗОНА: каталог, в котором лежат домашние каталоги людей — `/home`,
    // `/Users`, `C:\\Users`. Выводится из QDir::homePath(), а не из списка имён:
    // список знал бы только те системы, о которых мы вспомнили.
    //
    // ВНУТРИ ЖИЛОЙ ЗОНЫ КАТАЛОГИ НЕ УДАЛЯЮТСЯ — решение владельца. Там живёт
    // всё, что человеку дорого, и цена ошибки там не «лишний файл», а работа.
    static QStringList homeAreas();

    // ВРЕМЕННАЯ ЗОНА: каталоги, которые ЭТА система считает местом для мусора.
    // Единственное место, где программе позволено сносить каталоги.
    //
    // ЧТО ЗДЕСЬ СТАНДАРТ — измерено, а не вспомнено (опыты на маке, 30.08.2026):
    //
    //   POSIX (Linux, macOS, BSD): переменная ОДНА — TMPDIR (POSIX.1-2017,
    //       XBD §8.3). TEMP и TMP там не значат ничего: Qt на маке их
    //       игнорирует — подсунутый через них чужой каталог не был взят.
    //       Запасное место — /tmp (FHS) и /var/tmp; на маке P_tmpdir и вовсе
    //       равен /var/tmp, а /tmp — симлинк на /private/tmp.
    //   macOS: сверх того свой на каждого пользователя,
    //       confstr(_CS_DARWIN_USER_TEMP_DIR) = /var/folders/<..>/T. Именно его
    //       отдаёт QDir::tempPath() без TMPDIR — сверено с confstr напрямую.
    //   Windows: стандарт — порядок GetTempPath(): %TMP%, затем %TEMP%, затем
    //       %USERPROFILE%, затем каталог Windows. То есть TMP и TEMP здесь
    //       законны, и это ответ на вопрос «как определить local temp под
    //       Windows»: спросить GetTempPath, что QDir::tempPath() и делает.
    //
    // ПОЧЕМУ ПЕРЕМЕННЫЕ БЕРУТСЯ ПО ПРИНАДЛЕЖНОСТИ К СИСТЕМЕ, А НЕ ВСЕ СРАЗУ.
    // Каждая признанная временная зона РАСШИРЯЕТ то, что нам позволено сносить,
    // — то есть работает в опасную сторону. На Unix TEMP и TMP не значат
    // ничего, и случайное `TEMP=$HOME` в чужом окружении снова открыло бы
    // дыру, которую этот класс закрывает. TMP_DIR не стандарт ни в одной
    // системе и не признаётся нигде.
    static QStringList tempAreas();

    // Можно ли вообще сносить ЭТОТ каталог. Общий вход у обеих дверей ниже.
    // Порядок проверок важен:
    //
    //   1. каталог, содержащий в себе корень, дом или рабочий каталог, — нет;
    //   2. каталог ВНУТРИ системного временного — да. Эта прорезь не поблажка,
    //      а необходимость: на маке владельца QDir::tempPath() = /Users/…/tmp,
    //      то есть САМ лежит в жилой зоне, а на Windows временный каталог лежит
    //      в %LOCALAPPDATA%\\Temp, то есть внутри C:\\Users\\<имя> ВСЕГДА. Без
    //      прорези наборы не смогли бы прибрать за собой ни там, ни там. Заодно
    //      это и есть ответ на «как определить local temp под Windows»:
    //      спрашивать не у нас, а у Qt — QDir::tempPath() читает %TEMP%;
    //   3. каталог в жилой зоне и не во временном — нет.
    static bool mayRemoveTree(const QString& dir, QString* error = nullptr);

    // ЕДИНСТВЕННЫЙ СПОСОБ СНЕСТИ КАТАЛОГ, и он требует доказательства:
    //   * путь абсолютный — относительный резолвится по рабочему каталогу
    //     процесса, а он не тот, что человек держит в голове (инцидент);
    //   * каталог — хранилище zametti (looksLikeStorage);
    //   * каталог не является ни домашним каталогом, ни рабочим каталогом
    //     процесса, ни предком любого из них.
    // Не сошлось хоть одно — отказ ДО ЕДИНОГО УДАЛЕНИЯ, словами.
    static bool removeStorageTree(const QString& dir, QString* error = nullptr);

    // СНОС СВОЕЙ ПЕСОЧНИЦЫ — наборам и пробникам. Доказательство здесь другое,
    // а строгость та же: каталог обязан лежать ВНУТРИ системного каталога
    // временных файлов (QDir::tempPath), то есть быть тем, что программа завела
    // сама. Это и есть правило для обезьяны, записанное кодом: разрушительный
    // жест пробника не дотягивается до репозитория, домашнего каталога и
    // хранилища владельца, сколько бы мусорных доводов ему ни подсунули.
    //
    // Сам tempPath снести нельзя: он не «внутри» себя.
    static bool removeScratchTree(const QString& dir, QString* error = nullptr);

    // То же, но песочницу называет вызывающий: наборам она иногда каталог
    // сборки, а не каталог временных файлов. Оба конца обязаны быть
    // абсолютными, цель — СТРОГО внутри песочницы, и цель не смеет содержать
    // в себе ни корень, ни дом, ни рабочий каталог процесса.
    static bool removeTreeInside(const QString& sandbox, const QString& dir,
                                 QString* error = nullptr);

    // --- ЧУЖИЕ ПРОГРАММЫ -----------------------------------------------------
    //
    // Здесь же, а не отдельным классом: вопрос один и тот же — «программа
    // выходит за свои пределы», и дверь на него должна быть одна.

    // Запуск утилиты с ожиданием: пустой вывод не интересен, важен код
    // возврата. Аргументы идут СПИСКОМ — оболочки в этой двери нет вовсе, и
    // потому подстановки, кавычек и склейки строк тоже нет.
    static bool runTool(const QString& program, const QStringList& args,
                        int startMs = 5000, int finishMs = 120000);

    // То же, но вывод программы нужен. Возвращает false, когда программа не
    // запустилась или не дождалась; stderr не читается вовсе (его прежде гасили
    // в оболочке через `2>/dev/null` — теперь оболочки нет, и гасить нечего).
    static bool readTool(const QString& program, const QStringList& args, QString* out,
                         int startMs = 5000, int finishMs = 120000);

    // Отсоединённый запуск (внешний редактор). Тот же уговор про список.
    static bool startDetached(const QString& program, const QStringList& args);

    // Разбор командной строки из настроек на программу и аргументы. Живёт
    // здесь, чтобы QProcess не понадобился снаружи ВОВСЕ: иначе сторож ловил бы
    // безобидное splitCommand, а исключения в таб'у — это дырки в таб'у.
    static QStringList splitCommand(const QString& command);

protected:
    // Общая часть обоих удалений: путь внутри области и это не каталог.
    bool guard(const QString& path, const char* what, QString* error) const;

    Area area_;
    QString root_;
};

}  // namespace zametti

#endif  // ZAMETTI_STORE_ZSYSTEM_H
