// ПОЛ ВРЕМЕНИ ЗАПИСЕЙ — device-локальное число, общее на хранилище.
//
// Зачем. Порядок записей журнала держится на ревизии, а время осталось второй
// ступенью ключа и несёт ещё четыре нагрузки, которых ревизия не закрывает:
// вёдра прореживания, сторож свежести у правил отбора, даты перед глазами
// человека и запасная ветка адресации «ближайшая не позже искомой». Часы,
// прыгнувшие назад (dual-boot с локальным RTC, поправка NTP, ручная переводка),
// портят все четыре — и портят НАВСЕГДА: уже записанное время не лечится.
//
// Поэтому время новой записи берётся не прямо с часов, а не раньше, чем
// «последнее записанное + миллисекунда». Здесь живёт устройственная половина
// этого пола; вторая половина — время самих записей журнала — живёт в ZJournal,
// и складывает их одно место (ZJournal::composeRecord).
//
// Где лежит. `.zametti/last-written`, рядом со `store.lock`: это состояние
// УСТРОЙСТВА, а не данные заметок, и в облако оно не едет — весь каталог
// `.zametti/` не синхронизируется. Так число находит и окно, и `zametti-store`,
// и наборы, не протаскивая себя параметром через семь мест создания History.
//
// Потеря числа не ломает ничего: пол деградирует до пола самого журнала, а тот
// выводится из записей и потеряться не может.

#ifndef ZAMETTI_DEVICE_CLOCK_H
#define ZAMETTI_DEVICE_CLOCK_H

#include <QString>

namespace zametti::store {

class DeviceClock {
public:
    explicit DeviceClock(QString root) : root_(std::move(root)) {}

    // Путь числа. Открыт ради наборов: им надо уметь его стереть и подменить.
    static QString pathFor(const QString& root);

    // Последнее записанное время; 0 — числа нет или оно нечитаемо.
    qint64 floor() const;

    // Запомнить время новой записи. Меньшее не записывается: число только
    // растёт, иначе смысл пола теряется.
    void advanceTo(qint64 time) const;

protected:
    QString root_;
};

}  // namespace zametti::store

#endif  // ZAMETTI_DEVICE_CLOCK_H
