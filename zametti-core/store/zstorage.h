    // --- ПОЛ ВРЕМЕНИ ЗАПИСЕЙ ЭТОГО УСТРОЙСТВА -------------------------------
    //
    // Зачем. Порядок записей журнала держится на ревизии, а время осталось
    // второй ступенью ключа и несёт ещё четыре нагрузки, которых ревизия не
    // закрывает: вёдра прореживания, сторож свежести у правил отбора, даты
    // перед глазами человека и запасная ветка адресации «ближайшая не позже
    // искомой». Часы, прыгнувшие назад (dual-boot с локальным RTC, поправка
    // NTP, ручная переводка), портят все четыре — и портят НАВСЕГДА: уже
    // записанное время не лечится.
    //
    // Поэтому время новой записи берётся не прямо с часов, а не раньше, чем
    // «последнее записанное + миллисекунда». Здесь живёт устройственная
    // половина этого пола; вторая половина — время самих записей журнала —
    // живёт в ZJournal, и складывает их одно место (ZJournal::composeRecord).
    //
    // Где лежит. `.zametti/last-written`, рядом со `store.lock`: это состояние
    // УСТРОЙСТВА, а не данные заметок, и в облако оно не едет — весь каталог
    // `.zametti/` не синхронизируется. Пишет его ТОЛЬКО хранилище, из
    // appendJournalLocked: начни его писать ещё и синк — порядок времён
    // поехал бы молча.
    //
    // Потеря числа не ломает ничего: пол деградирует до пола самого журнала,
    // а тот выводится из записей и потеряться не может.

    // Путь числа. Открыт ради наборов: им надо уметь его стереть и подменить.
