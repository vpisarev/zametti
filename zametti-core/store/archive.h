// Архив — ПОМЕТКА В ШАПКЕ, и ничего кроме.
//
// Пришёл на место корзины (этап 15). Разница не в названии, а в устройстве:
// корзина была ПАПКОЙ, куда заметку переносили (parent := корзина, прежний
// родитель в отдельный ключ), а архив — ПОМЕТКА. `parent` не трогается вовсе,
// в шапке появляется `archived: yes`, а «Архив» в дереве собирается сам из
// помеченных. Отсюда и восстановление: снять пометку — и заметка дома, без
// всякой памяти о том, откуда её брали.
//
// ДО ЭТАПА 17 АРХИВАЦИЯ СРЕЗАЛА ТЕЛО в журнал, оставляя от заметки стаб из
// шапки и заголовка. Экономия на диске выходила изрядная, но платили за неё
// четырежды, и каждый раз молча:
//
//   - вместе с телом из файла исчезали ССЫЛКИ НА ВЛОЖЕНИЯ, а по ним считается,
//     чему уходить при удалении насовсем. Картинки архивных заметок не
//     удалялись никогда;
//   - картинку, которую держала только архивная заметка, уносило удаление
//     СОСЕДНЕЙ: стаб её не «держал»;
//   - поиск по хранилищу переставал видеть архивные тела — их не было в файлах;
//   - человек, вышедший из режима истории, получал стаб, полностью доступный
//     для правки, и первое же сохранение клало стаб в журнал поверх тела.
//
// Теперь тело остаётся в файле, а архив — одна строка в шапке. Порядок:
// сперва ФАЙЛ, потом ЖУРНАЛ (прежний обратный порядок держал инвариант «тело
// не должно исчезнуть отовсюду»; теперь оно никуда не девается, зато нельзя
// объявлять заметку архивной раньше, чем она такой стала). Запись в журнал
// ложится по общим правилам отбора: пометка мелкая, значит гасит прошлую
// запись, а не встаёт рядом.
//
// Вложения не трогаются вовсе: их «архивность» выводится из заметок так же, как
// прежде выводилась корзинность (этап 10).

#ifndef ZAMETTI_STORE_ARCHIVE_H
#define ZAMETTI_STORE_ARCHIVE_H

#include "history_rules.h"
#include "note_header.h"

#include <QString>
#include <QStringList>

#include <string_view>

namespace zametti::store {

// Ключ архивности в шапке и его значение. Отдельным ключом, а НЕ значением
// `role`: роль у заметки уже может быть занята (`folder`), а заархивировать
// папку человек вправе — и она обязана остаться папкой. Железное правило
// владельца «заметка никогда не станет папкой, и наоборот» этим и держится.
inline constexpr char kArchivedKey[] = "archived";
inline constexpr char kArchivedValue[] = "yes";

// Помечена ли заметка архивной. Читает и СТАРЫЙ вид — `role: trash`: так
// выглядела заметка-корзина до этапа 15, и разовая миграция могла ещё не
// случиться (чужая копия хранилища, откат на прежнюю сборку).
bool isArchivedMeta(const NoteHeader& meta);

// Пометить/снять пометку в шапке. Ничего, кроме своего ключа, не трогает —
// `modified` в том числе: архивация не правка содержимого.
void setArchivedMeta(NoteHeader& meta, bool archived);

// Заархивировать заметку: в шапку добавляется одна строка, тело не трогается
// вовсе. Идемпотентно — уже архивная заметка не трогается.
//
// Порядок: сперва файл, потом журнал. Прежний обратный порядок держал инвариант
// «тело не должно исчезнуть отовсюду» (архивация срезала тело в журнал); теперь
// тело никуда не девается, зато нельзя объявлять заметку архивной раньше, чем
// она такой стала.
//
// rules — тот же свод, что и у живого сохранения: пометка мелкая, поэтому он
// гасит ею прошлую запись, а не заводит вторую вешку.
bool archiveNote(const QString& root, const QString& noteId, const history::Rules& rules,
                 QString* error);

// Вернуть заметку из архива: снять строку из шапки. Журнал для этого не нужен
// вовсе — тело всё это время лежало в файле; архивная заметка, приехавшая с
// чужой машины без истории, возвращается как своя.
bool restoreNote(const QString& root, const QString& noteId, QString* error);

// Удалить архивную заметку насовсем: стаб, журнал и — заботой вызывающего —
// вложения-эксклюзивы. Здесь только файл заметки и её история; журнал ЗДЕСЬ и
// только здесь удаляется по-настоящему: тело живёт в нём, и оставить его
// значило бы оставить и заметку.
bool forgetNote(const QString& root, const QString& noteId, QString* error);

// РАЗВЕРНУТЬ АРХИВНЫЕ СТАБЫ ПРЕЖНИХ СБОРОК.
//
// В хранилище, пожившем на прежней сборке, архивные заметки лежат стабами:
// шапка плюс строка заголовка, тело — в журнале. Пока они такие, у них нет ни
// ссылок на вложения (по ним считается, чему уходить при удалении насовсем), ни
// текста для поиска по хранилищу.
//
// Тело берётся из головы журнала, ШАПКА — ИЗ ФАЙЛА: в ней живут parent, sort и
// всё, что человек мог поменять, пока заметка лежала в архиве. `modified` не
// трогается, в журнал ничего не пишется — миграция про структуру, а не про
// правку, ровно как migrateTrashToArchive.
//
// ДЕТЕКТОР СТАБА — БАЙТОВЫЙ И КОНСЕРВАТИВНЫЙ: тело считается стабом, только
// если после отбрасывания пустых строк в нём осталась не больше одной
// непустой и та начинается с `#`. Сомневаешься — не трогай: ошибка здесь
// означает порчу заметки.
//
// Журнала нет или в нём нечего разворачивать — заметка не трогается, а её id
// уходит в leftAlone. Идемпотентно: второй заход не находит работы.
// Возвращает, сколько развёрнуто; -1 — беда, и она описана в error.
int unfoldArchivedStubs(const QString& root, QStringList* leftAlone, QString* error);

// РАЗОВАЯ МИГРАЦИЯ СТАРОЙ КОРЗИНЫ (решение владельца).
//
// До этапа 15 выброшенное лежало ВНУТРИ заметки-корзины: `parent` указывал на
// неё, а прежний родитель прятался в `trash-parent`. Архиву эта конструкция не
// нужна вовсе — он собирается пометкой, — поэтому при первом запуске каждая
// такая заметка переписывается в новый вид: `parent` := прежний родитель,
// `archived: yes`, ключи `trash-parent`/`trash-path` уходят. Опустевшая
// заметка-корзина удаляется вместе со своим журналом.
//
// Тела заметок при этом НЕ трогаются: миграция про структуру, а не про архив.
// Заметка, выброшенная год назад, останется полной — стабом её сделает только
// новая архивация. `modified` не поднимается: правка организационная.
//
// Идемпотентна: корзины нет — не делает ничего и возвращает 0. Возвращает,
// сколько заметок переехало; -1 — беда, и она описана в error.
int migrateTrashToArchive(const QString& root, QString* error);

}  // namespace zametti::store

#endif  // ZAMETTI_STORE_ARCHIVE_H
