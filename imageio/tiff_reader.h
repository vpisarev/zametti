// Чтение TIFF своими силами, поверх вендоренной libtiff.
//
// ЗАЧЕМ, если TIFF читает и Qt. Потому что Qt читает его не весь и местами
// неверно:
//
//   * 16-битный RGB с профилем он читает ВЕРНО — проверено сверкой на файле из
//     потока DxO: полная глубина, профиль Display P3, значения сходятся с
//     независимым разбором до единицы;
//   * а CIELab он ТИХО ПЕРЕВИРАЕТ. Нейтральный серый L=50 выходит
//     (133,123,107) вместо (119,119,119). Не отказывается — отдаёт
//     правдоподобную и неверную картинку, а это хуже отказа: пережатие
//     необратимо;
//   * метаданных не отдаёт вовсе — ни XMP, ни EXIF, ни даже того, какое у
//     файла цветовое пространство.
//
// Корень ошибки найден: плагин Qt зовёт у libtiff путь TIFFReadRGBAImage, а
// тот применяет СВОЮ модель дисплея (гамма 2.2, своя опорная белая) вместо
// колориметрического перевода. Утилита tiff2rgba даёт ту же ошибку в ту же
// сторону — эталоном она тоже не является.
//
// ОТСЮДА ГЛАВНОЕ ПРАВИЛО: берём СЫРЫЕ отсчёты (TIFFReadScanline) и считаем
// цвет сами. TIFFReadRGBAImage не зовём никогда.
//
// Что в корпусе владельца (120 файлов): без сжатия/CIELab 62, LZW/CIELab 53,
// без сжатия/CMYK 2, без сжатия/RGB-16 1, серый 1, Adobe Deflate/CIELab 1.

#pragma once

#include <QByteArray>
#include <QImage>
#include <QString>

namespace zametti {

// Откуда взялись цвета — нужно и для отчёта, и чтобы решить, переводили ли мы
// пространство сами (а значит, надо ли ставить картинке новый профиль).
enum class TiffColor {
    Rgb,        // как в файле, профиль оттуда же
    Gray,
    Lab,        // перевели мы: своего RGB-профиля у файла нет
    Cmyk,       // перевели мы, по ICC если он есть
    Palette,
};

struct TiffImage {
    QImage image;          // RGBX64/RGBA64 при глубине >8, иначе RGB(A)8888
    TiffColor color = TiffColor::Rgb;
    int bitsPerSample = 8; // как было в ФАЙЛЕ, до нашего перевода
    int photometric = 0;   // сырое значение тега, для отчёта
    bool converted = false;// пространство переводили мы, а не читали как есть

    QByteArray icc;
    QByteArray xmp;
    QByteArray exif;       // сырой блок каталога EXIF, если он в файле есть

    bool isNull() const { return image.isNull(); }
};

// Читает первый кадр. Ошибку кладёт в error — молчаливого провала быть не
// должно: человек обязан узнать, почему его картинка не вставилась.
//
// maxDecodeBytes — потолок на разжатую картинку. Проверяется ПО ЗАГОЛОВКУ, до
// чтения хоть одной строки: у TIFF размеры и глубина известны заранее, и
// незачем выяснять про бомбу после того, как под неё выделили память.
bool readTiff(const QString& path, TiffImage* out, QString* error,
              qint64 maxDecodeBytes = 0);

// Опознать TIFF по подписи, не открывая libtiff.
bool looksLikeTiff(const QByteArray& head);

// ТОЛЬКО ТЕГИ, без единой прочитанной строки пикселей.
//
// Нужен тому, кто считает место под фотографию до отрисовки. Спрашивать это у
// полного чтения нельзя: у TIFF каталог тегов бывает в конце файла, и наивная
// «проба» разжимала бы всю картинку — на каждой раскладке, на каждой картинке.
// Я на это наступил: набор снимков зависал на сорока файлах.
struct TiffHeader {
    QSize size;
    int bitsPerSample = 8;   // как в ФАЙЛЕ
    bool hasAlpha = false;
    // Поедет ли картинка шестнадцатибитным кадром: у Lab и CMYK это так даже
    // при восьмибитном файле, потому что перевод нелинеен.
    bool wideFrame = false;
    QByteArray icc;

    bool valid() const { return !size.isEmpty(); }
};
bool readTiffHeader(const QString& path, TiffHeader* out, QString* error);

}  // namespace zametti
