// Лестница качества: что делать, когда картинка не влезла в бюджет файла.
//
// Порядок отступления задан брифом и держится на одном соображении: РАЗМЕР
// ДОРОЖЕ КАЧЕСТВА. Сначала жертвуем степенью сжатия, и только когда она
// исчерпана — самими пикселями, которых потом не вернуть.
//
//   1. энкод в целевой размер с обычным качеством. Влез в бюджет×1.5 — готово;
//   2. перелёт → снизить качество на один шаг;
//   3. всё ещё перелёт в r раз → уменьшить сторону в √r;
//   4. последний резерв — пол качества. Ниже не опускаемся никогда;
//   5. если пришлось отступать от умолчаний, зовём АРБИТРА: SSIMULACRA2
//      финала против входа. Не меньше 80 — принять; меньше 70 — вернуться на
//      ступень назад и принять перелёт бюджета, записав это в отчёт.
//
// Почему бюджет×1.5, а не ровно бюджет: гоняться за последними процентами
// значит делать лишний энкод ради мегабайта, который никого не спасёт.
//
// ЧЕГО ЗДЕСЬ НЕТ. Дожимания «раз уж вышло хорошо». Владелец эту опцию выключил
// прямо: если картинка влезла с запасом по качеству, это не повод портить её
// ещё немного.
//
// АРБИТР И АЛЬФА. На картинках с прозрачностью арбитра звать НЕЛЬЗЯ, не
// наложив их сперва на фон: под прозрачными областями цвет не определён, и
// SSIMULACRA2 выдаёт бессмыслицу. Замер: на прозрачном PNG вышло -403.84.
// Этого в брифе нет — нашлось замером.

#pragma once

#include "import_limits.h"
#include "jxl_encoder.h"

#include <QByteArray>
#include <QImage>

namespace zametti {

// Что произошло на лестнице. Нужно для отчёта: «сжалось» ничего не говорит, а
// «пришлось спуститься до пола качества» — говорит, и человеку это стоит знать.
struct LadderResult {
    QByteArray bytes;
    int width = 0;
    int height = 0;
    int quality = 0;
    int encodes = 0;        // сколько раз звали энкодер
    int steps = 0;          // сколько ступеней прошли (0 — влезло сразу)
    bool hitQualityFloor = false;
    bool overBudget = false;   // приняли перелёт, потому что качество важнее
    double ssimulacra2 = 0;    // 0 — арбитра не звали
    bool arbiterRolledBack = false;
    QString error;

    bool ok() const { return !bytes.isEmpty(); }
};

// Пол качества: ниже не опускаемся ни при каких бюджетах. Число из брифа.
inline constexpr int kQualityFloor = 70;
// Шаг качества вниз — один, и он тоже из брифа.
inline constexpr int kQualityStep = 10;
// Пороги арбитра по шкале CID22.
inline constexpr double kArbiterAccept = 80.0;
inline constexpr double kArbiterReject = 70.0;
// Насколько разрешено перелететь бюджет, не вступая в лестницу.
inline constexpr double kBudgetSlack = 1.5;
// А насколько — картинке БЕЗ ПОТЕРЬ, прежде чем уйти на путь фото. Меньше, чем
// у лестницы, и это решение владельца: полтора — уже серьёзное превышение, а на
// нём lossy обычно выигрывает по обоим счетам сразу. Пятнадцать процентов
// покрывают ровно тот случай, ради которого запас и заведён: скриншот, который
// пробу на «плоскость» прошёл уверенно, а в бюджет не влез самую малость.
inline constexpr double kLosslessSlack = 1.15;

// Прогоняет лестницу. image уже приведена к целевому размеру и в нужном
// пространстве — уменьшать её дальше будет сама лестница.
LadderResult runLadder(const QImage& image, const EncodeMeta& meta, const ImportLimits& limits);

// Оценка SSIMULACRA2 между двумя картинками одного размера. Вынесена наружу,
// потому что нужна и лестнице, и стендам, и recompress.
//
// Картинки с альфой накладываются на СЕРЫЙ фон: чёрный или белый исказил бы
// оценку в сторону тех областей, где прозрачность граничит с краем.
double compareSsimulacra2(const QImage& a, const QImage& b);

}  // namespace zametti
