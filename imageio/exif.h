// Метаданные картинок: достать из входного файла и перенести в наш JXL.
//
// Зачем это здесь, а не отдано библиотеке. Qt не отдаёт сырых блобов
// метаданных НИ ДЛЯ ОДНОГО формата: из всего богатства он показывает только
// разобранную ориентацию и цветовой профиль. А переносить надо максимум —
// снимок без даты, места и выдержки теряет половину смысла.
//
// Сколько этого добра в живом хранилище (713 файлов владельца, exiftool):
// 209 JPEG с EXIF, 227 с профилем, 130 с XMP, 18 с поворотом; все 118 TIFF
// с EXIF. То есть это не редкость, а обычное дело.
//
// Что здесь есть и чего нет. Здесь — ОБХОД КОНТЕЙНЕРОВ: вынуть блоб оттуда,
// где он лежит. Это чистая работа с байтами, и потому ей место в ядре, рядом
// с разбором markdown, а не в слое картинок:
//
//     JPEG   маркеры APP1 (Exif, XMP) и APP2 (ICC, склейка кусков)
//     WebP   чанки RIFF: EXIF, XMP, ICCP
//     PNG    чанки eXIf, iTXt (XMP), iCCP
//
// Форматов, у которых свой разборщик есть у самой библиотеки, здесь нет и не
// будет: TIFF читается через libtiff, HEIF через libheif, JXL через libjxl —
// каждая отдаёт метаданные сама, и городить второй путь незачем.
//
// Разбор САМОГО EXIF тут неполный и намеренно: нам нужен один тег, Orientation.
// Всё остальное переносится не разбирая — байты как есть. Полный разбор EXIF
// (а это сотни тегов, четыре типа каталогов и вложенные IFD) нам не нужен ни
// для чего.
//
// Ядро без Qt (за этим следит набор core-without-qt), поэтому здесь только
// стандартная библиотека.

#ifndef ZAMETTI_EXIF_H
#define ZAMETTI_EXIF_H

#include <cstdint>
#include <string>
#include <string_view>

namespace zametti {

// Ориентация по EXIF: числа те же, что в стандарте, и те же, что у JXL и
// libheif. Своей нумерации не заводим — перекладывать одно в другое значит
// однажды получить зеркало вместо поворота.
enum class Orientation : int {
    Normal = 1,          // как лежит
    FlipHorizontal = 2,
    Rotate180 = 3,
    FlipVertical = 4,
    Transpose = 5,
    Rotate90 = 6,        // самый частый у телефонов и зеркалок
    AntiTranspose = 7,
    Rotate270 = 8,
};

// Всё, что переносится из источника. Блобы — сырые байты, как лежали в файле:
// exif начинается с заголовка TIFF ("II*\0" или "MM\0*"), без префикса "Exif\0\0"
// и без четырёх нулей, которые нужны боксу JXL, — их добавляет тот, кто пишет.
struct ImageMeta {
    std::string exif;
    std::string xmp;
    std::string icc;
    // Из блоба exif, если он есть. Отдельным полем потому, что спрашивают её
    // куда чаще, чем всё остальное, и потому, что источник у неё бывает и не
    // в exif (у HEIF — бокс контейнера).
    Orientation orientation = Orientation::Normal;

    bool empty() const { return exif.empty() && xmp.empty() && icc.empty(); }
};

// Опознаёт формат по подписи и зовёт нужный обход. Неизвестный формат — не
// ошибка: просто нечего вернуть.
ImageMeta readImageMeta(std::string_view file);

// То же, но когда формат уже известен. Возвращают false, если файл не того
// формата или испорчен настолько, что ходить по нему нельзя.
bool readJpegMeta(std::string_view file, ImageMeta* out);
bool readWebpMeta(std::string_view file, ImageMeta* out);
bool readPngMeta(std::string_view file, ImageMeta* out);

// --- сам EXIF -------------------------------------------------------------

// Ориентация из блоба. Блоб непонятен или тега нет — Normal.
Orientation exifOrientation(std::string_view exif);

// Сбросить Orientation в 1 прямо в блобе.
//
// ЗАЧЕМ ЭТО ОБЯЗАТЕЛЬНО. Мы разжимаем картинку с уже применённым поворотом:
// в хранилище ложатся пиксели, стоящие правильно. Если при этом перенести тег
// как есть, показывающая программа повернёт их ВТОРОЙ раз, и портрет ляжет
// набок. Тег не удаляем, а именно обнуляем в единицу: длина блоба не меняется,
// а значит не сдвигаются смещения, на которые ссылаются другие теги.
//
// Возвращает false, если блоб не EXIF или тега в нём нет — и то и другое
// нормально, просто сбрасывать нечего.
bool resetExifOrientation(std::string* exif);

// Проверка, что блоб вообще похож на EXIF: заголовок TIFF на месте и порядок
// байт понятен. Мусор в боксе JXL хуже, чем пустой бокс.
bool looksLikeExif(std::string_view exif);

// --- XMP ------------------------------------------------------------------

// Вписать в XMP имя исходного файла (xmpMM:PreservedFileName). Возвращает
// готовый XMP: existing, дополненный именем, или собранный с нуля, если его не
// было.
//
// ЗАЧЕМ. Имя исходника живёт в заметке — как alt у картинки, — но стоит
// вынести вложение из хранилища, и оно теряется: файл называется
// бессмысленным id. Тег держит имя внутри самой картинки, и его видит любой
// просмотрщик, понимающий XMP (проверено на exiftool).
//
// ПОЧЕМУ XMP, А НЕ EXIF. Запись тега в EXIF означает пересборку TIFF-структуры
// со сдвигом всех смещений на данные за пределами двенадцатибайтовых записей,
// с двумя порядками байт и подкаталогами (EXIF IFD, GPS IFD) — то есть
// полноценный писатель EXIF, где ошибка в смещениях портит метаданные молча.
// XMP же обычный XML, и добавление свойства к нему — вставка одного элемента.
//
// ПОЧЕМУ ОТДЕЛЬНЫМ rdf:Description, а не правкой существующего: по RDF
// свойства из нескольких Description с одним rdf:about объединяются, и такая
// вставка не зависит от того, как устроен пришедший XMP. Разбирать чужой XML,
// чтобы дописать в него поле, значило бы завести в проект разборщик XML.
std::string xmpWithFileName(std::string_view existing, std::string_view fileName);

}  // namespace zametti

#endif  // ZAMETTI_EXIF_H
