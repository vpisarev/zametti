// Приведение цветового пространства к каноническому.
//
// ЗАЧЕМ ЭТО ВООБЩЕ ПОНАДОБИЛОСЬ. Замер на выборке из 219 снимков показал, что
// 12% файлов получают SSIMULACRA2 около −40, причём ОДИНАКОВО на всех восьми
// уровнях качества. Ровное дно поперёк всей кривой — это не сжатие, это цвет:
// сжатие всегда чем-то отзывается на уровень качества.
//
// Виноватыми оказались снимки iPhone с профилем «Apple Wide Color Sharing
// Profile» — треть каталога владельца. Разбирательство дало такую картину:
//
//   * libjxl хранит исходный ICC рядом, но пиксели lossy-кода (XYB) отдаёт в
//     СВОЁМ пространстве, сообщая его как TARGET_DATA. Для канонических
//     профилей это ровно исходное пространство, и круг сходится байт в байт
//     (проверено на Display P3 от vivo и на 16-битном TIFF от DxO: средние
//     совпадают, оценки 83–86);
//   * для профиля, который описанием НЕ выражается, libjxl откатывается на
//     линейный sRGB. Пометить такие пиксели исходным профилем нельзя — они уже
//     не в нём; пометить линейным sRGB значит отдать наружу совсем другие
//     цвета. Отсюда и −40;
//   * djxl ведёт себя так же (см. lib/extras/dec/jxl.cc): по умолчанию берёт
//     TARGET_DATA и трогает выход, только если попросили --color_space. То
//     есть это не наша ошибка в вызовах, а свойство формата.
//
// ЧИНИМ НА ВХОДЕ, А НЕ НА ВЫХОДЕ. Раз круг сходится ровно для тех профилей,
// которые libjxl умеет описать, — приводим картинку к такому пространству ДО
// записи. Тогда в хранилище не остаётся ничего, что нельзя прочесть обратно.
//
// ПОЧЕМУ ПЕРЕВОДИМ НЕ СРЕДСТВАМИ Qt. Qt профиль Apple разбирает и даже что-то
// переводит, но неверно: средние 53/50/42 он превращает в 37/35/28, тогда как
// littleCMS — в 47/44/36. Ошибка втрое больше самого перевода. Поэтому
// движком служит тот, что уже вшит в libjxl (skcms — тот же, что в Chrome);
// заодно и вопрос «каноничен ли профиль» задаётся ровно тому, чей ответ
// потом и важен.
//
// ЦЕЛЬ ПЕРЕВОДА — Display P3. Не sRGB: почти всё неканоническое, что реально
// встречается, шире sRGB (профили Apple — это P3 с самодельной кривой), и
// сводить их в sRGB значит терять охват уже на входе. Не ProPhoto: он шире
// нужного, а лишняя ширина при восьми битах стоит полос на градиентах.

#pragma once

#include <QByteArray>
#include <QImage>

namespace zametti {

// Умеет ли libjxl выразить профиль первичными, кривой и белой точкой. Только
// такие пространства переживают круг записи и чтения.
bool iccIsCanonical(const QByteArray& icc);

// ICC канонического Display P3 — цель перевода.
QByteArray displayP3Icc();

// Перевод пикселей между профилями. false — движок не собрал преобразование;
// картинка тогда остаётся нетронутой.
bool convertIcc(QImage& image, const QByteArray& from, const QByteArray& to);

// Главная точка: если профиль картинки описанием не выражается, переводит её в
// Display P3 и заменяет icc на новый. Возвращает true, если перевод случился.
//
// icc — профиль, вынутый из контейнера; пустой означает «брать из самой
// картинки». После перевода в нём лежит профиль Display P3.
bool canonicalizeColor(QImage& image, QByteArray& icc);

}  // namespace zametti
